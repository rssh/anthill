/// Pick a unique C++ identifier for a type parameter. Keeps the source
/// name when it's safe; otherwise appends `0..N` until a free slot is
/// found. `taken` is updated with the chosen name.
fn canonicalise_param_name(
    source_name: &str,
    taken: &mut std::collections::HashSet<String>,
) -> String {
    let base = cpp_identifier(source_name.trim_start_matches('?'));
    let needs_suffix = CPP_KEYWORDS.contains(&base.as_str()) || taken.contains(&base);
    let chosen = if needs_suffix {
        let mut n = 0;
        loop {
            let candidate = format!("{base}{n}");
            if !taken.contains(&candidate) && !CPP_KEYWORDS.contains(&candidate.as_str()) {
                break candidate;
            }
            n += 1;
        }
    } else {
        base
    };
    taken.insert(chosen.clone());
    chosen
}

/// Build the C++ template-parameter declarations for `params`, the type
/// parameters owned by `owner_sym` (a sort or — for a per-operation generic —
/// an operation symbol). Returns the decl fragments (`typename A` for a
/// first-order param, `template<typename...> class F` for a higher-kinded
/// carrier) and the source-name → cpp-name mapping to push onto the
/// type-param stack. `taken` accumulates the chosen C++ identifiers; seed it
/// with the enclosing sort's param names when building an operation's
/// member-template prefix so a per-op `T` can't collide with the class `T`.
fn template_param_decls(
    kb: &KnowledgeBase,
    owner_sym: Symbol,
    params: &[String],
    taken: &mut std::collections::HashSet<String>,
) -> Result<
    (
        Vec<String>,
        std::collections::HashMap<String, TypeParamBinding>,
    ),
    CppCodegenError,
> {
    refuse_cpp_identifier_collisions(
        &format!("type parameters of '{}'", kb.qualified_name_of(owner_sym)),
        params.iter().map(|p| p.trim_start_matches('?')),
    )?;
    let mut mapping = std::collections::HashMap::new();
    let mut decls = Vec::with_capacity(params.len());
    for p in params {
        let cpp = canonicalise_param_name(p, taken);
        // WI-575 (f): a higher-kinded carrier — a param whose own body declares
        // type params (`sort Spec[F[T]]`, or `operation op[G[T]](…)`) — becomes
        // a C++ template-template parameter `template<typename...> class F`, so
        // a use `F[T = A]` can lower to `F<A>`. A first-order param stays the
        // plain `typename F`. The kind rides into the binding (WI-891) so the
        // unlowerable-body static_assert never keys `dependent_false_v<…>` on a
        // template-template name, which is not a type.
        let higher_kinded = is_higher_kinded_param(kb, owner_sym, p);
        let decl = if higher_kinded {
            format!("template<typename...> class {cpp}")
        } else {
            format!("typename {cpp}")
        };
        mapping.insert(p.clone(), TypeParamBinding { cpp, higher_kinded });
        decls.push(decl);
    }
    Ok((decls, mapping))
}

/// Build the `(template prefix, name → binding)` pair for a sort.
/// Empty prefix and empty map when the sort has no type parameters.
fn template_prefix_for_sort(
    kb: &KnowledgeBase,
    sort_sym: Symbol,
) -> Result<(String, std::collections::HashMap<String, TypeParamBinding>), CppCodegenError> {
    let params = type_params_of(kb, sort_sym);
    if params.is_empty() {
        return Ok((String::new(), std::collections::HashMap::new()));
    }
    let mut taken = std::collections::HashSet::new();
    let (decls, mapping) = template_param_decls(kb, sort_sym, &params, &mut taken)?;
    let prefix = format!("template<{}>\n", decls.join(", "));
    Ok((prefix, mapping))
}

/// Build an operation's `    template<…>\n` member-template prefix from its
/// per-op type-param `(cpp_name, decl)` pairs, KEEPING only the params that
/// actually appear in the lowered signature (the param C++ types, the return
/// type, and the synthesised body). A param that lowers to nothing — most
/// commonly an effect-only `EffP`, since C++ erases the effect row — is
/// dropped rather than emitted as a dead `typename EffP`. Declaration order is
/// preserved; an empty result (no params, or all erased) yields no prefix.
///
/// Usage is decided on whole identifier tokens of the emitted C++, so a name
/// can never be erased while it is genuinely referenced (no substring
/// false-negative); a coincidental token match only ever *keeps* a param,
/// which is harmless.
fn member_template_prefix(
    decls: &[(String, String)],
    params: &[ParamInfo],
    return_type: &str,
    body: &Option<String>,
) -> String {
    if decls.is_empty() {
        return String::new();
    }
    let mut used = std::collections::HashSet::new();
    for p in params {
        collect_cpp_identifiers(&p.cpp_type, &mut used);
    }
    collect_cpp_identifiers(return_type, &mut used);
    if let Some(b) = body {
        collect_cpp_identifiers(b, &mut used);
    }
    let kept: Vec<&str> = decls
        .iter()
        .filter(|(cpp, _)| used.contains(cpp.as_str()))
        .map(|(_, decl)| decl.as_str())
        .collect();
    if kept.is_empty() {
        String::new()
    } else {
        format!("    template<{}>\n", kept.join(", "))
    }
}

/// Collect the maximal C++ identifier tokens (`[A-Za-z0-9_]+` runs) of `s`
/// into `out`. Used by `member_template_prefix` to decide which template
/// params actually appear in an emitted signature.
fn collect_cpp_identifiers(s: &str, out: &mut std::collections::HashSet<String>) {
    let mut cur = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            cur.push(c);
        } else if !cur.is_empty() {
            out.insert(std::mem::take(&mut cur));
        }
    }
    if !cur.is_empty() {
        out.insert(cur);
    }
}

/// WI-575 (f): is `param` a higher-kinded type parameter of `sort_sym`? A
/// marked carrier `F` of `sort Spec[F[T]]` loads as a nested sort
/// `<Spec>.F` whose own body declares type params (`T`), so the test is
/// "the nested sort named `param` has at least one type parameter of its
/// own". Form-agnostic: the marked/unmarked-carrier distinction is a loader
/// concern (it decides whether `F` gets a backing var), but by the time
/// codegen runs the kind shows up the same way — as nested type params.
fn is_higher_kinded_param(kb: &KnowledgeBase, sort_sym: Symbol, param: &str) -> bool {
    let nested = format!("{}.{}", kb.qualified_name_of(sort_sym), param);
    kb.try_resolve_symbol(&nested)
        .is_some_and(|sym| !kb.type_params_of_sort(sym).is_empty())
}

/// Classify a declared effect term into a short, codegen-relevant
/// kind. `Error[T = …]`, `sort_ref(Error)`, and bare `Error` all
/// return `"Error"`; `Modify[T = …]` returns `"Modify"`. Unknown
/// effects map to their short name. Returns `None` for terms that
/// don't look like an effect reference at all.
fn effect_kind_short(kb: &KnowledgeBase, term: TermId) -> Option<String> {
    let short_of = |sym: Symbol| short_name_of(kb.qualified_name_of(sym)).to_string();
    // Unwrap `sort_ref(...)` and `parameterized(base: ..., bindings: ...)`
    // envelopes via the existing helpers — pre-typing forms like
    // `Error[T = X]` or `Modify(self)` fall through to the bare
    // functor short name.
    if let Some(sym) = extract_sort_ref_sym(kb, &TermIdView(term)) {
        return Some(short_of(sym));
    }
    if let Some((base, _)) = unpack_parameterized(kb, term) {
        return Some(short_of(base));
    }
    // Bare functor/ref short name — shared with `EffectMapping.receiver` reads.
    functor_or_ref_short(kb, term)
}

/// WI-576: what one declared effect label denotes to the capability gate.
enum EffectLabel {
    /// A concrete effect kind (`Error`; `Modify[self]` → `"Modify"`), checkable
    /// against the target profile's supported-effect set.
    Kind(String),
    /// An effect ROW PARAMETER — the `EffP` of
    /// `flatMap[A, B, EffP](…) effects {EffP}`. An effect-polymorphic operation
    /// states no concrete requirement at its DECLARATION: the row is whatever a
    /// call site instantiates, so the capability check belongs at that
    /// instantiation. Not a silent skip — this is a recognised category, and it
    /// is recognised narrowly (the label must BE one of this op's own declared
    /// type params), so a free var from anywhere else still falls through to
    /// `Unreadable`.
    RowParam,
    /// Neither of the above: the gate cannot decide realizability, and says so.
    Unreadable,
}

/// Carrier-agnostic [`effect_kind_short`]: classify a declared effect label as
/// `OperationInfo` stores it (`OpInfoRecord.effects`, WI-348). A ground label
/// (`Error`) rides as `Value::Term`; a `denoted`-bearing one (`Modify[self]`)
/// cannot hash-cons and rides as a `Value::Node` whose `TypeNode::Parameterized`
/// base holds the effect sort — the ONLY part the gate needs, since a profile
/// realizes an effect KIND, not a particular carrier binding.
///
/// Every other carrier — a `Value::Entity` label, a `Node` that is not a
/// parameterized type — is `Unreadable` ON PURPOSE rather than given a best
/// guess: the gate then reports the carrier it actually saw instead of passing
/// an effect it never checked. No producer mints those shapes today; if one
/// appears, the error names it.
fn classify_effect_label(
    kb: &KnowledgeBase,
    eff: &Value,
    type_params: &[(Symbol, Var)],
) -> EffectLabel {
    use anthill_core::kb::node_occurrence::{NodeKind, TypeChild, TypeNode};
    let kind_of = |t: TermId| match effect_kind_short(kb, t) {
        Some(name) => EffectLabel::Kind(name),
        // `OpInfoRecord.type_params` carries each param's own `Var` (WI-849), and
        // the effect row carries the SAME variable as a hash-consed `Term::Var` —
        // so `EffP` in the row and `EffP` in the type-param list are one variable.
        // The test is therefore by VARIABLE IDENTITY (a `VarId` compare, WI-632),
        // not a name-string match; before WI-849 the same judgement was spelled as
        // a `TermId` compare, which held only because vars hash-cons.
        None if matches!(kb.get_term(t), Term::Var(v) if type_params.iter().any(|(_, p)| p == v)) => {
            EffectLabel::RowParam
        }
        None => EffectLabel::Unreadable,
    };
    match eff {
        Value::Term { id, .. } => kind_of(*id),
        Value::Node(occ) => match &occ.kind {
            NodeKind::Type(TypeNode::Parameterized {
                base: TypeChild::Ground(t),
                ..
            }) => kind_of(*t),
            _ => EffectLabel::Unreadable,
        },
        _ => EffectLabel::Unreadable,
    }
}

/// Short name of a term that is a bare constructor reference: `Ref`/`Ident` for
/// a nullary entity, `Fn` for a payload-bearing one. The common tail of
/// `effect_kind_short` (after its sort_ref/parameterized unwrap) and the reader
/// for an `EffectMapping.receiver` (a `ReceiverForm` constructor). `None` for
/// terms that aren't a constructor reference at all.
fn functor_or_ref_short(kb: &KnowledgeBase, term: TermId) -> Option<String> {
    match kb.get_term(term) {
        Term::Ref(s) | Term::Ident(s) => Some(short_name_of(kb.qualified_name_of(*s)).to_string()),
        Term::Fn { functor, .. } => Some(short_name_of(kb.qualified_name_of(*functor)).to_string()),
        _ => None,
    }
}

/// WI-886 — lower a bare symbol reference, the shared body of `lower_node`'s
/// `Ref`/`Ident` and `VarRef` arms.
///
/// `consult_value_bindings` is the ONE difference between them: a `VarRef` may name a
/// let-local or a match binding, which shadows a same-named const. It sits where it
/// does in the ladder because the earlier rungs are all keyed on a QUALIFIED name that
/// a binder cannot have.
fn lower_symbol_ref(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sym: Symbol,
    consult_value_bindings: bool,
) -> Result<String, CppCodegenError> {
    let qn = kb.qualified_name_of(sym);
    // Stdlib wrapper constants used as values (`none` on its own line) — lower the
    // qualified name through the same table that handles `none()` / `some(...)`.
    if let Some(rendered) = lower_stdlib_constant(qn) {
        return Ok(rendered);
    }
    // WI-886: a bare nullary operation (`pi`, `tau`, `Int64.minValue`) — its cpp
    // binding's template, which for a constant is the literal.
    if let Some(rendered) = render_host_mapped_bare(kb, ctx, sym)? {
        return Ok(rendered);
    }
    // WI-889: a bare reference to a host-supplied `const` (the Float IEEE specials) —
    // its `const_map` C++ expression. The const-level peer of the arm above; formerly
    // the hand-written `render_as_float_special` table.
    if let Some(rendered) = ctx.host_consts.lookup(sym) {
        return Ok(rendered.to_string());
    }
    let short = short_name_of(qn);
    if consult_value_bindings {
        if let Some(access) = ctx.lookup_value_binding(short) {
            return Ok(access);
        }
    }
    // WI-536: a reference to a term-level const resolves to its named constant (struct
    // member or namespace companion), not the bare short name (which would not be in
    // scope at the C++ use site).
    if kb.kind_of(sym) == Some(SymbolKind::Const) {
        return Ok(const_ref_cpp(kb, ctx, sym));
    }
    if let Some(err) = unlowerable_operation(kb, ctx, sym) {
        return Err(err);
    }
    Ok(cpp_identifier(short))
}

/// WI-886 — lower a BARE reference to a mapped operation: `pi`, `tau`,
/// `Int64.minValue` written without parentheses, which reach `lower_node` as a
/// `Ref`/`VarRef` rather than an `Apply`. A nullary operation's template has no
/// placeholders, so this is the template verbatim.
///
/// `Ok(None)` when the symbol names no cpp-mapped operation — every ordinary
/// parameter, local binding and const reference takes that path. A mapped operation
/// that TAKES arguments is refused instead: the binding says how to spell the
/// operation APPLIED, which is not a C++ function value, and emitting the short name
/// would be the silent broken call this ticket removes.
fn render_host_mapped_bare(
    kb: &KnowledgeBase,
    ctx: &CodegenContext,
    sym: Symbol,
) -> Result<Option<String>, CppCodegenError> {
    let Some(tmpl) = ctx.host_ops.lookup(sym) else {
        return Ok(None);
    };
    let qn = kb.qualified_name_of(sym);
    if tmpl.arity > 0 {
        return Err(CppCodegenError {
            message: format!(
                "`{qn}` is referenced as a value, but its C++ realization is the \
                 expression template {:?} — a template stands for the operation APPLIED \
                 to its {} argument(s) and cannot be passed as a function value",
                tmpl.source, tmpl.arity
            ),
        });
    }
    render_host_template(tmpl, qn, &[]).map(Some)
}

/// WI-886 — the refusal that replaced cpp-gen's silent fall-through. An `Apply` /
/// bare reference that no earlier arm lowered used to become `{short_name}(...)`:
/// for a user's own bodied operation that is the emitted C++ function and correct,
/// but for a BODY-LESS one it is a call to a function that does not exist, emitted
/// into a header with nothing reported at the anthill layer. MEASURED before the fix
/// on a program that codegen'd "successfully": `isNaN(a)`, `compare(a, b)`,
/// `max(a, b)`, `minValue()`, `gt(a, b)`.
///
/// BODY-LESS AND UNMAPPED is the line, and the first half is the same one the
/// load-time backing check draws (`op_backed`, WI-876): an operation with a body has
/// an anthill definition cpp-gen can in principle emit, while one without gets its
/// meaning from the host — so if no `provides <carrier> language cpp` block named a
/// realization, there is nothing to lower and saying so is the only honest move.
/// Returns `None` (fall through) for everything that is not an operation at all: a
/// lambda binder, a local, an entity.
///
/// BOTH halves are asked HERE, though every caller has already tried `ctx.host_ops`
/// and would fall through on a hit anyway: a predicate whose answer depends on where
/// it is called from silently refuses a mapped operation the day someone adds a fourth
/// call site or reorders an arm.
///
/// "Has a body" reads `kb.op_body_node`, NOT `ctx.op_impls` — the two differ, and this
/// is the wider one. `OpImplTable` additionally requires an `anthill.realization.
/// OperationImpl` fact, which the loader emits only when the realization vocabulary is
/// loaded, so `op_impls ⊆ op_body_node`. The message says "has no body", and that must
/// be true of every operation it names.
///
/// NOT CLOSED BY THIS: an operation with a DEFAULT body declared on a spec cpp-gen is
/// not emitting still falls through to a bare call. That is a wider question — which
/// definitions a run emits — and the ticket's line is the silent HOST gap.
fn unlowerable_operation(
    kb: &KnowledgeBase,
    ctx: &CodegenContext,
    op: Symbol,
) -> Option<CppCodegenError> {
    if kb.kind_of(op) != Some(SymbolKind::Operation)
        || ctx.host_ops.lookup(op).is_some()
        || kb.op_body_node(op).is_some()
    {
        return None;
    }
    let qn = kb.qualified_name_of(op).to_string();
    let carrier = parent_qualified_name(kb, op).unwrap_or_else(|| "<unknown>".to_string());
    // "No cpp mappings at all" is a different fault from "this one is missing", and
    // by far the likelier one to hit a new project: the `provides … language cpp`
    // blocks live in `rustland/anthill-cpp-gen/anthill/` and a KB built without them
    // has no cpp realizations for ANY primitive.
    let hint = if ctx.host_ops.is_empty() {
        " No cpp `operation_map` entries were loaded at all — if this is a primitive \
          carrier, the C++ binding files (rustland/anthill-cpp-gen/anthill/) are \
          missing from the load."
    } else {
        ""
    };
    // WI-891: a broken host binding is a FAULT, not a capability gap, so it stays a
    // bare `CppCodegenError` — fatal by default. `synthesise_body_for` never sees the
    // `capability_gap` flag set for it, so it aborts codegen (the whole header) rather
    // than degrading, exactly as WI-886 intended: the broken call this replaced at
    // least failed the C++ build.
    Some(CppCodegenError {
        message: format!(
            "`{qn}` has no body and no C++ realization, so cpp-gen cannot lower a call \
             to it. Name the host expression in an `operation_map` clause of a \
             `provides {carrier} language cpp` block.{hint}"
        ),
    })
}

// WI-889 — `render_as_float_special` DELETED. The Float IEEE specials
// (`infinity`/`negativeInfinity`/`nan`) were the last of WI-886's four hand-written
// per-carrier cpp tables; they now reach cpp-gen as DATA through the `const_map`
// clause of `provides Float language cpp` → `HostConstTable` (this file) → the two
// `ctx.host_consts.lookup(sym)` call sites, symmetric with `operation_map` /
// `HostOpTable` for `pi`/`e`/`tau`. See the WI-889 note in `HostConstTable`.

/// Match a fully-qualified or short prelude name against a (suffix,
/// payload) table. `suffix` is the qn after `anthill.prelude.`.
/// Accepts both `anthill.prelude.<suffix>` (qualified) and `<suffix>`
/// (short — produced when imports leave a name partly-qualified).
fn lookup_prelude_qn<'a, T: Copy>(fn_qn: &str, table: &'a [(&'a str, T)]) -> Option<T> {
    let stripped = fn_qn.strip_prefix("anthill.prelude.").unwrap_or(fn_qn);
    table
        .iter()
        .find(|(suffix, _)| *suffix == stripped)
        .map(|(_, v)| *v)
}

/// Lower `IndexedSeq.nth(xs, i)` and `IndexedSeq.length(xs)` to
/// container-agnostic C++ — works for any host type with `size()`
/// and `operator[]` (`std::vector`, `std::array`, hand-rolled, …).
/// `nth` checks bounds and wraps in `std::optional`.
fn render_as_indexed_seq(fn_qn: &str, args: &[String]) -> Option<String> {
    let stripped = fn_qn.strip_prefix("anthill.prelude.").unwrap_or(fn_qn);
    match stripped {
        "IndexedSeq.length" if args.len() == 1 => {
            Some(format!("static_cast<int64_t>({}.size())", args[0]))
        }
        "IndexedSeq.nth" if args.len() == 2 => {
            let xs = &args[0];
            let i = &args[1];
            Some(format!(
                "(({i} >= 0 && static_cast<size_t>({i}) < {xs}.size()) \
                 ? std::make_optional({xs}[{i}]) : std::nullopt)"
            ))
        }
        _ => None,
    }
}

/// Render a known prelude typeclass call as a C++ operator expression.
/// Returns `None` for non-typeclass functions, which the caller then
/// emits as a plain function call.
///
/// Why string-keyed: typeclass facts (`fact Numeric{T = Int64}`) make the
/// dispatch decision a typeclass-membership check, but for primitives
/// the answer is always "yes" — and our scrutinees today are almost
/// always primitives. The user's own sorts can overload the C++
/// operator if they want to participate, or they keep using the named
/// function form (which would round-trip through this table since the
/// QN wouldn't match — but the QN of a user's own `add` differs).
///
/// WI-886 — SPEC OPS ONLY now, and that is a boundary rather than a gap list. The
/// EIGHT per-CARRIER entries that used to sit here moved to their carriers'
/// `operation_map`, where the rest of that surface already lives: `Int64.div`,
/// `Int64.mod`, `Int64.neg`, `Float.div`, `Float.neg` — and `Bool.and`/`or`/`not`,
/// which are `Bool`'s OWN declared operations and were the counterexample to this
/// table's first claim to hold only spec ops. Keeping half a carrier's operations in a
/// Rust table and half in its binding was the divergence this ticket exists to end.
///
/// What is left is the SPEC-OP LOWERING, and since WI-880 that is a genuine fallback
/// rather than the only reading. `Int64` and `Float` now declare `add`/`sub`/`mul` of
/// their own and map them in their cpp binding blocks, which is what this note
/// predicted ("when WI-880 moves the spec-op families per carrier, these follow"), and
/// a carrier that maps its own WINS because `lower_node` asks `host_ops` first. The
/// entries below still serve a carrier that maps NOTHING — a user sort whose values are
/// a C++ arithmetic type — which is the case one lowering of `Additive.add` genuinely
/// covers for every such carrier at once.
///
/// `Int64.mod` did not merely move, its lowering was CORRECTED: C++ `%` follows the
/// DIVIDEND's sign while anthill's `mod` is documented always non-negative, so the old
/// entry was a silent wrong answer for a negative left operand. `%` realizes `rem`.
fn render_as_operator(fn_qn: &str, args: &[String]) -> Option<String> {
    // (qualified_name, arity, infix_or_prefix_op)
    let infix: &[(&str, &str)] = &[
        // WI-20260825-1WBZT — the SYNTAX CATEGORY that declares each (`Additive`,
        // `Multiplicative`), not the `Numeric` bundle that used to. Keyed by qualified
        // name, so the key follows the declaration.
        ("anthill.prelude.Additive.add", "+"),
        ("anthill.prelude.Additive.sub", "-"),
        ("anthill.prelude.Multiplicative.mul", "*"),
        // WI-644 / proposal 004: the partial comparison ops live on PartialEq /
        // PartialOrd. Mapping them to C++ `==`/`>`/… (IEEE) is now CORRECT — these
        // are the partial specs, so the compiler and the interpreter's IEEE-for-Float
        // builtins agree (the WI-645 acceptance). The total Eq/Ord/TotalFloat
        // would emit a total comparator instead (a `= default` operator== / <=> on the
        // generated struct) — a follow-up, tracked with the entity operator== gap.
        ("anthill.prelude.PartialOrd.gt", ">"),
        ("anthill.prelude.PartialOrd.lt", "<"),
        ("anthill.prelude.PartialOrd.gte", ">="),
        ("anthill.prelude.PartialOrd.lte", "<="),
        ("anthill.prelude.PartialEq.eq", "=="),
        ("anthill.prelude.PartialEq.neq", "!="),
    ];
    for (qn, op) in infix {
        if fn_qn == *qn && args.len() == 2 {
            return Some(format!("({} {} {})", args[0], op, args[1]));
        }
    }
    None
}

/// Lower stdlib wrapper-constants used as bare values (e.g. `none`
/// on its own, without parens). Returns `Some(s)` when matched.
fn lower_stdlib_constant(fn_qn: &str) -> Option<String> {
    let table: &[(&str, &str)] = &[("Option.none", "std::nullopt")];
    // Also handle the bare-import case (`none`) which strip_prefix can't reach.
    if fn_qn == "none" {
        return Some("std::nullopt".to_string());
    }
    lookup_prelude_qn(fn_qn, table).map(str::to_string)
}

/// Lower stdlib wrapper-constructor calls (Option, Result, …) from
/// NodeOccurrence arg slices. Returns `Ok(Some(s))` when matched,
/// `Ok(None)` when the functor is not one we recognise. Today:
/// `Option.{some, none}`.
fn lower_stdlib_wrapper_node(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    fn_qn: &str,
    pos_args: &[std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>],
    named_args: &[(
        Symbol,
        std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>,
    )],
) -> Result<Option<String>, CppCodegenError> {
    if let Some(c) = lower_stdlib_constant(fn_qn) {
        return Ok(Some(c));
    }
    let stripped = fn_qn.strip_prefix("anthill.prelude.").unwrap_or(fn_qn);
    if stripped == "Option.some" || fn_qn == "some" {
        let mut parts = Vec::new();
        for a in combined_args(pos_args, named_args) {
            parts.push(lower_node(kb, ctx, a)?);
        }
        if parts.len() != 1 {
            return Err(CppCodegenError {
                message: format!("Option.some expects 1 arg, got {}", parts.len()),
            });
        }
        return Ok(Some(format!("std::make_optional({})", parts[0])));
    }
    Ok(None)
}

/// Lower an entity-constructor application from NodeOccurrence args
/// to brace-initialiser syntax: `EntityName{val0, val1, ...}`. Args
/// may be positional or named; either way values are emitted in the
/// entity's field declaration order so the resulting C++ matches the
/// struct layout emitted by `emit_entity_struct_by_symbol`.
fn lower_constructor_literal_node(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    entity_sym: Symbol,
    pos_args: &[std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>],
    named_args: &[(
        Symbol,
        std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>,
    )],
) -> Result<String, CppCodegenError> {
    use std::collections::HashMap;
    let qn = kb.qualified_name_of(entity_sym).to_string();
    let short = short_name_of(&qn);
    let short_name = qualify_cross_namespace(ctx, &qn, short);
    // WI-760: own the field list — lowering each argument threads `&mut` on
    // the KB, so a borrowed slice can't stay live across the loops below.
    let fields = kb
        .entity_field_types(entity_sym)
        .ok_or_else(|| CppCodegenError {
            message: format!("'{qn}' has no registered fields"),
        })?
        .to_vec();

    let mut named_values: HashMap<String, String> = HashMap::new();
    let mut positional: Vec<String> = Vec::new();
    for arg in pos_args.iter() {
        positional.push(lower_node(kb, ctx, arg)?);
    }
    for (name_sym, arg) in named_args.iter() {
        let n = kb.local_name_of(*name_sym).to_string();
        named_values.insert(n, lower_node(kb, ctx, arg)?);
    }

    let mut vals = Vec::with_capacity(fields.len());
    for (i, (field_sym, _)) in fields.iter().enumerate() {
        let field_name = kb.local_name_of(*field_sym).to_string();
        if let Some(v) = named_values.remove(&field_name) {
            vals.push(v);
        } else if let Some(v) = positional.get(i) {
            vals.push(v.clone());
        } else {
            return Err(CppCodegenError {
                message: format!(
                    "constructor literal '{short_name}': no value for field '{field_name}'"
                ),
            });
        }
    }
    Ok(format!("{short_name}{{{}}}", vals.join(", ")))
}

/// Lower a sequence of `MatchBranch` terms over a scrutinee expression
/// to a chain of `<tag-check> ? <body> : <next>` ternaries. The
/// final branch becomes the catch-all — exhaustiveness is the
/// source's responsibility (the type checker rejects non-exhaustive
/// matches before codegen).
///
/// Branches with binding patterns (e.g. `case some(?w) -> body`)
/// emit the body inside an IIFE that introduces the bound names.
/// `Option.some` / `Option.none` are special-cased to use
/// `o.has_value()` / `o.value()` instead of the variant primitives,
/// since Option lowers to `std::optional<T>` rather than a variant.
fn lower_match_branches_node(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    scrutinee: &str,
    branches: &[anthill_core::kb::node_occurrence::MatchBranch],
) -> Result<String, CppCodegenError> {
    struct Compiled {
        tag_check: Option<String>, // None = catch-all (wildcard)
        body: String,
    }
    let mut compiled: Vec<Compiled> = Vec::with_capacity(branches.len());
    for branch in branches {
        // WI-318: branch.pattern is a Pattern-kind occurrence.
        let info = analyse_pattern_occ(kb, &branch.pattern, scrutinee)?;
        // Bindings frame: `?w` in the body refers to the local
        // `auto w` introduced by the IIFE, not to the access
        // expression — the latter could re-trigger side effects.
        refuse_cpp_identifier_collisions(
            "one match pattern",
            info.decls.iter().map(|decl| decl.source_name.as_str()),
        )?;
        let mut frame: std::collections::HashMap<String, String> = std::collections::HashMap::new();
        for decl in &info.decls {
            frame.insert(decl.source_name.clone(), decl.cpp_name.clone());
        }
        let _guard = ctx.push_value_bindings(frame);
        let body_s = lower_node(kb, ctx, &branch.body)?;
        let body_with_bindings = if info.decls.is_empty() {
            body_s
        } else {
            let mut decls = String::new();
            for decl in &info.decls {
                decls.push_str(&format!("auto {} = {}; ", decl.cpp_name, decl.access));
            }
            format!("[&]() {{ {decls}return {body_s}; }}()")
        };
        compiled.push(Compiled {
            tag_check: info.tag_check,
            body: body_with_bindings,
        });
    }
    // Right-to-left fold so the first branch appears outermost.
    let last = compiled.pop().expect("caller ensured at least one branch");
    let mut out = last.body;
    while let Some(c) = compiled.pop() {
        let tag = c.tag_check.ok_or_else(|| CppCodegenError {
            message: "match: a non-final branch had a wildcard pattern \
                      (catch-all only allowed last)"
                .into(),
        })?;
        out = format!("({tag} ? {body} : {out})", body = c.body);
    }
    Ok(out)
}

/// Result of analysing one `MatchBranch`'s pattern: the tag-check
/// expression (None for wildcard catch-alls), and the value bindings
/// the pattern introduces. `decls` is what the IIFE should emit as
/// local declarations (e.g. `("w", "o.value()")` becomes
/// `auto w = o.value();`); the body's binding map then resolves
/// references to the *local* names, not the access expressions, so
/// the local is used instead of re-evaluating the access.
struct PatternInfo {
    tag_check: Option<String>,
    decls: Vec<PatternBinding>,
}

struct PatternBinding {
    source_name: String,
    cpp_name: String,
    access: String,
}

/// Compile a pattern against `scrutinee` into a tag check + binding map.
/// Recognised forms:
/// - `Pattern.var_pattern{name}` — a BINDER, so a catch-all (no tag check) that
///   declares `auto <name> = s;`. WI-20260827-EJ5F5: it used to read as a nullary
///   constructor, which is what the typer's rewrite now settles before codegen sees
///   the body — a bare name that names one arrives as `constructor_pattern`.
/// - `Pattern.constructor_pattern{name, args}` — N-ary constructor with
///   sub-patterns, and the NULLARY spelling too. For Option's `none` (qn
///   `anthill.prelude.Option.none`) uses `!s.has_value()`, otherwise
///   `std::holds_alternative<X>(s)`. For `Option.some(?w)` uses `s.has_value()` and
///   binds `w → s.value()`. For other entities, binds each sub-`var_pattern`
///   to `std::get<Ctor>(s).<field_name>` in declaration order.
/// - `Pattern.wildcard` — no tag check (None), no bindings.
/// WI-318: Pattern-occurrence variant of `analyse_pattern`.
/// Dispatches on the structural `Pattern` enum instead of round-
/// tripping through a TermId.
fn analyse_pattern_occ(
    kb: &KnowledgeBase,
    occ: &std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>,
    scrutinee: &str,
) -> Result<PatternInfo, CppCodegenError> {
    use anthill_core::kb::node_occurrence::Pattern;
    let Some(pat) = occ.as_pattern() else {
        return Err(CppCodegenError {
            message: "expected Pattern-kind occurrence in match branch (WI-318)".into(),
        });
    };
    match pat {
        Pattern::Wildcard => Ok(PatternInfo {
            tag_check: None,
            decls: Vec::new(),
        }),
        Pattern::Var { .. } => {
            // WI-20260827-EJ5F5: a `Pattern::Var` reaching a MATCH ARM is a BINDER, and
            // a binder arm is a CATCH-ALL that binds the scrutinee — exactly how
            // `eval::pattern` reads it.
            //
            // This arm used to emit a nullary tag check instead, which was cpp-gen
            // getting the ticket's defect WRONG IN THE OTHER DIRECTION: the interpreter
            // read every bare `case` name as a binder, this read every one as a
            // constructor, and the two agreed on nothing. A bare name that DOES name one
            // of the scrutinee's own nullary constructors is now rewritten to
            // `Pattern::Constructor` by the typer before the body is stored
            // (kernel-language.md, "Constructor patterns resolve against the scrutinee"),
            // so it reaches the arm below and this one sees only genuine binders — for
            // which `std::holds_alternative<other>(s)` names a C++ type that does not
            // exist. MEASURED: with this arm made a `panic!`, the whole cpp-gen suite
            // (197 tests) stays green, so no fixture reached it once the rewrite landed.
            //
            // `tag_check: None` also puts a binder arm under the SAME "catch-all only
            // allowed last" refusal a `case _` gets, which is the honest reading — a
            // binder arm before another arm makes that arm dead.
            //
            // THE PRECONDITION, said plainly because it is now load-bearing and there is
            // nothing here that could check it: this arm is correct because the body it
            // reads WAS TYPE-CHECKED. On a body the typer never rewrote — a KB built
            // through `load_kb_with_lenient`, whose discarded `Err` WI-966 made a named
            // exception — a bare `case red` would still be a `Var` and would be compiled
            // as a catch-all that kills every later arm. cpp-gen cannot tell the two
            // apart (the binder symbol is fresh either way, so no predicate separates
            // them), so this is a contract on the caller, not a check: emit only from a
            // KB that finished loading.
            let bind_name = pattern_var_name_occ(kb, occ)?;
            Ok(PatternInfo {
                tag_check: None,
                decls: vec![PatternBinding {
                    cpp_name: cpp_identifier(&bind_name),
                    source_name: bind_name,
                    access: scrutinee.to_string(),
                }],
            })
        }
        Pattern::Constructor { name, pos_args, .. } => {
            let ctor_sym = *name;
            let ctor_qn = kb.qualified_name_of(ctor_sym).to_string();
            let short = short_name_of(&ctor_qn);
            // Option.some(?w) special case mirrors the term-based path.
            if ctor_qn == "anthill.prelude.Option.some" || ctor_qn == "Option.some" {
                if pos_args.len() != 1 {
                    return Err(CppCodegenError {
                        message: format!(
                            "Option.some pattern expects 1 sub-pattern, got {}",
                            pos_args.len()
                        ),
                    });
                }
                let bind_name = match_subpattern_name(kb, &ctor_qn, &pos_args[0])?;
                return Ok(PatternInfo {
                    tag_check: Some(format!("{scrutinee}.has_value()")),
                    decls: vec![PatternBinding {
                        cpp_name: cpp_identifier(&bind_name),
                        source_name: bind_name,
                        access: format!("{scrutinee}.value()"),
                    }],
                });
            }
            if ctor_qn == "anthill.prelude.Option.none" || ctor_qn == "Option.none" {
                return Ok(PatternInfo {
                    tag_check: Some(format!("!{scrutinee}.has_value()")),
                    decls: Vec::new(),
                });
            }
            // Generic entity constructor: variant tag + per-sub-pattern
            // bind into `std::get<Ctor>(s).<field>`. Mirrors the pre-WI-318
            // term-based path's error reporting — fail loudly on unknown
            // entity and arity mismatch rather than emit invalid C++.
            let cpp_short = cpp_identifier(short);
            let tag = format!("std::holds_alternative<{cpp_short}>({scrutinee})");
            let fields = kb
                .entity_field_types(ctor_sym)
                .ok_or_else(|| CppCodegenError {
                    message: format!("constructor pattern '{ctor_qn}' is not a known entity"),
                })?;
            if pos_args.len() != fields.len() {
                return Err(CppCodegenError {
                    message: format!(
                        "constructor pattern '{ctor_qn}' expects {} sub-patterns, got {}",
                        fields.len(),
                        pos_args.len()
                    ),
                });
            }
            let mut decls: Vec<PatternBinding> = Vec::new();
            for (sub_pat, (field_sym, _)) in pos_args.iter().zip(fields.iter()) {
                if matches!(sub_pat.as_pattern(), Some(Pattern::Wildcard)) {
                    continue;
                }
                let bind_name = match_subpattern_name(kb, &ctor_qn, sub_pat)?;
                let field_name = cpp_identifier(kb.local_name_of(*field_sym));
                decls.push(PatternBinding {
                    cpp_name: cpp_identifier(&bind_name),
                    source_name: bind_name,
                    access: format!("std::get<{cpp_short}>({scrutinee}).{field_name}"),
                });
            }
            Ok(PatternInfo {
                tag_check: Some(tag),
                decls,
            })
        }
        Pattern::Tuple { .. } | Pattern::Literal { .. } => Err(CppCodegenError {
            message: format!("match pattern not yet supported in cpp-gen: {pat:?}"),
        }),
    }
}

/// WI-20260827-EJ5F5 — the bound name of a MATCH sub-pattern, or a refusal that names the
/// match rather than a let/lambda.
///
/// cpp-gen lowers a constructor pattern's sub-patterns as plain bindings
/// (`auto w = std::get<Ctor>(s).field;`), which has no spelling for a sub-pattern that is
/// itself refutable — a nested constructor (`case some(red)`, `case cons(nil(), t)`) needs
/// a nested tag check inside the arm's own, and cpp-gen has no form for one.
///
/// It is a REFUSAL and not a silent binding, and the wording is its own because
/// `pattern_var_name_occ`'s says "let/lambda binder", which sends the author to the wrong
/// line. The population reaching it GREW with this ticket, which is why it is separated
/// now: the parenthesized `case some(red())` always came here, and the bare
/// `case some(red)` used to arrive as a `Var` and be lowered as a binding that ignored the
/// constructor entirely — the same silent wrong answer this ticket removes in the
/// interpreter.
fn match_subpattern_name(
    kb: &KnowledgeBase,
    ctor_qn: &str,
    sub_pat: &std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>,
) -> Result<String, CppCodegenError> {
    use anthill_core::kb::node_occurrence::Pattern;
    match sub_pat.as_pattern() {
        Some(Pattern::Var { .. }) => pattern_var_name_occ(kb, sub_pat),
        Some(other) => Err(CppCodegenError {
            message: format!(
                "match pattern not yet supported in cpp-gen: a sub-pattern of \
                 '{ctor_qn}' is {other:?}, and only a plain binder or `_` can be lowered \
                 there (a nested pattern needs a nested tag check)"
            ),
        }),
        None => Err(CppCodegenError {
            message: format!(
                "expected Pattern-kind occurrence in a sub-pattern of '{ctor_qn}' (WI-318)"
            ),
        }),
    }
}

/// Extract the bound name from a `Pattern.var_pattern(name: Ref(<n>), ...)`.
/// Used by let / lambda lowering. Constructor / tuple / wildcard /
/// literal pattern shapes are handled by `pattern_constructor_name`
/// in the match path instead. WI-318: pre-lift sibling of
/// `pattern_var_name_occ`, kept for the term-form code paths still in
/// use (constructor analysis fallbacks); the let/lambda lowering uses
/// the `_occ` variant.
#[allow(dead_code)] // WI-318: pre-lift sibling, kept for future fallback paths.
fn pattern_var_name(kb: &KnowledgeBase, pat: TermId) -> Result<String, CppCodegenError> {
    if let Term::Fn {
        functor,
        named_args,
        ..
    } = kb.get_term(pat)
    {
        let qn = kb.qualified_name_of(*functor);
        if qn == "anthill.reflect.Pattern.var_pattern" {
            if let Some(name_term) = find_named(kb, named_args, "name") {
                if let Term::Ref(s) | Term::Ident(s) = kb.get_term(name_term) {
                    let qn = kb.qualified_name_of(*s);
                    return Ok(short_name_of(qn).to_string());
                }
            }
        }
        return Err(CppCodegenError {
            message: format!("let/lambda binder: only var_pattern supported, got {qn}"),
        });
    }
    Err(CppCodegenError {
        message: format!("expected var_pattern, got {:?}", kb.get_term(pat)),
    })
}

/// WI-318: Pattern-occurrence variant of `pattern_var_name`. Reads the
/// bound name directly from `Pattern::Var`; other Pattern variants are
/// not yet supported in let/lambda binder position by cpp-gen.
///
/// WI-20260827-EJ5F5 added a third caller, `analyse_pattern_occ`'s MATCH-ARM binder
/// arm, which has already destructured `Pattern::Var` — so the two refusals below are
/// unreachable from it, and the "let/lambda binder" wording still names every site that
/// can reach them.
fn pattern_var_name_occ(
    kb: &KnowledgeBase,
    occ: &std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>,
) -> Result<String, CppCodegenError> {
    use anthill_core::kb::node_occurrence::Pattern;
    match occ.as_pattern() {
        Some(Pattern::Var { name, .. }) => {
            let qn = kb.qualified_name_of(*name);
            Ok(short_name_of(qn).to_string())
        }
        Some(other) => Err(CppCodegenError {
            message: format!("let/lambda binder: only Var pattern supported, got {other:?}"),
        }),
        None => Err(CppCodegenError {
            message: "let/lambda binder: expected Pattern-kind occurrence".into(),
        }),
    }
}

/// Escape the CONTENTS of a C++ narrow string literal (no surrounding quotes):
/// the `\"` / `\\` / `\n` / `\r` / `\t` set the printer uses. Shared by
/// `lower_literal` and the WI-891 `static_assert` degrade payload, whose message
/// is arbitrary error text that may carry a quote or newline.
fn escape_cpp_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

/// Lower a `Literal` to its C++ source spelling. String literals get
/// the same `\"` / `\\` / `\n` / `\r` / `\t` escaping the printer uses.
fn lower_literal(lit: &Literal) -> String {
    match lit {
        Literal::Int(n) => n.to_string(),
        Literal::Float(f) => {
            let s = f.to_string();
            if s.contains('.') {
                s
            } else {
                format!("{s}.0")
            }
        }
        Literal::Bool(b) => if *b { "true" } else { "false" }.to_string(),
        Literal::String(s) => format!("\"{}\"", escape_cpp_str(s)),
        // BigInt has no native C++17 stdlib mapping — caller would
        // need a custom carrier. Emitted as a comment so the failure
        // is loud.
        other => format!("/* unsupported literal: {other:?} */"),
    }
}

fn lower_type(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    type_term: TermId,
) -> Result<String, CppCodegenError> {
    if let Some(sym) = extract_sort_ref_sym(kb, &TermIdView(type_term)) {
        return sort_to_cpp(kb, ctx, sym);
    }

    let term = kb.get_term(type_term);
    match term {
        Term::Ref(sym) | Term::Ident(sym) => sort_to_cpp(kb, ctx, *sym),
        // Logic variable in a type position — references to a sort's
        // declared type parameter (`?T`) lower to the C++ template
        // parameter name. The Var's `name` symbol matches the
        // `add_type_param` entry in the sort body's scope.
        Term::Var(v) => {
            let name_sym = match v {
                anthill_core::kb::term::Var::Global(vid) => vid.name(),
                anthill_core::kb::term::Var::DeBruijn(_) => {
                    return Err(CppCodegenError {
                        message: "DeBruijn var in type position — should have been opened".into(),
                    })
                }
                anthill_core::kb::term::Var::Rigid(_) => {
                    return Err(CppCodegenError {
                        message: "Rigid var in type position — only valid during proof".into(),
                    })
                }
            };
            let name = kb.local_name_of(name_sym).to_string();
            if let Some(cpp) = ctx.lookup_type_param(&name) {
                return Ok(cpp);
            }
            Err(CppCodegenError {
                message: format!(
                    "type variable '?{name}' is not bound by any enclosing \
                     sort's type parameters — declare `sort {name} = ?` in \
                     the sort body, or pass an explicit binding"
                ),
            })
        }
        Term::Fn { functor, .. } => {
            // WI-575 (proposal 002): structural TYPE functors that are not
            // parameterized sorts — lower them to their C++ shapes rather than
            // erroring. Read through the typed, carrier-agnostic `extract_type`
            // (the same accessor `unpack_parameterized` uses) so both the deep
            // and term-backed carriers decode uniformly. An arrow type →
            // `std::function<R(Args...)>` (its effect row is erased — a
            // spec-side concern with no C++ type witness, per proposal 002
            // §"Effect Subtyping"); a `named_tuple` → `std::tuple<…>`.
            match extract_type(kb, &TermIdView(type_term)) {
                TypeExtractor::Arrow {
                    param,
                    result,
                    arity,
                    ..
                } => {
                    return lower_arrow_type(kb, ctx, &param, &result, arity);
                }
                TypeExtractor::NamedTuple(fields) => {
                    ctx.requested_includes
                        .borrow_mut()
                        .insert("#include <tuple>".to_string());
                    let elems = lower_tuple_elem_types(kb, ctx, &fields)?;
                    return Ok(format!("std::tuple<{}>", elems.join(", ")));
                }
                _ => {}
            }
            // Parameterized type — the deep `parameterized(base: sort_ref(S),
            // bindings)` OR the term-backed `Fn{S, named}` form (WI-361).
            // `unpack_parameterized` reads both; a non-parameterized Fn (e.g.
            // an unrecognised structural type) falls through to error.
            if unpack_parameterized(kb, type_term).is_some() {
                return lower_parameterized(kb, ctx, type_term);
            }
            let qualified = kb.qualified_name_of(*functor);
            Err(CppCodegenError {
                message: format!(
                    "unexpected non-parameterized Fn term as type: '{qualified}' \
                     (expected a sort ref, a parameterized type, or a term-backed Fn{{S, named}})"
                ),
            })
        }
        other => Err(CppCodegenError {
            message: format!("cannot lower term to C++ type: {other:?}"),
        }),
    }
}

/// WI-575 (proposal 002): lower an `arrow(param, result, effects)` Type to a
/// C++ `std::function<R(Args...)>`. The `param` child is a single type (one
/// Arg) or a `named_tuple` (its element types become the Args, in declaration
/// order — so `() -> R` yields zero args). `result` is `R`. The `effects`
/// child is intentionally dropped: an arrow's effect row has no C++ type
/// witness (the host realizes effects in the value, not the type).
fn lower_arrow_type(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    param: &Value,
    result: &Value,
    arity: usize,
) -> Result<String, CppCodegenError> {
    let r = lower_type_value(kb, ctx, result)?;

    // A multi-param / nullary arrow carries its params as a `named_tuple`; a
    // unary arrow carries the single param type directly. Decode through the
    // same typed extractor so both forms (and both carriers) read uniformly.
    // A `named_tuple` param is taken to BE the parameter list (this is the
    // WI-575 contract: "the param named_tuple becomes Args...").
    //
    // WI-791: WHICH form this is is now read off the arrow's `arity` child
    // rather than guessed. The loader used to build `(a: A, b: B) -> R` and the
    // single tuple-typed parameter `((A, B)) -> R` into the identical
    // `named_tuple([A, B])` param, so the multi-arg reading won and silently
    // flattened the latter into a two-argument `std::function` the anthill side
    // calls with one `std::tuple`. Arity one now lowers as ONE argument.
    let args: Vec<String> = if arity == 1 {
        vec![lower_type_value(kb, ctx, param)?]
    } else {
        match param {
            Value::Term { id: t, .. } => match extract_type(kb, &TermIdView(*t)) {
                TypeExtractor::NamedTuple(fields) => lower_tuple_elem_types(kb, ctx, &fields)?,
                _ => vec![lower_type(kb, ctx, *t)?],
            },
            _ => vec![lower_type_value(kb, ctx, param)?],
        }
    };

    ctx.requested_includes
        .borrow_mut()
        .insert("#include <functional>".to_string());
    Ok(format!("std::function<{r}({})>", args.join(", ")))
}

/// Lower a type carried as a [`Value`]. A ground type rides as `Value::Term`;
/// a denoted-bearing (`Value::Node`) type — a callback arrow whose effect
/// carries a value like `Modify[c]` — has no C++ type witness and is a loud
/// error here, matching how op param / return lowering rejects the same shape.
fn lower_type_value(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    v: &Value,
) -> Result<String, CppCodegenError> {
    match v {
        Value::Term { id: t, .. } => lower_type(kb, ctx, *t),
        _ => Err(CppCodegenError {
            message: "denoted-bearing type carrier is unsupported by C++ codegen".into(),
        }),
    }
}

/// Lower the element field-types of a `named_tuple` to C++, in declaration
/// order. The element names are dropped — C++ `std::tuple` slots and function
/// parameters are positional. Shared by the standalone-tuple arm of
/// `lower_type` and the multi-param arrow's parameter list.
fn lower_tuple_elem_types(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    fields: &[(Symbol, Value)],
) -> Result<Vec<String>, CppCodegenError> {
    fields
        .iter()
        .map(|(_, v)| lower_type_value(kb, ctx, v))
        .collect()
}

/// Lower a `parameterized(base: sort_ref(...), bindings: [...])` term
/// to its C++ template form. Base resolves via carrier or the keyed
/// `TypeMapping` query (`cpp_base_host_type`);
/// each binding's `value` is recursively lowered into the angle-bracket
/// arg list, in TypeBinding declaration order.
fn lower_parameterized(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    type_term: TermId,
) -> Result<String, CppCodegenError> {
    let (base_sym, binding_pairs) =
        unpack_parameterized(kb, type_term).ok_or_else(|| CppCodegenError {
            message: "expected a parameterized(base: ..., bindings: [...]) term".into(),
        })?;

    let qualified = kb.qualified_name_of(base_sym).to_string();
    let short = short_name_of(&qualified);
    // WI-575 (f): a parameterized type whose base is a higher-kinded type
    // parameter (`F[T = A]`, where `F` is the carrier of `sort Spec[F[T]]`)
    // lowers to the template-template parameter applied — `F<A>`. Checked
    // first (mirroring `sort_to_cpp`) so an enclosing `?F` shadows any stray
    // carrier / `TypeMapping` that happens to share the short name. The base
    // must be GENUINELY higher-kinded (its own body declares type params) —
    // applying a first-order param (`T[X = Int]`, a kind error) would emit
    // `T<Int>` against a `typename T` declaration; gating on the param's
    // arity leaves that ill-kinded case to fall through to the loud
    // "no C++ mapping" error below rather than silently emitting invalid C++.
    let base_is_hk_param = !kb.type_params_of_sort(base_sym).is_empty();
    // WI-760: the `TypeMapping` arm can no longer ride an `or_else` closure —
    // it takes `&mut` on the KB, which the closure would capture uniquely while
    // the earlier arms still borrow it. Matching preserves both the fallback
    // ORDER and its laziness: the mapping is queried only if neither earlier
    // arm hit.
    let template_name = match ctx
        .lookup_type_param(short)
        .filter(|_| base_is_hk_param)
        .or_else(|| ctx.carriers.lookup(&qualified).map(str::to_string))
    {
        Some(name) => name,
        None => resolve_type_mapping(kb, ctx, &[short], None)?
            .map(|h| h.host_type)
            .ok_or_else(|| CppCodegenError {
                message: format!(
                    "no C++ mapping for parameterized sort '{qualified}' — add a \
                     CarrierBinding, or a `fact TypeMapping(lang: some(\"cpp\"), \
                     anthill_type: \"{short}\", host_type: ...)`"
                ),
            })?,
    };

    // C++ template args follow the sort's DECLARATION order (`template<K, V>`),
    // but `binding_pairs` are stored in canonical symbol-interning order (WI-361
    // flip). Reorder by `type_params_of_sort` (source/declaration order); fall back
    // to stored order if the sort exposes no declared params (defensive).
    let decl_order = kb.type_params_of_sort(base_sym);
    let ordered: Vec<TermId> = if decl_order.is_empty() {
        binding_pairs.iter().map(|(_, v)| *v).collect()
    } else {
        let mut out: Vec<TermId> = decl_order
            .iter()
            .filter_map(|pname| {
                binding_pairs
                    .iter()
                    .find(|(p, _)| kb.local_name_of(*p) == pname.as_str())
                    .map(|(_, v)| *v)
            })
            .collect();
        // Defensive: append any binding whose param wasn't in the declared set
        // (over-application — not produced by well-formed types) so nothing is lost.
        for (p, v) in &binding_pairs {
            if !decl_order
                .iter()
                .any(|n| kb.local_name_of(*p) == n.as_str())
            {
                out.push(*v);
            }
        }
        out
    };

    let mut args = Vec::with_capacity(ordered.len());
    for value in ordered {
        args.push(lower_type(kb, ctx, value)?);
    }

    if args.is_empty() {
        // Parameterized form with no bindings — degenerate, but emit
        // the bare template name so we don't error.
        Ok(template_name)
    } else {
        Ok(format!("{template_name}<{}>", args.join(", ")))
    }
}

/// Map a sort symbol to its C++ type spelling. Lookup order:
///   1. `CarrierTable` (from `Implementation` / `CarrierBinding` facts)
///   2. Keyed `TypeMapping` query (`cpp_base_host_type`, WI-089) — the
///      fact-driven base renames in `anthill.realization.cpp_std`
///   3. Project-local entity → its short name (the struct we emit
///      ourselves lives in the same C++ namespace)
///   4. Error
///
/// Carrier bindings take precedence — a user-supplied
/// `CarrierBinding(sort_name: "Int", host_type: "int32_t")` overrides
/// the default `Int → int64_t` mapping. The keyed `TypeMapping` base is
/// the fallback, not a constraint, and is itself project-extensible
/// (assert another `fact TypeMapping(lang: some("cpp"), ...)`).
fn sort_to_cpp(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sym: Symbol,
) -> Result<String, CppCodegenError> {
    let qualified = kb.qualified_name_of(sym).to_string();
    let short = short_name_of(&qualified);
    // Type parameter of any enclosing sort (set via push_type_params
    // by emit_traits / emit_entity). Checked before carriers and
    // primitives so a `?T` reference inside `Box[T = ?]` lowers to
    // the template name `T` even if a stray carrier or primitive
    // happens to share the short name.
    if let Some(cpp) = ctx.lookup_type_param(short) {
        return Ok(cpp);
    }
    if let Some(host) = ctx.carriers.lookup(&qualified) {
        // Register the header that declares this carrier's host type
        // so the surrounding namespace header gains a matching
        // `#include` (e.g. `webots::GPS *` → `#include <webots/GPS.hpp>`).
        if let Some(artifact) = ctx.carriers.artifact(&qualified) {
            ctx.requested_includes
                .borrow_mut()
                .insert(format!("#include <{artifact}>"));
        }
        return Ok(host.to_string());
    }
    // WI-089(a): declared-signature position — no binding key is active, so
    // `[profile?, none]` selects a profile overlay or the language base (never
    // a binding's marshalling overlay). `cpp_base_host_type` (base-only) is the
    // profile-agnostic special case of this.
    if let Some(hit) = resolve_type_mapping(kb, ctx, &[short], None)? {
        return Ok(hit.host_type);
    }
    // Runtime use of `anthill.reflect.*` (TermRepr, SortInfo, KB, …)
    // and `anthill.persistence.*` (Store, FileStore, IndexedFileStore, …) is
    // refused: cpp17-stl has no term-store / hash-cons infrastructure
    // on the host side, so these can't be lowered to value-typed C++.
    // A future `cpp-meta` profile (or an explicit CarrierBinding) can
    // opt in by mapping the sort to a host type.
    if let Some(profile) = unsupported_runtime_profile(&qualified) {
        return Err(CppCodegenError {
            message: format!(
                "profile cpp17-stl does not support runtime {profile} (sort '{qualified}') — \
                 these require term-store infrastructure not provided in C++; \
                 either add an explicit CarrierBinding mapping the sort to a host type, \
                 or omit the operation from the C++ surface"
            ),
        });
    }
    // Project-local entity. Refer by short name when the entity
    // lives in the same C++ namespace block we're currently
    // emitting; otherwise use the fully-qualified path so the
    // generated header compiles regardless of where the consumer
    // sits (e.g. `anthill.geometry.Vec3` referenced from inside an
    // `anthill.examples.lf1` entity must render as
    // `::anthill::geometry::Vec3`).
    if kb.entity_field_types(sym).is_some() {
        register_cross_namespace_include(ctx, &qualified);
        return Ok(qualify_cross_namespace(ctx, &qualified, short));
    }
    if !constructors_of(kb, sym).is_empty() {
        register_cross_namespace_include(ctx, &qualified);
        return Ok(qualify_cross_namespace(ctx, &qualified, short));
    }
    Err(CppCodegenError {
        message: format!(
            "no C++ mapping for sort '{qualified}' — add a CarrierBinding \
             via an Implementation fact, or model it as an entity with fields"
        ),
    })
}

/// Classify a fully-qualified sort name as belonging to a stdlib
/// subsystem the cpp17-stl profile cannot lower at runtime. Returns
/// the human-readable subsystem label, or `None` if the sort is fine.
fn unsupported_runtime_profile(qualified: &str) -> Option<&'static str> {
    if qualified.starts_with("anthill.reflect.") {
        Some("reflection")
    } else if qualified.starts_with("anthill.persistence.") {
        Some("persistence")
    } else {
        None
    }
}

/// A keyed type-mapping entry resolved from the KB (WI-089). `key = none`
/// is the language base (the default rename); `some(k)` is a profile or
/// foreign-binding overlay queried ahead of the base.
///
/// `PartialEq`/`Eq` (WI-833): two hits are equal iff every CONSUMED field
/// agrees, so `select_keyed_unique` can collapse the same mapping resolved via
/// several derivations (a duplicate) yet still reject two hits that differ at
/// one key (a genuine conflict).
#[derive(Clone, PartialEq, Eq)]
struct TypeMappingHit {
    host_type: String,
    /// foreign->anthill adapter (marshalled overlay only; `None` on a plain
    /// rename). Read back so marshalling rides the SAME query as the renames.
    lift: Option<String>,
    /// anthill->foreign adapter (marshalled overlay only; `None` on a plain
    /// rename).
    lower: Option<String>,
    key: Option<String>,
}

/// WI-833: the single-valued aggregation every realization reader applies to its
/// RESOLVED candidates — DEDUPLICATE identical items, then map the count to a
/// verdict: 0 → `None` (absent), 1 → `Some` (the pick), >1 distinct → a loud
/// `CppCodegenError` built by `ambiguous`. Resolution enumerates one mapping once
/// per derivation (a fact reachable two ways, two guards that both hold), so an
/// identical item twice is one mapping (deduped), while two DISTINCT items are
/// genuinely competing (no deterministic pick — the caller names them in the
/// error). Equality is `T`'s own `PartialEq`. Shared by [`select_keyed_unique`]
/// (per key) and [`cpp_method_name`] (the whole convention set); the lists are a
/// handful of entries, so the O(n²) `contains` dedup is not worth a `HashSet`.
fn unique_or_ambiguous<T: Clone + PartialEq>(
    items: impl IntoIterator<Item = T>,
    ambiguous: impl FnOnce(&[T]) -> CppCodegenError,
) -> Result<Option<T>, CppCodegenError> {
    let mut distinct: Vec<T> = Vec::new();
    for it in items {
        if !distinct.contains(&it) {
            distinct.push(it);
        }
    }
    match distinct.len() {
        0 => Ok(None),
        1 => Ok(distinct.into_iter().next()),
        _ => Err(ambiguous(&distinct)),
    }
}

/// WI-089(a) / WI-833 / WI-847: keyed overlay selection over an ordered
/// active-key list, most-specific-first — the priority logic that stays
/// CALLER-SIDE (in Rust), not in the resolver, so migrating the read to
/// `Resolve` (WI-833) only changes where the candidate rows come from, not how a
/// key shadows another. `spellings` are the candidate `anthill_type` spellings of
/// ONE sort, each paired with its OWN resolved hits, in priority order (a
/// qualified name before its short name). For each key in `active_keys`, in
/// order, each spelling's hits carrying that key are aggregated by
/// [`unique_or_ambiguous`]:
///   * 0 distinct  → this spelling is absent at this key; try the NEXT spelling,
///     and once every spelling is absent, fall through to the next key (a
///     binding / profile overlay shadows the base only where present, and the
///     base sentinel `None` is always last, so a base-only type still resolves);
///   * 1 distinct  → that is the selection;
///   * >1 distinct → AMBIGUOUS: two COMPETING mappings of the SAME spelling share
///     one key, so no deterministic pick exists — a loud `CppCodegenError` naming
///     the spelling, the key, and the competing host types, never the silent
///     first-wins the WI-089 `select_keyed` did. The `Refuse` read this replaced
///     could not surface a same-key conflict (it never evaluated a guard, so two
///     competing overlays were a load-time fact collision); under `Resolve` two
///     guarded overlays can both fire here, so the ambiguity is detected here.
///
/// The KEY ladder DOMINATES the spelling order: a higher-priority key is resolved
/// across EVERY spelling before a lower key is consulted, so a binding / profile
/// overlay written under EITHER spelling still shadows a base written under the
/// other — WI-847 must not let a qualified-name BASE preempt a short-name binding
/// OVERLAY (binding > base). WITHIN a key, the earliest spelling that carries a
/// hit wins: that is the qualified-over-short OVERRIDE — a cross-spelling pair at
/// one key resolves to the qualified one, while only a SAME-spelling pair at one
/// key is the ambiguity above (WI-833). This per-spelling-within-key walk is what
/// the WI-833 MERGE (which fused both spellings into one list, reading a
/// cross-spelling override as that same-key ambiguity — WI-847) replaced.
fn select_keyed_unique(
    spellings: &[(&str, Vec<TypeMappingHit>)],
    active_keys: &[Option<String>],
) -> Result<Option<TypeMappingHit>, CppCodegenError> {
    for ak in active_keys {
        for (what, hits) in spellings {
            let at_key = hits.iter().filter(|h| &h.key == ak).cloned();
            let selected = unique_or_ambiguous(at_key, |distinct| {
                let hosts: Vec<&str> = distinct.iter().map(|h| h.host_type.as_str()).collect();
                CppCodegenError {
                    message: format!(
                        "ambiguous cpp TypeMapping for {what} at key {ak:?}: competing host \
                         types {hosts:?} — a resolved overlay must select a single mapping \
                         per key (check for duplicate facts, or guarded rules whose guards \
                         overlap)"
                    ),
                }
            })?;
            if selected.is_some() {
                return Ok(selected);
            }
        }
    }
    Ok(None)
}

/// The shared front of the realization readers: resolve `functor_names`
/// (qualified first, then bare short name) to the first loaded symbol and encode
/// the `field = value` `selection` as ground `Value::Str` equalities pushed down
/// as the read's `bound` (057 §"query contract"). Only PLAIN-string fields are
/// selectable this way (an `Option`-typed `lang: some("cpp")` cannot be grounded
/// structurally — callers post-filter it instead). `None` is the shared
/// BAIL-EMPTY: no `functor_names` entry is loaded, or a selection field name
/// isn't interned (so no fact carries it and nothing could match).
///
/// WI-833: the sole consumer is now [`resolve_realization_rows`] (`Resolve`); the
/// `Refuse` twin (`read_realization_facts`) retired when the three type-lowering
/// readers graduated to `read_facts_resolved`. The direct `read_facts(Refuse)`
/// sibling readers (`CarrierTable` / `OpImplTable` / `generated_targets`) build
/// their own empty selection inline and do not route through here.
fn realization_functor_and_selection(
    kb: &KnowledgeBase,
    functor_names: &[&str],
    selection: &[(&str, &str)],
) -> Option<(Symbol, Vec<(Symbol, Value)>)> {
    let functor = functor_names
        .iter()
        .find_map(|n| kb.try_resolve_symbol(n))?;
    let mut sel: Vec<(Symbol, Value)> = Vec::with_capacity(selection.len());
    for (field, value) in selection {
        let fsym = kb.lookup_symbol(field)?;
        sel.push((fsym, Value::Str(value.to_string())));
    }
    Some((functor, sel))
}

/// WI-089: resolve host-type mappings for `anthill_type` under `lang` over the
/// keyed `TypeMapping` facts (the discrim tree IS the table). `lang`/`key` are
/// `Option` fields read back from each matched row — grounding `some("cpp")`
/// structurally would be awkward — so only `anthill_type` is grounded and
/// `lang` is post-filtered. Returns every matching entry across keys; callers
/// pick by key priority.
///
/// WI-089(a): both plain renames and adapter-bearing marshalling overlays flow
/// through THIS one query (the retired `MarshalTable` was a second reader).
/// Only facts with `lang: some("cpp")` are selected; the active-key priority
/// then picks among the matches by `key`. A `TypeMapping` for another language,
/// or one with no `lang`, is simply not a cpp mapping and is not selected.
///
/// WI-833: RESOLVED, not `Refuse`. A bodied `TypeMapping` rule is now EVALUATED
/// (its guard honored) via [`resolve_realization_rows`] / `read_facts_resolved`,
/// so a project can gate an overlay on a condition — the WI-089 guarded-overlay
/// direction the old `read_facts(Refuse)` reader had to reject loudly. The
/// key-priority aggregation stays caller-side ([`select_keyed_unique`]); this
/// query only gathers the candidate rows, whose per-key ambiguity that selector
/// then resolves or rejects.
fn query_type_mappings(
    kb: &mut KnowledgeBase,
    lang: &str,
    anthill_type: &str,
) -> Result<Vec<TypeMappingHit>, CppCodegenError> {
    let mut hits = Vec::new();
    for row in resolve_realization_rows(
        kb,
        &["anthill.realization.TypeMapping", "TypeMapping"],
        &[("anthill_type", anthill_type)],
    )? {
        let fact_lang = row_named_optional_string(kb, &row, "lang")?;
        if fact_lang.as_deref() != Some(lang) {
            continue;
        }
        let Some(host_type) = row_named_string(kb, &row, "host_type")? else {
            continue;
        };
        let lift = row_named_optional_string(kb, &row, "lift")?;
        let lower = row_named_optional_string(kb, &row, "lower")?;
        let key = row_named_optional_string(kb, &row, "key")?;
        hits.push(TypeMappingHit {
            host_type,
            lift,
            lower,
            key,
        });
    }
    Ok(hits)
}

/// WI-089(a): resolve the single best `TypeMapping` entry for an anthill type
/// under the active-key priority. `names` are the candidate `anthill_type`
/// spellings for ONE sort — a qualified name first, then its short name — each
/// queried into its OWN hit list and handed, IN THAT ORDER, to
/// [`select_keyed_unique`]. So a fact written either way resolves; a
/// qualified-name overlay OVERRIDES a short-name one at the same key (the
/// qualified-over-short priority this doc has always promised — WI-847); and the
/// key ladder (binding > profile > base) still DOMINATES that spelling order, so
/// a binding overlay written under EITHER spelling shadows a base written under
/// the other. `binding` is the foreign-binding key in scope (`Some` at a
/// carrier-dispatch boundary, `None` in declared-signature position). Returns the
/// highest-priority overlay present — the one query that backs BOTH
/// declared-signature host-type lowering (reads `host_type`) and value-level
/// marshalling (reads `lift` / `lower`).
fn resolve_type_mapping(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    names: &[&str],
    binding: Option<&str>,
) -> Result<Option<TypeMappingHit>, CppCodegenError> {
    let active_keys = ctx.active_keys(binding);
    let mut spellings: Vec<(&str, Vec<TypeMappingHit>)> = Vec::with_capacity(names.len());
    for &name in names {
        // Skip a repeated spelling (a sort whose qualified name equals its short
        // name — builtins like `Float`) so we don't issue the same discrim query
        // twice; the first occurrence already carries that spelling's hits.
        if spellings.iter().any(|(n, _)| *n == name) {
            continue;
        }
        spellings.push((name, query_type_mappings(kb, "cpp", name)?));
    }
    select_keyed_unique(&spellings, &active_keys)
}

/// WI-089: the C++ language-base host type for `anthill_type` (the
/// `key = none` entry), via the keyed `TypeMapping` query. Replaces the
/// hardcoded `prim_lower` / `param_lower` tables: primitives lower to a
/// leaf type (`Int64 -> int64_t`); parameterized stdlib sorts lower to a
/// bare template name (`List -> std::vector`) the caller wraps with args.
pub fn cpp_base_host_type(
    kb: &mut KnowledgeBase,
    anthill_type: &str,
) -> Result<Option<String>, CppCodegenError> {
    // The language base is the `key = none` entry — i.e. selection over the
    // single-element active-key list `[none]`, with the single spelling
    // `anthill_type`. Routed through the shared `select_keyed_unique` so there is
    // one implementation of "pick the entry for this key", not a divergent
    // `.find(key.is_none())` spelling — and so a duplicate/competing base entry
    // (WI-833) is deduped or rejected here too.
    let hits = query_type_mappings(kb, "cpp", anthill_type)?;
    Ok(select_keyed_unique(&[(anthill_type, hits)], &[None])?.map(|h| h.host_type))
}

/// WI-089(a): resolve the cpp host type for `anthill_type` under the active-key
/// priority — binding overlay > profile overlay > language base. `profile` is
/// the compilation profile (e.g. "cpp20-stl"); `binding` is the foreign-binding
/// key in scope at a carrier-dispatch boundary (`None` in declared-signature
/// position). This is exactly the selection declared-signature lowering and the
/// marshalling boundary perform internally, surfaced so callers (and tests) can
/// ask "what does X map to under profile P at binding B?". `cpp_base_host_type`
/// is the `profile = None, binding = None` special case.
pub fn cpp_host_type(
    kb: &mut KnowledgeBase,
    anthill_type: &str,
    profile: Option<&str>,
    binding: Option<&str>,
) -> Result<Option<String>, CppCodegenError> {
    let ctx = CodegenContext::with_profile(kb, profile.map(str::to_string))?;
    Ok(resolve_type_mapping(kb, &ctx, &[anthill_type], binding)?.map(|h| h.host_type))
}

/// WI-576: THE uniform effect-realization accessor — the host `ReceiverForm`
/// short name realizing `effect` for `lang` under `profile`, or `None` when
/// nothing realizes it (the effect is outside that profile's supported set).
/// The effect-side sibling of `cpp_host_type`.
///
/// WI-760: this is READ BY RESOLUTION. The selection logic is not here — it is
/// the `anthill.realization.realizes_effect` rule set, resolved by SLD. Both
/// representations (cpp's FLAT keyed `EffectMapping` facts; rust/scala's NESTED
/// `LanguageMapping.effect_map` entries) and the `[profile?, none]` priority
/// live in those rule bodies, so callers never see which form a language uses
/// and no `select_keyed` merge happens caller-side. This is what WI-089's
/// addendum specified and what the old head-match path could not do: the
/// priority arms are mutually exclusive via a negation guard, which a
/// `query_view` head match would have skipped silently.
///
/// CONTRACT — `profile` is REQUIRED for a nested-representation language. Only
/// the flat form has a language BASE (`key: none`); every `LanguageMapping`
/// fact in the stdlib declares a profile (`std` / `caps` / `anthill`) and NONE
/// declares `profile: none`, so `realizes_effect(kb, "rust", None, "Modify")`
/// resolves nothing even though rust plainly realizes `Modify`. That is
/// deliberate — inventing a "sole mapping for this language wins" fallback
/// would guess at the caller's profile, and the repo prefers a knowable miss to
/// a fallback. cpp is unaffected: its facts carry `key: none` and cpp-gen
/// always threads `ctx.profile`. Pinned by
/// `realizes_effect_without_a_profile_resolves_no_nested_entry`.
///
/// Effects are profile-scoped, not binding-scoped: no foreign-binding key
/// participates (unlike `resolve_type_mapping`, where a boundary overlay can
/// shadow the profile).
pub fn realizes_effect(
    kb: &mut KnowledgeBase,
    lang: &str,
    profile: Option<&str>,
    effect: &str,
) -> Option<String> {
    let Some(functor) = kb.try_resolve_symbol("anthill.realization.realizes_effect") else {
        // No rule symbol — two very different situations, and conflating them
        // is exactly the silent-wrong-answer this accessor exists to prevent:
        //   * No realization stdlib at all. `None` is honest, and the capability
        //     gate turns it into an accurate "nothing realizes this effect"
        //     error naming the effect — the same diagnostic as before WI-760.
        //   * `EffectMapping` IS loaded but the rules are not (half-loaded or
        //     renamed stdlib). Answering `None` would mark every effect
        //     unrealizable while blaming the FACTS, so fail loudly instead.
        assert!(
            kb.try_resolve_symbol("anthill.realization.EffectMapping")
                .is_none(),
            "anthill.realization.EffectMapping is loaded but the `realizes_effect` \
             rule set is not — effect realization cannot be decided"
        );
        return None;
    };
    let receiver_sym = kb.intern("receiver");
    let vid = kb.fresh_var(receiver_sym);
    let profile_val = option_value(kb, profile);
    let goal = Value::Entity {
        functor,
        pos: std::rc::Rc::from(vec![
            Value::Str(lang.to_string()),
            profile_val,
            Value::Str(effect.to_string()),
            Value::Var(Var::Global(vid)),
        ]),
        named: std::rc::Rc::from(Vec::new()),
    };

    let solutions = kb.resolve(&[goal], &ResolveConfig::default());
    // A floundered solution binds nothing and proves nothing — drop it rather
    // than read an unbound receiver out of it.
    let mut receivers: Vec<String> = solutions
        .iter()
        .filter(|s| s.residual.is_empty())
        .filter_map(|s| s.subst.resolve_as_value(vid))
        .filter_map(|v| receiver_short_name(kb, &v))
        .collect();
    // Sort BEFORE dedup: `dedup` only drops ADJACENT repeats, and solution
    // order is not deterministic (the discrimination tree is HashMap-backed),
    // so the same receiver derived twice could arrive non-adjacent and trip the
    // uniqueness check below.
    receivers.sort();
    receivers.dedup();

    // The rule set is written so the priority arms are mutually exclusive; two
    // DISTINCT receivers means a malformed overlay (or a rule regression), not
    // a choice to make silently. A `debug_assert` would compile out and let a
    // release build pick one arbitrarily — emitting C++ with the wrong receiver
    // form — so this is loud in every build (repo rule: error over silent skip).
    assert!(
        receivers.len() <= 1,
        "realizes_effect({lang}, {profile:?}, {effect}) resolved to multiple \
         distinct receivers {receivers:?} — the overlay arms must be mutually \
         exclusive; a profile-keyed entry should have suppressed the base"
    );
    receivers.into_iter().next()
}

/// `some(x)` / `none()` as a goal value. `Option.some` carries its payload in a
/// NAMED `value` field, so a positional build would not unify with the facts.
fn option_value(kb: &mut KnowledgeBase, v: Option<&str>) -> Value {
    let (qn, named) = match v {
        Some(s) => {
            let value_sym = kb.intern("value");
            (
                "anthill.prelude.Option.some",
                vec![(value_sym, Value::Str(s.to_string()))],
            )
        }
        None => ("anthill.prelude.Option.none", Vec::new()),
    };
    let functor = kb
        .try_resolve_symbol(qn)
        .unwrap_or_else(|| panic!("{qn} is not loaded — the prelude is required"));
    Value::Entity {
        functor,
        pos: std::rc::Rc::from(Vec::new()),
        named: std::rc::Rc::from(named),
    }
}

/// Read a bound `?receiver` back as its `ReceiverForm` SHORT name. A nullary
/// form (`MutRef`) rides as a symbol ref; a payload-bearing one
/// (`ResultTyped(error: …)`) as an `Fn` — `functor_or_ref_short` answers both
/// with the constructor name, which is what the caller matches on. Only the
/// `Value` → `TermId` unwrap is local; the naming rule stays in one place.
fn receiver_short_name(kb: &KnowledgeBase, v: &Value) -> Option<String> {
    let Value::Term { id, .. } = v else {
        return None;
    };
    functor_or_ref_short(kb, *id)
}

/// WI-089(b): the cpp `ReceiverForm` short name realizing `effect` under the
/// active compilation profile — the effect_map analogue of declared-signature
/// host-type resolution. Thin `lang = "cpp"` binding of [`realizes_effect`].
fn cpp_effect_receiver(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    effect: &str,
) -> Option<String> {
    realizes_effect(kb, "cpp", ctx.profile.as_deref(), effect)
}

/// WI-774: the values-first RESOLVED realization-fact reader — the ground rows of
/// the first loaded `functor_names` (tried in order, qualified first) under the
/// named `selection`, via `kb.read_facts_resolved` (057 `Resolve` policy). A
/// bodied realization rule is RESOLVED — its guard honored — so a guarded
/// `TypeMapping` / `IncludeMapping` / `NamingConvention` / `EffectMapping` /
/// `LanguageMapping` entry participates iff its body succeeds (the `Resolve`
/// counterpart of the retired `read_facts(Refuse)` reader, which rejected every
/// bodied candidate outright). Empty when no name is loaded or a selection field
/// name isn't interned (no fact carries it). A DEPTH-CAP-truncated candidate
/// search is a loud `CppCodegenError` (via the `?` on
/// [`ExtentReadError::SearchTruncated`], the WI-767 discipline). A mounted-BACKEND
/// query failure is NOT surfaced here — the resolver's mount path handles it
/// leniently in v1 (log + empty, WI-797); the loud channel for a fallible backend
/// arrives with the write seam (WI-780). Immaterial to the realization readers,
/// which are resident.
///
/// WI-833: all five realization functors now flow through this ONE resolved
/// reader. Each row is a reified `Value::Entity` (children `Value::Term`); read
/// its fields with [`row_named_string`] / [`row_named_optional_string`] /
/// [`row_named_term`], not the `TermId`-head `named_string` the `Refuse` readers
/// use.
fn resolve_realization_rows(
    kb: &mut KnowledgeBase,
    functor_names: &[&str],
    selection: &[(&str, &str)],
) -> Result<Vec<Value>, CppCodegenError> {
    let Some((functor, sel)) = realization_functor_and_selection(kb, functor_names, selection)
    else {
        return Ok(Vec::new());
    };
    Ok(kb.read_facts_resolved(functor, &sel)?)
}

/// Read named field `field` off a RESOLVED row (a `Value` from
/// [`resolve_realization_rows`] / `read_facts_resolved`) as its child `TermId`. A
/// resolved row is a reified enumeration goal — a `Value::Entity` whose children
/// are carrier-faithful reifications — so this reads the field carrier-neutrally
/// and hands its (term) carrier to the existing term readers (`as_string` /
/// `walk_list`) unchanged. `Ok(None)` when the field is ABSENT (a legitimate skip
/// — e.g. an entity-constructor row that lacks it).
///
/// A field READ BACK through this function is always a `Value::Term` (WI-848,
/// measured across `IncludeMapping` / `TypeMapping` / `NamingConvention`, fact and
/// bodied rule). Readers read back the FREE (non-selected) columns — a selected
/// column is grounded to its selection scalar and never re-read here — and the
/// realization functors are plain entity sorts, so their facts/rules are
/// TERM-headed. Each free column is a goal var that unifies with the stored head's
/// term child, and `read_facts_resolved` reifies the row via `KnowledgeBase::reify`,
/// which surfaces a term-level variable — the loader's var-fill of an OMITTED
/// REQUIRED field, or an UNCONSTRAINED rule-head var — as `Value::Term` wrapping a
/// `Term::Var`, NOT as a value-level `Value::Var`. So an under-determined field
/// arrives via the `Value::Term` arm below (returned `Ok(Some(id))`); `as_string`
/// then matches only `Term::Const(String)` and reads a var-term as absent, so the
/// row contributes no mapping — the correct reading of a realization entry missing
/// a required field (it maps nothing). That is WHY an omitted required field emits
/// cleanly instead of erroring; it is a correct program, not a malformed one.
/// (An omitted `Option` field is `none`-filled by the loader, so it is a real
/// `Term` — `some`/`none` — that `extract_optional_string` reads directly.)
///
/// The non-`Term` arm is therefore DEFENSIVE, not a described user-facing behavior:
/// a value-level `Value::Var` cannot arise (per above — so the prior "field is
/// unbound / missing required field" story on it was measurably false and
/// UNREACHABLE), and no realization source produces any other non-`Term` carrier
/// today. It guards a future value-headed producer (a mounted store handing back a
/// raw `Value`, a builtin-computed field) the Term-assuming realization readers
/// could not consume — kept loud per the CLAUDE.md "loud error over silent skip"
/// principle, never a silent drop.
fn row_named_term(
    kb: &KnowledgeBase,
    row: &Value,
    field: &str,
) -> Result<Option<TermId>, CppCodegenError> {
    let Some(sym) = kb.lookup_symbol(field) else {
        return Ok(None);
    };
    match row.named_arg(kb, sym).map(|v| v.to_value()) {
        None => Ok(None),
        // The universal case (WI-848): a resolved row's field is always a term. An
        // under-determined field is a `Term::Var` here — the string readers skip a
        // non-literal, so a realization entry missing a required field maps nothing.
        Some(Value::Term { id, .. }) => Ok(Some(id)),
        // DEFENSIVE (WI-848): unreachable today — see the doc comment. A resolved
        // realization row is term-carried, so this fires only if a future
        // value-headed producer hands back a non-term carrier; loud when it does.
        Some(other) => Err(CppCodegenError {
            message: format!(
                "resolved realization row: field `{field}` has an unexpected {} \
                 carrier; cpp-gen reads realization fact fields as terms",
                other.type_name()
            ),
        }),
    }
}

/// WI-833: read a plain-`String` field off a RESOLVED row — the row-based
/// counterpart of [`named_string`] (which reads a fact-head `TermId`). `Ok(None)`
/// when the field is absent or not a string literal; a present non-term carrier
/// is a loud error via [`row_named_term`].
fn row_named_string(
    kb: &KnowledgeBase,
    row: &Value,
    field: &str,
) -> Result<Option<String>, CppCodegenError> {
    Ok(row_named_term(kb, row, field)?.and_then(|t| as_string(kb, t)))
}

/// WI-833: read an `Option[String]` field off a RESOLVED row (`some("x")` →
/// `Some("x")`, `none` → `None`) — the row-based counterpart of
/// [`named_optional_string`]. `Ok(None)` when the field is absent or its `Option`
/// is `none`; a present non-term carrier is a loud error via [`row_named_term`].
fn row_named_optional_string(
    kb: &KnowledgeBase,
    row: &Value,
    field: &str,
) -> Result<Option<String>, CppCodegenError> {
    Ok(row_named_term(kb, row, field)?.and_then(|t| extract_optional_string(kb, t)))
}

/// WI-576: every effect `lang` realizes under `profile` — the profile's
/// SUPPORTED-EFFECT SET, which the capability gate requires an operation's
/// residual row to be a subset of.
///
/// WI-774: both representations are RESOLVED to gather CANDIDATE effect names, then
/// [`realizes_effect`] decides membership per name. Resolution (not the retired
/// WI-770 head-match) means a bodied `EffectMapping` / `LanguageMapping` rule is
/// EVALUATED — its guard honored — instead of aborting the read: the old
/// head-match `assert!` fired even while RENDERING this gate's error, turning a
/// diagnostic into a panic. The candidate list stays deliberately over-broad (the
/// flat read grounds nothing — `lang` is an `Option` field, `some("cpp")`, not a
/// plain-string selection; the nested read grounds only `language`), and the
/// `realizes_effect` filter, not the candidate read, is what makes the answer
/// exact. Sorted + deduplicated for a deterministic diagnostic. Fallible: a
/// truncated candidate search (WI-767 depth-cap discipline) or a mounted-store
/// failure is a loud refusal, never a silently short set.
fn supported_effects(
    kb: &mut KnowledgeBase,
    lang: &str,
    profile: Option<&str>,
) -> Result<Vec<String>, CppCodegenError> {
    // Resolve the CANDIDATE rows first (each read borrows `&mut kb`), collecting
    // owned `Value` rows, before extracting names under a shared borrow —
    // `realizes_effect` (below) also resolves (`&mut`), so no reader may run inside
    // a chain still borrowing the KB.
    let flat_rows = resolve_realization_rows(
        kb,
        &["anthill.realization.EffectMapping", "EffectMapping"],
        &[],
    )?;
    let lang_rows = resolve_realization_rows(
        kb,
        &["anthill.realization.LanguageMapping", "LanguageMapping"],
        &[("language", lang)],
    )?;

    let mut names: Vec<String> = Vec::new();
    // Flat: each top-level `EffectMapping` row's `effect`.
    for row in &flat_rows {
        if let Some(effect) = row_named_string(kb, row, "effect")? {
            names.push(effect);
        }
    }
    // Nested: each `LanguageMapping` row's `effect_map` cons-list → each entry's
    // `effect` (the rust/scala representation the flat read never surfaces).
    for row in &lang_rows {
        if let Some(list) = row_named_term(kb, row, "effect_map")? {
            for entry in walk_list(kb, list) {
                if let Some(effect) = named_string(kb, entry, "effect") {
                    names.push(effect);
                }
            }
        }
    }
    names.sort();
    names.dedup();
    names.retain(|effect| realizes_effect(kb, lang, profile, effect).is_some());
    Ok(names)
}

/// WI-576: name the codegen target in a diagnostic. `emit_traits_struct` and
/// friends run with no profile selected (only `Generated.profile` threads one
/// in), and "profile None" is not a useful thing to tell a user.
fn cpp_profile_label(ctx: &CodegenContext) -> String {
    match &ctx.profile {
        Some(p) => format!("profile '{p}'"),
        None => "the cpp language base (no profile selected)".to_string(),
    }
}

/// WI-576: render [`supported_effects`] for the capability gate's error text.
/// Fallible (WI-774): a truncated / failed candidate resolution propagates rather
/// than aborting mid-diagnostic (the head-match `assert!` this replaced panicked
/// exactly here — while rendering the gate error).
fn describe_supported_effects(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
) -> Result<String, CppCodegenError> {
    let names = supported_effects(kb, "cpp", ctx.profile.as_deref())?;
    Ok(if names.is_empty() {
        "(none declared — is the cpp realization profile loaded?)".to_string()
    } else {
        names.join(", ")
    })
}

/// WI-089(c): the cpp `(host_type spelling, include directive)` probe pairs from
/// the keyed `IncludeMapping` facts — replaces the hardcoded `INCLUDE_PROBES`
/// array. Grounds the plain-String `lang`; caller sorts for deterministic output.
///
/// WI-833: RESOLVED, not `Refuse` — a bodied `IncludeMapping` rule is EVALUATED
/// (its guard honored), so a project can gate a probe on a condition. The probes
/// form a SET (each is an independent "when this spelling appears, include that
/// header"), so aggregation is a plain DEDUP: `Resolve` may enumerate the same
/// pair via several derivations, and a probe list with duplicates would render a
/// directive twice (`Includes::needed` keys on the probe INDEX). Two probes with
/// the same spelling but DIFFERENT includes are NOT a conflict — a type can need
/// two headers — so both are kept (deduped, sorted) and both fire on a hit;
/// there is no per-key winner to be ambiguous about (unlike `TypeMapping`).
fn query_include_mappings(
    kb: &mut KnowledgeBase,
    lang: &str,
) -> Result<Vec<(String, String)>, CppCodegenError> {
    let mut out: Vec<(String, String)> = Vec::new();
    for row in resolve_realization_rows(
        kb,
        &["anthill.realization.IncludeMapping", "IncludeMapping"],
        &[("lang", lang)],
    )? {
        let (Some(host_type), Some(include)) = (
            row_named_string(kb, &row, "host_type")?,
            row_named_string(kb, &row, "include")?,
        ) else {
            continue;
        };
        let pair = (host_type, include);
        if !out.contains(&pair) {
            out.push(pair);
        }
    }
    Ok(out)
}

/// WI-089(b): the host method spelling for an anthill `source` identifier under
/// the cpp `NamingConvention` fact — replaces the hardcoded `snake_to_camel`
/// call at the carrier-dispatch boundary. The only transform implemented is
/// `snake_case -> camelCase` (cpp's declared convention); any other declared
/// pair (including same-case) is identity. The convention is the source of
/// truth, not a hardcoded default: an ABSENT one is a loud `CppCodegenError`
/// (WI-846), not a silent identity fallback — this reader is reached only at a
/// carrier-dispatch boundary, where guessing the host method name emits
/// non-compilable C++. Per-operation acronym irregulars (get_gps -> getGPS)
/// ride a CppName override (WI-087), not this default.
fn cpp_method_name(kb: &mut KnowledgeBase, source: &str) -> Result<String, CppCodegenError> {
    // NamingConvention describes casing, not lexical validity. Cross the
    // Anthill -> C++ identifier boundary first so both identity casing and the
    // snake_case -> camelCase transform receive `zero_val`, never `zero-val`.
    let normalized = cpp_identifier(source);
    // WI-833: RESOLVED, not `Refuse` — a bodied `NamingConvention` rule is
    // EVALUATED (its guard honored), so a project can gate the convention on a
    // condition instead of the read refusing it loudly.
    let rows = resolve_realization_rows(
        kb,
        &["anthill.realization.NamingConvention", "NamingConvention"],
        &[("language", "cpp")],
    )?;
    // The convention is SINGLE-VALUED: cpp_std supplies exactly one cpp
    // NamingConvention, and per-op irregulars ride a CppName attribute (WI-087),
    // never a second convention. `unique_or_ambiguous` collapses identical
    // resolved rows (Resolve can enumerate one convention via several derivations
    // — a duplicate, not a conflict) and rejects a genuinely competing pair loudly
    // (WI-833), the `realizes_effect` discipline applied to a `Result` reader.
    let pairs: Vec<(Option<String>, Option<String>)> = rows
        .iter()
        .map(|row| {
            Ok((
                row_named_string(kb, row, "source_case")?,
                row_named_string(kb, row, "method_case")?,
            ))
        })
        .collect::<Result<_, CppCodegenError>>()?;
    let convention = unique_or_ambiguous(pairs, |distinct| CppCodegenError {
        message: format!(
            "ambiguous cpp NamingConvention: {distinct:?} — exactly one (source_case, \
             method_case) may resolve; per-operation irregulars ride a CppName \
             attribute (WI-087), not a second convention"
        ),
    })?;
    // Zero conventions is NOT an ordinary miss (WI-846): `cpp_method_name` is
    // reached only at a CARRIER-DISPATCH boundary (the `self->method(...)` call),
    // where the host method spelling MUST be known — guessing identity emits
    // `self->get_reading()` against a vendor header that may declare
    // `getReading()`, non-compilable C++, silently. The realization profile is
    // the source of truth, so its absence is a profile bug, not a default to
    // paper over: fail loudly, naming the absent profile and the fix (repo rule:
    // "prefer a loud error over a silent skip"). This is the zero-half twin of
    // the >1 ambiguity error above — both are the `realizes_effect` <=1
    // discipline applied to a `Result` reader; WI-833 restored only the >1 half
    // and replaced this half with silent identity. Unreachable in normal codegen:
    // the bundled stdlib always ships one cpp NamingConvention (cpp_std, a plain
    // fact that always resolves). A hand-built KB with no realization profile is
    // further guarded wherever a signature carries a primitive (`sort_to_cpp`
    // fails there first), though an all-carrier-typed op has none — which is what
    // the WI-846 test exercises.
    let Some((source_case, method_case)) = convention else {
        return Err(CppCodegenError {
            message: format!(
                "no cpp NamingConvention resolved for carrier-dispatch method '{source}' — \
                 the cpp realization profile (anthill.realization.cpp_std) is not loaded, or \
                 declares no NamingConvention for language \"cpp\". Load a cpp naming profile, \
                 or assert `fact NamingConvention(language: \"cpp\", source_case: ..., \
                 method_case: ...)` (set source_case = method_case, e.g. \"snake_case\" -> \
                 \"snake_case\", to declare identity casing intentional)"
            ),
        });
    };
    Ok(match (source_case.as_deref(), method_case.as_deref()) {
        (Some("snake_case"), Some("camelCase")) => snake_to_camel(&normalized),
        // Same source/method spelling: a legitimate no-op (e.g. a profile that
        // keeps snake_case).
        (Some(s), Some(m)) if s == m => normalized,
        // A declared-but-unimplemented, partial, or malformed casing is a
        // realization-profile misconfiguration (not user input): fail loudly in
        // dev/test per "loud error over silent skip"; identity in release.
        (s, m) => {
            debug_assert!(
                false,
                "cpp NamingConvention declares unsupported/partial casing {s:?} -> {m:?}; \
                 only snake_case -> camelCase (and identity) are implemented"
            );
            normalized
        }
    })
}
