// ── Templates ────────────────────────────────────────────────────────
//
// Slots use `{name}` syntax. They are textually `.replace`d; no nesting,
// no escaping needed (C++ source we emit doesn't contain literal `{name}`
// at any slot position). Slot values must not themselves contain other
// slots that would be re-substituted — for current uses this is trivially
// safe (slots hold identifiers, type names, or already-rendered field
// blocks).

const TEMPLATE_ENTITY_STRUCT: &str = "\
{template}struct {name} {
{fields}};
";

const TEMPLATE_FIELD: &str = "    {ty} {name};\n";

const TEMPLATE_HEADER: &str = "\
// Generated by anthill-cpp-gen — do not edit by hand.
// Source: anthill spec namespace `{ns_anthill}`.

#pragma once
{includes}
namespace {ns_cpp} {

{items}}  // namespace {ns_cpp}
";

const TEMPLATE_TRAITS_STRUCT: &str = "\
{template}struct {name} {
{methods}};
";

const TEMPLATE_STATIC_METHOD_DECL: &str = "    static {ret} {name}({params});\n";

const TEMPLATE_VARIANT_ALIAS: &str = "{template}using {sort_name} = std::variant<{ctor_list}>;\n";

// Note: deliberately no `\<newline>` line-continuation here — that
// would strip the leading 4-space indent. The literal starts with
// the four spaces as written.
const TEMPLATE_STATIC_METHOD_BODY: &str = "    static {ret} {name}({params}) {
        {body}
    }
";

// ── Errors ───────────────────────────────────────────────────────────

#[derive(Debug, Clone)]
pub struct CppCodegenError {
    pub message: String,
}

impl std::fmt::Display for CppCodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for CppCodegenError {}

/// WI-771: a bodied-rule refusal (or extent failure) from the values-first
/// `read_facts` accessor (WI-773/057) renders through cpp-gen's own error
/// channel — `error: {message}`, exit 1 at `run_codegen_cpp`. With this `From`,
/// a realization reader in a `Result<_, CppCodegenError>` context routes the
/// refusal with a bare `?`. This is the graceful successor to the WI-770
/// `assert!` abort (exit 101, no span) for the readers WI-771 migrated —
/// `Implementation` / `OperationImpl` / `Generated` / `OperationInfo` — which
/// still ride `read_facts(Refuse)` (they consume GROUND SINGLE-VALUED fact heads,
/// so a bodied rule under those functors is genuinely unconsumable and a loud
/// refusal is correct).
///
/// WI-833: the type-lowering readers `TypeMapping` / `IncludeMapping` /
/// `NamingConvention` GRADUATED from `Refuse` to `Resolve` (`read_facts_resolved`,
/// via [`resolve_realization_rows`]) — joining `supported_effects` (WI-774). A
/// bodied realization rule under those functors is now EVALUATED (its guard
/// honored), with per-key ambiguity resolved or rejected caller-side
/// ([`select_keyed_unique`]) rather than the read refusing every bodied
/// candidate. Every cpp-gen realization read now rides `read_facts` /
/// `read_facts_resolved`; the WI-770 `assert!`-abort mechanism is gone.
impl From<ExtentReadError> for CppCodegenError {
    fn from(e: ExtentReadError) -> Self {
        CppCodegenError {
            message: e.to_string(),
        }
    }
}

/// WI-771: narrow a `read_facts` row — a fact head `Value` — to the head
/// `TermId` the term-based realization readers consume. `Implementation`,
/// `OperationImpl`, and `Generated` are invariantly Term-carried (their facts
/// are asserted as ground terms; the pre-WI-771 walk read them via
/// `kb.rule_head`, which panics on a value head), so a value/Node head is a loud
/// error here — never a silent skip (surface the unexpected carrier). Contrast
/// the `OperationInfo` readers, which DO carry value heads (WI-348/WI-366) and
/// so read the row carrier-neutrally via `op_info::head_name_ref`.
fn expect_term_head(
    kb: &KnowledgeBase,
    functor: Symbol,
    row: Value,
) -> Result<TermId, CppCodegenError> {
    match row {
        Value::Term { id, .. } => Ok(id),
        _ => Err(CppCodegenError {
            message: format!(
                "realization functor `{}` has a non-term fact head; cpp-gen reads it as a term",
                kb.local_name_of(functor)
            ),
        }),
    }
}

// ── Carrier table & codegen context ──────────────────────────────────

/// Resolved table of qualified-anthill-sort-name → C++ host type,
/// built from `Implementation` + `CarrierBinding` facts in the KB.
///
/// Currently captures the *self-carrier* of each Implementation: when
/// `Implementation(target: "X", carrier: [CarrierBinding(sort_name: "X_short", host_type: "Y")])`
/// is asserted, `lookup("X")` returns `Some("Y")`. Sub-sort carriers
/// (CarrierBindings whose sort_name is not the target's short name)
/// are not yet wired through — extending this is mechanical when a
/// concrete consumer needs it.
///
/// Only Implementation facts with `language: "cpp"` participate.
pub struct CarrierTable {
    /// Anthill qualified name → host C++ type spelling.
    by_qualified: HashMap<String, String>,
    /// Anthill qualified name → header path that declares the host
    /// type (`Implementation.artifact`). Populated alongside the host
    /// type so the namespace-header writer can emit a corresponding
    /// `#include` whenever a carrier-bound type is referenced.
    artifacts: HashMap<String, String>,
    /// WI-089(a): anthill qualified name → foreign-binding overlay key
    /// (`Implementation.binding`, e.g. "webots"). A carrier-dispatch body
    /// onto this sort prepends the binding key to the active-key list so the
    /// binding's marshalling `TypeMapping` overlays win over the language
    /// base. Absent for a plain host-std realization (`binding: none`).
    bindings: HashMap<String, String>,
}

impl CarrierTable {
    /// Build the table from the KB's `Implementation` facts, read through the
    /// values-first `read_facts` accessor (WI-771/773/057). Returns an empty
    /// table if no `Implementation` symbol is in the KB (i.e. the realization
    /// stdlib wasn't loaded). A BODIED `Implementation` rule is refused loudly
    /// through `CppCodegenError` rather than head-matched with its guard silently
    /// skipped — which would bind carrier / host_type / binding-key
    /// unconditionally and emit the wrong C++ type and include (WI-770 class).
    /// Resident today; a mounted `realization.Implementation` store reads through
    /// the same call, and cpp-gen unchanged.
    pub fn from_kb(kb: &KnowledgeBase) -> Result<Self, CppCodegenError> {
        let mut by_qualified = HashMap::new();
        let mut artifacts = HashMap::new();
        let mut bindings = HashMap::new();

        let impl_sym = kb
            .try_resolve_symbol("anthill.realization.Implementation")
            .or_else(|| kb.try_resolve_symbol("Implementation"));
        let Some(impl_sym) = impl_sym else {
            return Ok(Self {
                by_qualified,
                artifacts,
                bindings,
            });
        };

        for row in kb.read_facts(impl_sym, &[], BodiedRulePolicy::Refuse)? {
            let head = expect_term_head(kb, impl_sym, row)?;

            let target = match named_string(kb, head, "target") {
                Some(t) => t,
                None => continue,
            };
            let language = named_string(kb, head, "language");
            if language.as_deref() != Some("cpp") {
                continue;
            }
            let artifact = named_string(kb, head, "artifact");
            // WI-089(a): the foreign-binding overlay key for this realization
            // (e.g. "webots"). `binding: none` (or an omitted field, padded to
            // an unbound var by the loader) reads back as None — a plain host-
            // std realization contributing no value-level marshalling.
            let impl_binding = named_optional_string(kb, head, "binding");

            let carrier_list = match named_arg(kb, head, "carrier") {
                Some(t) => t,
                None => continue,
            };
            let target_short = target.rsplit('.').next().unwrap_or(&target).to_string();

            for binding in walk_list(kb, carrier_list) {
                let sort_name = named_string(kb, binding, "sort_name");
                let host_type = named_string(kb, binding, "host_type");
                if let (Some(sn), Some(ht)) = (sort_name, host_type) {
                    // For now: only the self-carrier (sort_name == target's
                    // short name) lands in the table keyed by `target`.
                    // Sub-sort carriers will get their own keys when needed.
                    if sn == target_short {
                        by_qualified.insert(target.clone(), ht);
                        // The loader defaults an absent `artifact` clause to
                        // "" (load.rs `unwrap_or_default`), so guard against
                        // empty here — otherwise a carrier with no artifact
                        // (e.g. `int64_t`, whose `<cstdint>` include comes
                        // from the std-include table) would emit `#include <>`.
                        if let Some(a) = artifact.clone().filter(|s| !s.is_empty()) {
                            artifacts.insert(target.clone(), a);
                        }
                        // WI-089(a): record the realization's binding key
                        // against the carrier sort, so a dispatch boundary onto
                        // it knows which marshalling overlay family is active.
                        if let Some(b) = impl_binding.clone() {
                            bindings.insert(target.clone(), b);
                        }
                    }
                }
            }
        }

        Ok(Self {
            by_qualified,
            artifacts,
            bindings,
        })
    }

    /// Look up a host type by the anthill sort's fully qualified name.
    pub fn lookup(&self, qualified: &str) -> Option<&str> {
        self.by_qualified.get(qualified).map(|s| s.as_str())
    }

    /// Look up the header that declares this carrier's host type, if
    /// the source `Implementation` fact carried an `artifact`. Used
    /// to emit `#include "<artifact>"` in headers that reference the
    /// carrier-bound type.
    pub fn artifact(&self, qualified: &str) -> Option<&str> {
        self.artifacts.get(qualified).map(|s| s.as_str())
    }

    /// WI-089(a): the foreign-binding overlay key for this carrier sort, if its
    /// `Implementation` declared one (`binding: some("webots")`). A carrier-
    /// dispatch body onto this sort prepends the key to the active-key list so
    /// the binding's marshalling `TypeMapping` overlays shadow the language base.
    pub fn binding(&self, qualified: &str) -> Option<&str> {
        self.bindings.get(qualified).map(|s| s.as_str())
    }

    /// Whether the table has any entries (used by tests).
    pub fn is_empty(&self) -> bool {
        self.by_qualified.is_empty()
    }
}

/// A marshalled type representation: the value-level adapter pair that
/// bridges an anthill type and a foreign host representation of it.
struct Marshal {
    /// foreign->anthill adapter, applied to a value READ from the host
    /// API (e.g. a carrier-method return: `const double * -> Vec3`).
    lift: Option<String>,
    /// anthill->foreign adapter, applied to a value PASSED INTO a
    /// host-API call (e.g. a carrier-method arg: `Vec3 -> const double *`).
    lower: Option<String>,
}

// WI-089(a): marshalling is NO LONGER a separate prebuilt reader. The
// adapter-bearing `TypeMapping` overlays are resolved through the SAME keyed
// query as the plain renames (`resolve_type_mapping` / `query_type_mappings`),
// selected by the active-key priority — so there is one TypeMapping reader, one
// place that implements binding-shadows-profile-shadows-base. The former
// `MarshalTable` (a second functor scan that ignored the key) is retired; see
// `marshal_for_type`.

/// Resolved table of operation symbol → body TermId, built from
/// `anthill.realization.OperationImpl` facts. Operations with
/// expression bodies (e.g. `operation square(x: Int) -> Int = mul(x, x)`)
/// land here; the body Term is lowered to a C++ expression by
/// `lower_node`. Post-WI-249 the value is the operation body's
/// NodeOccurrence root sourced from `kb.op_body_node` — the legacy
/// `OperationImpl.body` Handle field is no longer read here. The
/// OperationImpl fact still exists (it's also a realization-side
/// declaration), but the body is materialized at load time.
pub struct OpImplTable {
    by_op: HashMap<Symbol, std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>>,
}

impl OpImplTable {
    /// Build the table from the KB's `OperationImpl` facts, read through the
    /// values-first `read_facts` accessor (WI-771/773/057). A BODIED
    /// `OperationImpl` rule is refused loudly through `CppCodegenError` rather
    /// than head-matched with its guard silently skipped — which would enroll the
    /// operation body for emission unconditionally (WI-770 class).
    pub fn from_kb(kb: &KnowledgeBase) -> Result<Self, CppCodegenError> {
        let mut by_op = HashMap::new();
        let sym = kb
            .try_resolve_symbol("anthill.realization.OperationImpl")
            .or_else(|| kb.try_resolve_symbol("OperationImpl"));
        let Some(sym) = sym else {
            return Ok(Self { by_op });
        };

        for row in kb.read_facts(sym, &[], BodiedRulePolicy::Refuse)? {
            let head = expect_term_head(kb, sym, row)?;
            // operation: Term::Ref(<op_sym>)
            let Some(op_term) = named_arg(kb, head, "operation") else {
                continue;
            };
            let op_sym = match kb.get_term(op_term) {
                Term::Ref(s) | Term::Ident(s) => *s,
                _ => continue,
            };
            // Read the materialized body NodeOccurrence from the KB.
            // Ops with no body (spec-level declarations) are skipped.
            if let Some(node) = kb.op_body_node(op_sym) {
                by_op.insert(op_sym, node.clone());
            }
        }
        Ok(Self { by_op })
    }

    pub fn lookup(
        &self,
        op: Symbol,
    ) -> Option<std::rc::Rc<anthill_core::kb::node_occurrence::NodeOccurrence>> {
        self.by_op.get(&op).cloned()
    }
}

/// WI-886 — the per-carrier C++ implementations named by every loaded
/// `provides <carrier> language cpp` block's `operation_map` clause, read from the
/// KB's `anthill.realization.OperationMapping` cache (`kb.host_op_mappings()`).
///
/// This is cpp-gen's peer of the rust runtime's [`register_operation_mappings`]
/// (`anthill-core/src/eval/builtins.rs`), and it replaces THREE hand-written Rust
/// tables — `render_as_math_call`, `render_as_math_constant`, and the per-carrier half
/// of `render_as_operator` — which had drifted from the rust runtime's surface and from
/// each other. The measurement is in `wi886_host_operation_mapping_test`'s module doc;
/// see [`lower_node`]'s unmapped-operation refusal for the other half of the fix.
///
/// `host_fn` under `lang = "cpp"` is a C++ EXPRESSION TEMPLATE — `$1`, `$2`, … stand
/// for the operation's already-lowered arguments. `docs/kernel-language.md` §10.2 is
/// where that reading and its reason are defined.
///
/// ## What is checked, and where
///
/// The template is PARSED ONCE, here, at table-build time — for every cpp mapping,
/// not lazily at a call site, so a binding nothing calls is still checked — and what
/// is stored is the parse, not the string. Its argument slots must be exactly
/// `$1`..`$n` for the operation's `n` declared parameters, EACH ONCE. This is the peer
/// of the rust registry's arity column (WI-876), and it is the only check available:
/// whether `std::fabs` exists and takes a double is the C++ compiler's question.
pub struct HostOpTable {
    by_op: HashMap<Symbol, HostOpTemplate>,
}

/// One `operation_map` entry as cpp-gen consumes it: the parsed C++ expression
/// template, and the operation's declared arity (kept so a bare nullary reference —
/// `pi` without parentheses — can be told from a reference to an operation that takes
/// arguments).
struct HostOpTemplate {
    /// The source spelling, kept only so a diagnostic can quote what the author wrote.
    source: String,
    parts: Vec<TemplatePart>,
    arity: usize,
}

/// One piece of a parsed cpp `host_fn` template: literal C++, or the ONE-based index
/// of an argument to substitute.
enum TemplatePart {
    Text(String),
    Arg(usize),
}

impl HostOpTable {
    /// Build the table from the KB's cpp `operation_map` entries. `Err` when a
    /// template is malformed or its slots do not match its operation's declared arity.
    pub fn from_kb(kb: &KnowledgeBase) -> Result<Self, CppCodegenError> {
        let mut by_op = HashMap::new();
        for m in kb.host_op_mappings().iter().filter(|m| m.lang == CPP_LANG) {
            // `op` is `None` only when the loader already refused this mapping (the
            // carrier declares no such operation, or the name is not an operation),
            // so the load errored and there is nothing to key. Same reasoning as
            // `register_operation_mappings`.
            let Some(sym) = m.op else { continue };
            let subject = format!(
                "operation_map maps `{}` to the C++ template {:?}",
                m.op_qn, m.host_fn
            );
            let arity = anthill_core::kb::op_info::declared_arity(kb, sym).ok_or_else(|| {
                CppCodegenError {
                    message: format!(
                        "{subject}, but `{}` has no recorded signature — cpp-gen cannot check \
                         the template against an arity it does not know",
                        m.op_qn
                    ),
                }
            })?;
            let parts = parse_host_template(&m.host_fn).map_err(|what| CppCodegenError {
                message: format!(
                    "{subject}, which {what}. A cpp `host_fn` is an expression template: \
                     `$1`, `$2`, … stand for the operation's arguments"
                ),
            })?;
            // EACH slot ONCE, in any order: a template that drops an argument silently
            // discards a computed value, one that invents an index has nothing to
            // substitute, and one that REPEATS an index evaluates that argument twice —
            // the arguments arrive as already-lowered expressions, which may be calls.
            // (An operation whose C++ genuinely reads an operand twice binds it in a
            // non-capturing lambda instead; see `Int64.compare` in the binding file.)
            let mut slots: Vec<usize> = parts
                .iter()
                .filter_map(|p| match p {
                    TemplatePart::Arg(i) => Some(*i),
                    TemplatePart::Text(_) => None,
                })
                .collect();
            let rendered_slots = if slots.is_empty() {
                "none".to_string()
            } else {
                slots
                    .iter()
                    .map(|i| format!("${i}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            slots.sort_unstable();
            if slots.iter().copied().ne(1..=arity) {
                return Err(CppCodegenError {
                    message: format!(
                        "{subject}, but `{}` takes {arity} argument(s) and the template uses \
                         {rendered_slots}. Each argument must appear EXACTLY ONCE as \
                         `$1`..`${arity}`",
                        m.op_qn
                    ),
                });
            }
            by_op.insert(
                sym,
                HostOpTemplate {
                    source: m.host_fn.clone(),
                    parts,
                    arity,
                },
            );
        }
        Ok(Self { by_op })
    }

    /// The C++ expression template realizing `op`, with the operation's declared
    /// arity. `None` when no cpp binding block named this operation.
    fn lookup(&self, op: Symbol) -> Option<&HostOpTemplate> {
        self.by_op.get(&op)
    }

    /// Whether any cpp `operation_map` entry was loaded. Read by the
    /// unmapped-operation refusal, whose message points at the likely cause when the
    /// answer is "none at all" (the cpp binding files were not loaded).
    fn is_empty(&self) -> bool {
        self.by_op.is_empty()
    }
}

/// WI-889 — the per-carrier C++ VALUE SOURCES named by every loaded `provides
/// <carrier> language cpp` block's `const_map` clause, read from the KB's
/// `anthill.realization.ConstMapping` cache (`kb.host_const_mappings()`). The
/// const-level peer of [`HostOpTable`], and it replaces the last of WI-886's four
/// hand-written per-carrier tables, `render_as_float_special`.
///
/// A const's `host_fn` under `lang = "cpp"` is a VERBATIM C++ expression — the Float
/// IEEE specials have no C++ literal spelling (`std::numeric_limits<double>::
/// infinity()`), so unlike an operation template it has no `$1` slots to parse or
/// arity to check: a const takes no arguments. The `<limits>` header it needs rides the
/// `IncludeMapping` probe scan of the emitted text (`Includes::scan` finds
/// `std::numeric_limits`), exactly as it did when this was a hand-written table.
struct HostConstTable {
    by_const: HashMap<Symbol, String>,
}

impl HostConstTable {
    /// Build the table from the KB's cpp `const_map` entries.
    fn from_kb(kb: &KnowledgeBase) -> Self {
        let mut by_const = HashMap::new();
        for m in kb
            .host_const_mappings()
            .iter()
            .filter(|m| m.lang == CPP_LANG)
        {
            // `const_sym` is `None` only when the loader already refused this mapping
            // (the carrier declares no such const, or the name is not a const), so the
            // load errored and there is nothing to key. Same reasoning as `HostOpTable`.
            let Some(sym) = m.const_sym else { continue };
            by_const.insert(sym, m.host_fn.clone());
        }
        Self { by_const }
    }

    /// The C++ expression realizing `const_sym`. `None` when no cpp binding block named
    /// this const.
    fn lookup(&self, const_sym: Symbol) -> Option<&str> {
        self.by_const.get(&const_sym).map(String::as_str)
    }
}

/// WI-886 — parse a cpp `host_fn` into literal spans and argument slots. `Err` carries
/// a phrase describing the malformation, for the caller to fold into a message that
/// also names the operation.
///
/// A `$` must introduce a decimal index; there is no escape and none is needed,
/// because `$` is not part of any C++ token (an implementation may accept it in
/// identifiers, which is exactly why a stray one is refused rather than passed
/// through). `$` and the digits are ASCII, so byte offsets are char boundaries and the
/// scan needs no `Vec<char>`.
fn parse_host_template(template: &str) -> Result<Vec<TemplatePart>, String> {
    let mut parts = Vec::new();
    let bytes = template.as_bytes();
    let mut lit_from = 0;
    let mut i = 0;
    while let Some(off) = template[i..].find('$') {
        let dollar = i + off;
        let start = dollar + 1;
        let mut end = start;
        while end < bytes.len() && bytes[end].is_ascii_digit() {
            end += 1;
        }
        if end == start {
            return Err("has a `$` that is not followed by an argument index".to_string());
        }
        let digits = &template[start..end];
        let idx: usize = digits.parse().map_err(|_| {
            format!("has an argument index `${digits}` that is not a usable number")
        })?;
        if idx == 0 {
            return Err("uses `$0`; argument indexes are ONE-based".to_string());
        }
        if dollar > lit_from {
            parts.push(TemplatePart::Text(template[lit_from..dollar].to_string()));
        }
        parts.push(TemplatePart::Arg(idx));
        lit_from = end;
        i = end;
    }
    if lit_from < template.len() {
        parts.push(TemplatePart::Text(template[lit_from..].to_string()));
    }
    Ok(parts)
}

/// WI-886 — substitute already-lowered arguments into a parsed cpp `host_fn`.
///
/// A fold over the parse, so there is no second reading of the `$N` grammar and no
/// out-of-range slot to guard against — `HostOpTable::from_kb` settled both, and
/// storing the parse rather than the string is what makes that hold by construction.
/// The one thing it cannot settle is the CALL SITE's argument count, which is checked
/// here rather than left to substitute the wrong operand.
fn render_host_template(
    tmpl: &HostOpTemplate,
    op_qn: &str,
    args: &[String],
) -> Result<String, CppCodegenError> {
    if args.len() != tmpl.arity {
        return Err(CppCodegenError {
            message: format!(
                "`{op_qn}` is realized in C++ by the template {:?}, which expects {} \
                 argument(s), but the call site supplies {}",
                tmpl.source,
                tmpl.arity,
                args.len()
            ),
        });
    }
    let mut out = String::with_capacity(tmpl.source.len() + 16);
    for part in &tmpl.parts {
        match part {
            TemplatePart::Text(t) => out.push_str(t),
            TemplatePart::Arg(i) => out.push_str(&args[i - 1]),
        }
    }
    Ok(out)
}

/// Bundles a derived `CarrierTable` and `OpImplTable` so emit functions don't
/// have to re-scan facts on every lookup. Construct once per codegen run; pass
/// to every emit function alongside the KB. (Type/effect mappings are not
/// prebuilt — they ride the keyed-`TypeMapping` query, WI-089.)
///
/// WI-760: the context deliberately does NOT hold the `KnowledgeBase`. Codegen
/// now threads `kb: &mut KnowledgeBase` as a separate parameter so realization
/// lookups can run real SLD (`kb.resolve` needs `&mut`) instead of head-matching
/// via `query_view`. Keeping the two apart is what makes that possible: the RAII
/// scope guards below borrow the context *shared*, and if the KB lived here every
/// live guard would block every nested `&mut` call. Split, they never conflict —
/// and the context loses its lifetime parameter entirely.
pub struct CodegenContext {
    pub carriers: CarrierTable,
    pub op_impls: OpImplTable,
    /// WI-886: which C++ expression realizes each of a carrier's operations, from
    /// the loaded `provides <carrier> language cpp` blocks. Empty when none were
    /// loaded, which is a real state — a project that supplies no cpp bindings —
    /// and the unmapped-operation refusal says so.
    pub host_ops: HostOpTable,
    /// WI-889: which C++ expression realizes each of a carrier's bodyless `const`s
    /// (`const_map`) — the Float IEEE specials. The const-level peer of `host_ops`,
    /// and what replaced the hand-written `render_as_float_special` table.
    host_consts: HostConstTable,
    /// WI-089(a): the active compilation profile (e.g. "cpp20-stl"), threaded
    /// from the CLI (a `Generated`/`Implementation` fact's `profile`). Selects
    /// profile-keyed `TypeMapping` / `EffectMapping` overlays ahead of the
    /// language base in the active-key list. `None` = language base only.
    pub profile: Option<String>,
    /// Extra `#include` lines that lowering decides it needs at
    /// run-time (e.g. `<tl/expected.hpp>` for Error-effect ops). Merged
    /// into the rendered include set when emitting a header.
    pub requested_includes: std::cell::RefCell<std::collections::BTreeSet<String>>,
    /// Lexical stack of in-scope type parameters. Each frame holds
    /// the params introduced by one enclosing sort; lookup walks from
    /// top to bottom so an inner sort still sees an outer sort's
    /// params, while an inner declaration of the same name shadows
    /// the outer for the duration of inner emission.
    pub type_params: std::cell::RefCell<Vec<std::collections::HashMap<String, TypeParamBinding>>>,
    /// Lexical stack of in-scope value bindings introduced by match
    /// patterns. Each frame maps a source-level binding name to the
    /// C++ access expression that retrieves the bound value (e.g.
    /// `"w" → "o.value()"` inside `case some(?w) ->`). Lookup walks
    /// top-down so nested matches shadow outer bindings.
    pub value_bindings: std::cell::RefCell<Vec<std::collections::HashMap<String, String>>>,
    /// Anthill namespace currently being emitted as a C++ namespace
    /// block. Set by `emit_namespace_header_in`. Used by `sort_to_cpp`
    /// to decide between short-name (`Vec3`) and fully-qualified
    /// (`::anthill::geometry::Vec3`) references for cross-namespace
    /// entity types.
    pub emitting_namespace: std::cell::RefCell<Option<String>>,
    /// WI-891 — is the `CppCodegenError` currently propagating up the `lower_node`
    /// call tree a CAPABILITY GAP (a lowering the cpp profile does not implement yet:
    /// a self-referential lambda, a spliced recipe, `⊥`, a higher-order residual)
    /// rather than a program- or invariant-fault (a DeBruijn var reaching cpp-gen, an
    /// unresolved dot, an unknown constructor, a broken host binding)? The default is
    /// FATAL: an unmarked error aborts codegen. Only a capability gap is DEGRADED — by
    /// the one degrading reader (`synthesise_body_for`) into a build-breaking
    /// `static_assert` for the single method, keeping the rest of the header. Set ONLY
    /// through [`CodegenContext::capability_gap`], which builds the error and marks the
    /// cell in one step, so the two cannot drift.
    ///
    /// This SUBSUMES WI-886's `unrealized_refusal` flag by inverting it: that flag
    /// force-fatal-ed the one error the old degrade-by-default would have swallowed;
    /// now fatal IS the default and the flag marks the FEW that opt into degrading.
    ///
    /// A flag BESIDE the error rather than a field inside it, because the typed
    /// alternative — `lower_node` returning a two-variant error while its recursive
    /// helpers (`lower_let_chain_node`, `lower_match_branches_node`,
    /// `lower_stdlib_wrapper_node`, `lower_constructor_literal_node`) keep returning
    /// `CppCodegenError` and re-enter `lower_node` with `?` — silently downgrades a
    /// classification raised inside a `let` or `match` arm at that conversion, unless
    /// every helper changes too. A `Cell` on the single shared type cannot lose it.
    ///
    /// Staleness is impossible because the reader clears it immediately before the
    /// `lower_node` call it is asking about, and `lower_node` returns at its first
    /// error — so a set flag means the error just received IS a capability gap. Same
    /// shape as `requested_includes`: a cell the lowering writes and the emitter reads
    /// at a boundary it owns. THE CONTRACT IS THE CLEAR-THEN-READ, so any second
    /// degrading caller must do the same; there is one today.
    pub(crate) capability_gap: std::cell::Cell<bool>,
}

impl CodegenContext {
    /// Build a context with no active profile (language base only). Most
    /// callers; the profile-aware overlays are forward-looking. `Err` when a
    /// realization table read refuses a bodied rule (WI-771).
    pub fn new(kb: &KnowledgeBase) -> Result<Self, CppCodegenError> {
        Self::with_profile(kb, None)
    }

    /// WI-089(a): build a context for a specific compilation profile, so
    /// profile-keyed `TypeMapping` / `EffectMapping` overlays (e.g. a
    /// cpp20-stl-only rename) are selected ahead of the language base.
    ///
    /// Takes the KB only to derive the two tables; it is not retained (WI-760).
    /// `Err` when a realization table read refuses a bodied `Implementation` /
    /// `OperationImpl` rule (WI-771).
    pub fn with_profile(
        kb: &KnowledgeBase,
        profile: Option<String>,
    ) -> Result<Self, CppCodegenError> {
        Ok(Self {
            carriers: CarrierTable::from_kb(kb)?,
            op_impls: OpImplTable::from_kb(kb)?,
            host_ops: HostOpTable::from_kb(kb)?,
            host_consts: HostConstTable::from_kb(kb),
            profile,
            requested_includes: std::cell::RefCell::new(std::collections::BTreeSet::new()),
            type_params: std::cell::RefCell::new(Vec::new()),
            value_bindings: std::cell::RefCell::new(Vec::new()),
            emitting_namespace: std::cell::RefCell::new(None),
            capability_gap: std::cell::Cell::new(false),
        })
    }

    /// WI-089(a): the ordered active-key list for a keyed realization-fact
    /// query, most-specific-first. `binding` is the foreign-binding key in
    /// scope (`Some` at a carrier-dispatch boundary, `None` in declared-
    /// signature position); the compilation profile follows; the language base
    /// (`None`) is always last. `select_keyed_unique` walks this list and the
    /// first key with a matching (resolved, deduped) mapping wins — so a binding
    /// overlay shadows a profile overlay shadows the base; two competing mappings
    /// under one key are a loud error (WI-833). The base sentinel is always
    /// present, so a type with only a base entry still resolves.
    fn active_keys(&self, binding: Option<&str>) -> Vec<Option<String>> {
        active_key_ladder(binding, self.profile.as_deref())
    }
}

/// WI-089(a): the priority ladder itself, most-specific-first —
/// `[binding?, profile?, none]`. Free-standing (rather than only a
/// `CodegenContext` method) because [`realizes_effect`] needs the same ordering
/// but must not build a whole `CodegenContext` to get it: constructing one
/// scans the KB twice for the carrier / op-impl tables, and `supported_effects`
/// asks per candidate effect. ONE definition of the ladder, two entry points.
fn active_key_ladder(binding: Option<&str>, profile: Option<&str>) -> Vec<Option<String>> {
    let mut keys = Vec::with_capacity(3);
    keys.extend(binding.map(|b| Some(b.to_string())));
    keys.extend(profile.map(|p| Some(p.to_string())));
    keys.push(None);
    keys
}

/// One in-scope type parameter's C++ realization: the emitted parameter name plus
/// its kind. `higher_kinded` marks a template-template parameter — declared
/// `template<typename...> class F`, not `typename F` (WI-575) — which is NOT a type
/// and so cannot stand in a type-argument slot like `dependent_false_v<F>`
/// (WI-891); `innermost_type_param` skips those when keying an unlowerable-body
/// static_assert.
#[derive(Clone)]
pub struct TypeParamBinding {
    pub cpp: String,
    pub higher_kinded: bool,
}

impl CodegenContext {
    /// Look up a type-parameter binding by source-level name. Walks
    /// the lexical stack top-down so inner declarations shadow outer
    /// ones with the same name.
    pub fn lookup_type_param(&self, name: &str) -> Option<String> {
        let stack = self.type_params.borrow();
        for frame in stack.iter().rev() {
            if let Some(v) = frame.get(name).map(|b| &b.cpp) {
                return Some(v.clone());
            }
        }
        None
    }

    /// WI-891: build a CAPABILITY-GAP error — a lowering the cpp profile does not
    /// implement yet — and mark [`CodegenContext::capability_gap`] in one step so the
    /// mark cannot drift from the error it describes. Use ONLY as the argument of an
    /// immediately-returned `Err(...)`; the mark rides that error up to the degrading
    /// reader (`synthesise_body_for`), which turns it into a build-breaking
    /// `static_assert` for the one method instead of aborting codegen. Every OTHER
    /// error stays a bare `CppCodegenError { message }`, which is FATAL by default.
    fn capability_gap(&self, message: impl Into<String>) -> CppCodegenError {
        self.capability_gap.set(true);
        CppCodegenError {
            message: message.into(),
        }
    }

    /// WI-891: a FIRST-ORDER C++ template parameter in scope at the current emission
    /// point, or `None` when none is — either the enclosing method is not a template, or
    /// every in-scope param is higher-kinded. Keys the dependent-false idiom for an
    /// unlowerable-body `static_assert`: inside a template member a bare
    /// `static_assert(false, …)` is ill-formed, no diagnostic required, so the assert
    /// must depend on a template parameter to fire (with a required diagnostic) exactly
    /// when the member is instantiated. Picks the lexicographically-smallest such name in
    /// the innermost frame that has one, so a degrade payload is deterministic. Both a
    /// sort's class-template params and a generic op's member-template params qualify —
    /// either makes the method a template — so walking the whole stack top-down is right.
    ///
    /// HIGHER-KINDED params are SKIPPED: a template-template parameter is declared
    /// `template<typename...> class F`, so `dependent_false_v<F>` is ill-formed (F is not
    /// a type) and would replace the codegen diagnostic with a cryptic kind error while
    /// hard-failing the whole header — the very failure WI-891 exists to prevent. When
    /// only higher-kinded params are in scope, `unlowerable_body` falls back to
    /// `static_assert(false, …)`, which still carries the message.
    ///
    /// SAFE even against a member-template's effect-only param that `member_template_prefix`
    /// would otherwise ERASE (it keeps only params appearing in the signature or body):
    /// `unlowerable_body` emits the picked name INTO the body's `static_assert`, and
    /// `member_template_prefix` runs after body synthesis — so the reference resurrects the
    /// param, and the name it depends on is always declared in the emitted `template<…>`.
    fn innermost_type_param(&self) -> Option<String> {
        let stack = self.type_params.borrow();
        stack.iter().rev().find_map(|frame| {
            frame
                .values()
                .filter(|b| !b.higher_kinded)
                .map(|b| &b.cpp)
                .min()
                .cloned()
        })
    }

    /// Push a fresh frame of type-param bindings onto the lexical
    /// stack. Returns a guard that pops the frame on drop, so the
    /// caller doesn't have to remember to restore by hand.
    pub fn push_type_params(
        &self,
        frame: std::collections::HashMap<String, TypeParamBinding>,
    ) -> TypeParamGuard<'_> {
        self.type_params.borrow_mut().push(frame);
        TypeParamGuard { ctx: self }
    }

    /// Look up a value binding (introduced by a match pattern, e.g.
    /// `?w` from `case some(?w) -> ...`) and return its C++ access
    /// expression. Walks the lexical stack top-down for shadowing.
    pub fn lookup_value_binding(&self, name: &str) -> Option<String> {
        let stack = self.value_bindings.borrow();
        for frame in stack.iter().rev() {
            if let Some(v) = frame.get(name) {
                return Some(v.clone());
            }
        }
        None
    }

    /// Push a fresh frame of value bindings. Returns a RAII guard
    /// that pops on drop so callers don't need to manage the stack
    /// by hand. Used by match-branch lowering.
    pub fn push_value_bindings(
        &self,
        frame: std::collections::HashMap<String, String>,
    ) -> ValueBindingGuard<'_> {
        self.value_bindings.borrow_mut().push(frame);
        ValueBindingGuard { ctx: self }
    }

    /// Set the namespace currently being emitted as a C++ namespace
    /// block. Returns a RAII guard that restores the previous value
    /// on drop, so early-returns through `?` don't leave the cell
    /// in the wrong state. Read by `qualify_cross_namespace` and
    /// `register_cross_namespace_include`.
    pub fn enter_namespace(&self, namespace: &str) -> NamespaceGuard<'_> {
        let prev = self
            .emitting_namespace
            .borrow_mut()
            .replace(namespace.to_string());
        NamespaceGuard { ctx: self, prev }
    }
}

/// RAII guard that pops the top type-param frame on drop. Constructed
/// by `CodegenContext::push_type_params`; the lifetime ties it to the
/// context so nested calls compose naturally.
pub struct TypeParamGuard<'g> {
    ctx: &'g CodegenContext,
}

impl<'g> Drop for TypeParamGuard<'g> {
    fn drop(&mut self) {
        self.ctx.type_params.borrow_mut().pop();
    }
}

/// RAII guard that pops the top value-binding frame on drop.
/// Constructed by `CodegenContext::push_value_bindings`.
pub struct ValueBindingGuard<'g> {
    ctx: &'g CodegenContext,
}

impl<'g> Drop for ValueBindingGuard<'g> {
    fn drop(&mut self) {
        self.ctx.value_bindings.borrow_mut().pop();
    }
}

/// RAII guard that restores `emitting_namespace` on drop. Constructed
/// by `CodegenContext::enter_namespace`; `prev` holds whatever the
/// cell contained before this guard was created (typically `None`
/// for top-level emission, `Some(outer)` for a nested namespace).
pub struct NamespaceGuard<'g> {
    ctx: &'g CodegenContext,
    prev: Option<String>,
}

impl<'g> Drop for NamespaceGuard<'g> {
    fn drop(&mut self) {
        *self.ctx.emitting_namespace.borrow_mut() = self.prev.take();
    }
}

// ── Term inspection helpers ──────────────────────────────────────────

/// Get the value of a named argument from a `Term::Fn` head.
fn named_arg(kb: &KnowledgeBase, head: TermId, name: &str) -> Option<TermId> {
    if let Term::Fn { named_args, .. } = kb.get_term(head) {
        for (sym, val) in named_args {
            if kb.local_name_of(*sym) == name {
                return Some(*val);
            }
        }
    }
    None
}

/// Pull a `Literal::String` out of a term, if that's what it is.
fn as_string(kb: &KnowledgeBase, term: TermId) -> Option<String> {
    if let Term::Const(Literal::String(s)) = kb.get_term(term) {
        Some(s.clone())
    } else {
        None
    }
}

/// Combination of `named_arg` + `as_string`.
fn named_string(kb: &KnowledgeBase, head: TermId, name: &str) -> Option<String> {
    named_arg(kb, head, name).and_then(|t| as_string(kb, t))
}

/// Read a named arg declared `Option[String]`, returning the inner string when
/// present (`some("x")` -> `Some("x")`, `none` -> `None`). The Option-typed
/// counterpart of `named_string` (sibling reader for keyed realization facts).
fn named_optional_string(kb: &KnowledgeBase, head: TermId, name: &str) -> Option<String> {
    named_arg(kb, head, name).and_then(|t| extract_optional_string(kb, t))
}

/// Return the qualified name of `sym`'s parent, if any — e.g.
/// `test.geom.Vec3.x` → `Some("test.geom.Vec3")`. Used in lieu of
/// `SymbolTable::scope_of`, which has buggy semantics (finds a
/// sibling in the same scope, not the parent).
fn parent_qualified_name(kb: &KnowledgeBase, sym: Symbol) -> Option<String> {
    parent_namespace_of(kb.qualified_name_of(sym)).map(str::to_string)
}

/// Drop the trailing `.<short>` from a dotted qualified name.
/// `"test.geom.Vec3.x"` → `Some("test.geom.Vec3")`; `"top"` → `None`.
fn parent_namespace_of(qn: &str) -> Option<&str> {
    qn.rsplit_once('.').map(|(parent, _)| parent)
}

/// Last `.`-separated component of a qualified name. `test.geom.Vec3` → `"Vec3"`.
fn short_name_of(qn: &str) -> &str {
    qn.rsplit('.').next().unwrap_or(qn)
}

/// Map one Anthill identifier to its C++ spelling.
///
/// Anthill admits `-` in identifiers while C++ does not. The C++ profile keeps
/// source spelling otherwise, so normalization is deliberately the single
/// substitution `-` -> `_`; kind-specific transforms such as a carrier's
/// snake_case -> camelCase convention run after this boundary transform.
pub fn cpp_identifier(source: &str) -> String {
    source.replace('-', "_")
}

/// Render a dotted Anthill namespace as a C++17 nested namespace, normalizing
/// each segment at the same boundary as every other emitted identifier.
fn cpp_namespace(namespace: &str) -> String {
    namespace
        .split('.')
        .map(cpp_identifier)
        .collect::<Vec<_>>()
        .join("::")
}

/// Reject the information loss introduced by `-` -> `_` inside one C++ name
/// scope. Repeated occurrences of the same Anthill spelling are harmless (for
/// example an overloaded operation name); two distinct spellings are not.
fn refuse_cpp_identifier_collisions<'a>(
    scope: &str,
    source_names: impl IntoIterator<Item = &'a str>,
) -> Result<(), CppCodegenError> {
    let mut by_cpp: HashMap<String, String> = HashMap::new();
    for source in source_names {
        let cpp = cpp_identifier(source);
        if let Some(previous) = by_cpp.get(&cpp) {
            if previous != source {
                return Err(CppCodegenError {
                    message: format!(
                        "C++ identifier collision in {scope}: Anthill identifiers \
                         '{previous}' and '{source}' both normalize to '{cpp}'"
                    ),
                });
            }
        } else {
            by_cpp.insert(cpp, source.to_string());
        }
    }
    Ok(())
}

/// Filename convention for a generated namespace's header: dotted
/// name with `.` → `_`. Mirrors what `anthill codegen cpp-project`
/// writes (`anthill.geometry` → `anthill_geometry.hpp`); both
/// producers and consumers of cross-namespace references must agree.
pub fn header_filename_for_namespace(namespace: &str) -> String {
    let stem = namespace
        .split('.')
        .map(cpp_identifier)
        .collect::<Vec<_>>()
        .join("_");
    format!("{stem}.hpp")
}

/// Register an `#include "<other_namespace>.hpp"` when emitting a
/// reference to an entity in another anthill namespace. The
/// project-layout writer drops these files alongside the current
/// namespace's header, so the include resolves at compile time. No-op
/// when the reference is intra-namespace or no surrounding namespace
/// context is set.
fn register_cross_namespace_include(ctx: &CodegenContext, entity_qn: &str) {
    let current_ns = ctx.emitting_namespace.borrow();
    let Some(current) = current_ns.as_deref() else {
        return;
    };
    let Some(entity_ns) = parent_namespace_of(entity_qn) else {
        return;
    };
    if entity_ns == current {
        return;
    }
    let header = header_filename_for_namespace(entity_ns);
    ctx.requested_includes
        .borrow_mut()
        .insert(format!("#include \"{header}\""));
}

/// If a namespace block is being emitted and `entity_qn` belongs to
/// a *different* anthill namespace, return the C++ fully-qualified
/// path (`::anthill::geometry::Vec3`) so the reference compiles
/// inside the current `namespace foo::bar { ... }` block. Same
/// namespace, or no namespace context (direct `emit_traits_struct`
/// callers), fall back to the short name.
fn qualify_cross_namespace(ctx: &CodegenContext, entity_qn: &str, short: &str) -> String {
    let short = cpp_identifier(short);
    let current_ns = ctx.emitting_namespace.borrow();
    let Some(current) = current_ns.as_deref() else {
        return short;
    };
    let entity_ns = parent_namespace_of(entity_qn);
    match entity_ns {
        Some(ens) if ens == current => short,
        Some(_) => format!("::{}", cpp_namespace(entity_qn)),
        None => short,
    }
}

/// Walk a list-shaped term and collect element TermIds. Recognises:
///   - `ListLiteral(a, b, ...)` — pre-typing parser output
///   - `cons(head: ..., tail: ...)` — typed list form using named args
///   - `cons(head, tail)` — typed list form using positional args
///   - `nil` — list terminator
///
/// Anything else returns whatever has been collected so far.
fn walk_list(kb: &KnowledgeBase, list: TermId) -> Vec<TermId> {
    let mut out = Vec::new();
    let mut current = list;
    loop {
        let term = kb.get_term(current);
        let Term::Fn {
            functor,
            pos_args,
            named_args,
        } = term
        else {
            return out;
        };
        match kb.local_name_of(*functor) {
            "ListLiteral" => {
                for arg in pos_args {
                    out.push(*arg);
                }
                return out;
            }
            "cons" => {
                // Try named args first (head:/tail:), fall back to positional.
                let head = named_args
                    .iter()
                    .find(|(s, _)| kb.local_name_of(*s) == "head")
                    .map(|(_, v)| *v)
                    .or_else(|| pos_args.first().copied());
                let tail = named_args
                    .iter()
                    .find(|(s, _)| kb.local_name_of(*s) == "tail")
                    .map(|(_, v)| *v)
                    .or_else(|| pos_args.get(1).copied());
                match (head, tail) {
                    (Some(h), Some(t)) => {
                        out.push(h);
                        current = t;
                    }
                    _ => return out,
                }
            }
            "nil" => return out,
            _ => return out,
        }
    }
}

