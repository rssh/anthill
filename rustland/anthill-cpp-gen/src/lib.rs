/// Emit a C++ struct for a single anthill entity, looked up by name.
/// The name may be either short ("Vec3") or fully qualified
/// ("test.geom.Vec3"); the C++ struct is named with the short
/// component, regardless of which form was passed in.
///
/// Convenience wrapper: builds a fresh `CodegenContext` from `kb`
/// (which scans `Implementation` facts). For repeated calls in one
/// codegen run, build the context once and use the by-symbol API.
pub fn emit_entity_struct(
    kb: &mut KnowledgeBase,
    entity_name: &str,
) -> Result<String, CppCodegenError> {
    let ctx = CodegenContext::new(kb)?;
    let sym = kb
        .try_resolve_symbol(entity_name)
        .ok_or_else(|| CppCodegenError {
            message: format!("entity '{entity_name}' not found in KB"),
        })?;
    emit_entity_struct_by_symbol(kb, &ctx, sym)
}

/// Emit a C++ struct for an entity given its functor Symbol.
/// The struct's C++ name is the short (final) component of the
/// resolved qualified name, so callers cannot accidentally inject
/// a dotted path as the struct identifier.
pub fn emit_entity_struct_by_symbol(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    functor: Symbol,
) -> Result<String, CppCodegenError> {
    let (template, fields_text) = entity_struct_members(kb, ctx, functor)?;
    // WI-931 — ONE SYMBOL, ONE STRUCT. An EPONYMOUS sort both carries fields and
    // owns operations (`sort Vec3 { entity Vec3(x: Float, …); operation vec_add(…)
    // = … }`), and §6.3 / WI-926 make that one symbol and one declaration — so it
    // must reach C++ as one type, whichever entry point asks. The rule lives HERE,
    // in the by-symbol emitter every path funnels through, rather than in the
    // namespace walk: the walk is only one of three callers, and the other two are
    // this crate's public by-name API, which would otherwise keep handing out half
    // a type under the type's own name (`emit_entity_struct` the fields,
    // `emit_traits_struct` the methods — two `struct Vec3` definitions, which is
    // the redefinition error this rule exists to prevent).
    //
    // A non-eponymous entity — including a sum constructor, which `emit_sum_in`
    // routes here — owns no operations, so `methods_text` is empty and the output
    // is byte-for-byte what it always was.
    let (_, methods_text) = traits_struct_members(kb, ctx, functor)?;
    let qualified = kb.qualified_name_of(functor).to_string();
    let name = cpp_identifier(short_name_of(&qualified));
    Ok(TEMPLATE_ENTITY_STRUCT
        .replace("{template}", &template)
        .replace("{name}", &name)
        .replace("{fields}", &format!("{fields_text}{methods_text}")))
}

/// The template prefix and rendered FIELD lines of an entity struct, without the
/// `struct … { … };` wrapper — so [`emit_entity_struct_by_symbol`] can put an
/// eponymous sort's operations inside the same braces.
fn entity_struct_members(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    functor: Symbol,
) -> Result<(String, String), CppCodegenError> {
    let qualified = kb.qualified_name_of(functor).to_string();

    // WI-760: own the field list. Lowering a field type now threads
    // `&mut KnowledgeBase` (it may resolve a realization rule), so the loop
    // below cannot hold a slice borrowed out of the KB across the call. Only
    // the symbol and the type's TermId are needed, so project to those rather
    // than cloning each `Value`.
    //
    // WI-342: field types are carrier-agnostic; codegen handles only ground
    // types — a value-in-type / denoted field is not C++-representable and does
    // not occur in codegen'd entities, so a non-`Term` carrier is dropped here.
    let fields: Vec<(Symbol, TermId)> = kb
        .entity_field_types(functor)
        .ok_or_else(|| CppCodegenError {
            message: format!("'{qualified}' has no registered fields — is it really an entity?"),
        })?
        .iter()
        .filter_map(|(sym, v)| match v {
            Value::Term { id, .. } => Some((*sym, *id)),
            _ => None,
        })
        .collect();
    let field_names: Vec<&str> = fields
        .iter()
        .map(|(sym, _)| kb.local_name_of(*sym))
        .collect();
    refuse_cpp_identifier_collisions(&format!("entity '{qualified}'"), field_names)?;

    // Templates: an entity declared inside `sort S { sort T = ?; … }`
    // takes its parent sort's type parameters. We emit the template
    // prefix and push a frame onto the lexical scope stack for the
    // duration of field-type lowering — outer params (if any) stay
    // visible underneath.
    //
    // WI-926 (§6.3): ask the KB for the parent, not `parent_qualified_name`'s
    // chop of the last dotted segment. An EPONYMOUS `sort Box { sort T = ?;
    // entity Box(value: ?T) }` is ONE symbol, so the chop walks past the sort to
    // the enclosing NAMESPACE and `?T` lowered as unbound. The declaration
    // carrying the params IS this symbol — an entity that is its own type, the
    // same reading `field_constructors_of_sort` gives from the other direction.
    // (`parent_qualified_name` itself must NOT change: its other callers ask the
    // different question "which scope declares this name", for which the chop is
    // right — an eponymous entity is still declared in its namespace.)
    //
    // WI-946: WI-926 spelled that as `strict(c).or_else(is_entity_constructor)`,
    // a per-site patch over the strict view. `sort_of_constructor` OWNS the
    // reflexive case, so the patch is gone; the two agree on every functor
    // reaching here, which all have a registered field schema (measured: 244/244
    // such functors in the loaded stdlib answer `Some`).
    let parent_sym = kb.sort_of_constructor(functor);
    let (template, type_params) = match parent_sym {
        Some(p) => template_prefix_for_sort(kb, p)?,
        None => (String::new(), std::collections::HashMap::new()),
    };
    let _guard = ctx.push_type_params(type_params);

    let mut fields_text = String::new();
    for (field_sym, type_tid) in &fields {
        let cpp_type = lower_type(kb, ctx, *type_tid)?;
        let field_name = cpp_identifier(kb.local_name_of(*field_sym));
        fields_text.push_str(
            &TEMPLATE_FIELD
                .replace("{ty}", &cpp_type)
                .replace("{name}", &field_name),
        );
    }

    Ok((template, fields_text))
}

// ── Traits-class (sort-with-operations) emission ────────────────────

/// Emit a C++ "traits-class" struct exposing every operation of a
/// sort as a `static` method declaration. Convenience wrapper that
/// builds a fresh `CodegenContext`.
///
/// Today emits declarations only — no method bodies. Body generation
/// (calling into the carrier with `self->method(args)`) needs a
/// snake-to-camel naming convention which is part of WI-088 / WI-089.
/// Until then, the user fills bodies manually or hand-writes the
/// implementation file.
/// One term-level constant (proposal 039 / WI-084), lowered for C++ emission
/// as a `constexpr`. WI-533.
struct ConstSig {
    /// Source spelling retained for many-to-one collision diagnostics.
    source_name: String,
    name: String,
    cpp_type: String,
    cpp_value: String,
}

/// Discover and lower the term-level constants declared directly in `scope`
/// (a sort's or a namespace's qualified name). Consts carry no scope-member
/// fact (the WI-084 deferral), so they are absent from the fact index and
/// found instead by scanning `const_types_iter` and matching the parent
/// qualified name — mirroring how `operations_in_sort` filters operations by
/// `parent_qualified_name`. Sorted by qualified name for deterministic output.
/// A const whose declared type or value can't be lowered is a loud error, never
/// a silent drop (repo rule).
fn consts_in_scope(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    scope_qualified: &str,
) -> Result<Vec<ConstSig>, CppCodegenError> {
    let mut syms: Vec<Symbol> = kb
        .const_types_iter()
        .filter(|(sym, _)| parent_qualified_name(kb, *sym).as_deref() == Some(scope_qualified))
        .map(|(sym, _)| sym)
        .collect();
    syms.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));

    let mut out = Vec::with_capacity(syms.len());
    for sym in syms {
        let source_name = short_name_of(kb.qualified_name_of(sym)).to_string();
        let name = cpp_identifier(&source_name);
        let (cpp_type, cpp_value) = lower_one_const(kb, ctx, sym)?;
        out.push(ConstSig {
            source_name,
            name,
            cpp_type,
            cpp_value,
        });
    }
    Ok(out)
}

/// Lower a single const's declared type and value to C++. Shared by
/// `consts_in_scope` (struct/namespace members) and
/// `carrier_bound_const_companions` (WI-536 namespace companions).
fn lower_one_const(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sym: Symbol,
) -> Result<(String, String), CppCodegenError> {
    let qn = kb.qualified_name_of(sym).to_string();

    // Declared type: `const_type` is a `Value`; a simple sort type (the
    // common case — `Int64`, `Float`) lowers as a ground `Value::Term`.
    //
    // WI-760: this matches the KB borrow directly while the body path below
    // must `.cloned()` first. The difference is what each arm carries out: here
    // the only value used past the borrow is a `Copy` `TermId`, so the borrow
    // ends at `*tid`; there the arm hands a `&Rc<NodeOccurrence>` to a `&mut`
    // call, which would keep the KB borrowed across it.
    let cpp_type = match kb.const_type(sym) {
        Some(anthill_core::eval::value::Value::Term { id: tid, .. }) => {
            let t = lower_type(kb, ctx, *tid)?;
            // A `String` const cannot be `constexpr std::string` — std::string
            // is not a literal type before C++20. `std::string_view` is literal
            // and binds a string literal directly, so it works under C++17.
            if t == "std::string" {
                "std::string_view".to_string()
            } else {
                t
            }
        }
        Some(other) => {
            return Err(CppCodegenError {
                message: format!(
                    "const '{qn}': declared type is a non-ground value ({}) — \
                     value-in-type const types are not supported by cpp-gen yet",
                    other.type_name()
                ),
            });
        }
        None => {
            return Err(CppCodegenError {
                message: format!("const '{qn}': no declared type recorded in the KB"),
            });
        }
    };

    // Value: lower the anthill body when present; a bodyless host-supplied const
    // (WI-532) maps to its C++ expression from the `const_map` clause (WI-889 — the
    // Float IEEE specials, formerly a hand-written table).
    // WI-760: bind before matching — the scrutinee's borrow would otherwise
    // span the arms, and lowering the body needs `&mut` on the KB.
    let body_node = kb.const_body_node(sym).cloned();
    let cpp_value = match &body_node {
        Some(body) => lower_node(kb, ctx, body)?,
        None => ctx
            .host_consts
            .lookup(sym)
            .map(str::to_string)
            .ok_or_else(|| CppCodegenError {
                message: format!(
                    "const '{qn}': bodyless host-supplied const has no C++ value mapping. \
                 Name the host expression in a `const_map` clause of a `provides \
                 {} language cpp` block.",
                    parent_qualified_name(kb, sym).unwrap_or_else(|| "<carrier>".to_string())
                ),
            })?,
    };

    Ok((cpp_type, cpp_value))
}

/// WI-536: carrier-bound sorts are excluded from struct emission (their carrier
/// owns the type), so a const declared inside one has nowhere to live. Emit each
/// as a namespace-scope companion named `Sort_NAME` (non-shadowing) so a
/// reference can resolve to a named constant. Returns the companions for the
/// carrier-bound sorts declared one level under `namespace`, sorted by const
/// qualified name for determinism. `const_ref_cpp` produces the matching
/// reference form.
fn carrier_bound_const_companions(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    namespace: &str,
) -> Result<Vec<ConstSig>, CppCodegenError> {
    let prefix = format!("{namespace}.");
    let mut syms: Vec<Symbol> = kb
        .const_types_iter()
        .filter(|(sym, _)| {
            let Some(parent) = parent_qualified_name(kb, *sym) else {
                return false;
            };
            parent.starts_with(&prefix)
                && !parent[prefix.len()..].contains('.')
                && ctx.carriers.lookup(&parent).is_some()
                && matches!(
                    kb.try_resolve_symbol(&parent).and_then(|s| kb.kind_of(s)),
                    Some(SymbolKind::Sort)
                )
        })
        .map(|(sym, _)| sym)
        .collect();
    syms.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));

    let mut out = Vec::with_capacity(syms.len());
    for sym in syms {
        let source_name = companion_source_name(kb, sym);
        let name = cpp_identifier(&source_name);
        let (cpp_type, cpp_value) = lower_one_const(kb, ctx, sym)?;
        out.push(ConstSig {
            source_name,
            name,
            cpp_type,
            cpp_value,
        });
    }
    Ok(out)
}

/// The namespace-scope companion identifier for a carrier-bound sort's const:
/// `Sort_NAME`. Single source of truth shared by the declaration site
/// (`carrier_bound_const_companions`) and the reference site (`const_ref_cpp`),
/// so the two cannot drift out of sync.
fn companion_source_name(kb: &KnowledgeBase, const_sym: Symbol) -> String {
    let qn = kb.qualified_name_of(const_sym);
    let parent = parent_qualified_name(kb, const_sym);
    let sort_short = parent.as_deref().map(short_name_of).unwrap_or("");
    format!("{sort_short}_{}", short_name_of(qn))
}

fn companion_name(kb: &KnowledgeBase, const_sym: Symbol) -> String {
    cpp_identifier(&companion_source_name(kb, const_sym))
}

/// WI-536: C++ reference expression for a term-level const — a NAMED constant,
/// not the inlined value. A const in a carrier-bound sort uses the namespace
/// companion `Sort_NAME`; a const in an emitted (non-carrier) sort uses the
/// struct member `Sort::NAME`; a namespace-level const uses `NAME`. References
/// from another namespace are fully qualified and pull in the declaring
/// namespace's header.
fn const_ref_cpp(kb: &mut KnowledgeBase, ctx: &CodegenContext, sym: Symbol) -> String {
    let qn = kb.qualified_name_of(sym).to_string();
    let name = cpp_identifier(short_name_of(&qn));
    let Some(parent) = parent_qualified_name(kb, sym) else {
        return name;
    };
    let parent_is_sort = matches!(
        kb.try_resolve_symbol(&parent).and_then(|s| kb.kind_of(s)),
        Some(SymbolKind::Sort)
    );

    // (declaring namespace, identifier within that namespace)
    let (decl_ns, in_ns): (String, String) = if parent_is_sort {
        let sort_ns = parent_namespace_of(&parent).unwrap_or("").to_string();
        if ctx.carriers.lookup(&parent).is_some() {
            (sort_ns, companion_name(kb, sym)) // namespace companion
        } else {
            (
                sort_ns,
                format!("{}::{name}", cpp_identifier(short_name_of(&parent))),
            ) // emitted struct member
        }
    } else {
        // Namespace-level const: the parent qualified name IS the namespace.
        (parent, name)
    };

    let current = ctx.emitting_namespace.borrow().clone();
    match current {
        Some(cur) if cur == decl_ns => in_ns,
        _ => {
            if !decl_ns.is_empty() {
                let header = header_filename_for_namespace(&decl_ns);
                ctx.requested_includes
                    .borrow_mut()
                    .insert(format!("#include \"{header}\""));
                format!("::{}::{}", cpp_namespace(&decl_ns), in_ns)
            } else {
                format!("::{in_ns}")
            }
        }
    }
}

/// Order namespace-scope const-likes (WI-533 namespace consts + WI-536
/// carrier-bound companions) so a const whose lowered value references another
/// const in the same band is emitted AFTER it — a C++ `inline constexpr`
/// initializer must name only already-declared constants. Dependency is read
/// off the lowered value strings: const A depends on const B when B's emitted
/// identifier appears as a whole token in A's value. Ready nodes are taken in
/// the band's incoming (qualified-name) order for determinism. A dependency
/// cycle (a pair of consts referencing each other) cannot be a constexpr and is
/// a loud error. WI-536.
fn topo_sort_const_likes(band: Vec<ConstSig>) -> Result<Vec<ConstSig>, CppCodegenError> {
    let n = band.len();
    // deps[i] = indices j (j != i) whose emitted name appears in band[i]'s value.
    let deps: Vec<Vec<usize>> = (0..n)
        .map(|i| {
            (0..n)
                .filter(|&j| j != i && value_references_token(&band[i].cpp_value, &band[j].name))
                .collect()
        })
        .collect();

    let mut done = vec![false; n];
    let mut order: Vec<usize> = Vec::with_capacity(n);
    for _ in 0..n {
        // Smallest index whose dependencies are all already emitted.
        match (0..n).find(|&i| !done[i] && deps[i].iter().all(|&j| done[j])) {
            Some(i) => {
                done[i] = true;
                order.push(i);
            }
            None => {
                let cyclic: Vec<&str> = (0..n)
                    .filter(|&i| !done[i])
                    .map(|i| band[i].name.as_str())
                    .collect();
                return Err(CppCodegenError {
                    message: format!(
                        "const dependency cycle among {cyclic:?} — a cyclic constant cannot be \
                         emitted as a C++ constexpr"
                    ),
                });
            }
        }
    }

    let mut slots: Vec<Option<ConstSig>> = band.into_iter().map(Some).collect();
    Ok(order
        .into_iter()
        .map(|i| slots[i].take().expect("each index taken once"))
        .collect())
}

/// True if `name` occurs in `haystack` as a whole C++ identifier token — not as
/// a substring of a larger identifier (so `BROADCAST` does not match inside
/// `BROADCAST_CHANNEL`, and `BROADCAST_CHANNEL` does not match inside
/// `Emitter_BROADCAST_CHANNEL`).
fn value_references_token(haystack: &str, name: &str) -> bool {
    if name.is_empty() {
        return false;
    }
    let bytes = haystack.as_bytes();
    let is_ident = |b: u8| b.is_ascii_alphanumeric() || b == b'_';
    let mut from = 0;
    while let Some(pos) = haystack[from..].find(name) {
        let start = from + pos;
        let end = start + name.len();
        let before_ok = start == 0 || !is_ident(bytes[start - 1]);
        let after_ok = end == bytes.len() || !is_ident(bytes[end]);
        if before_ok && after_ok {
            return true;
        }
        from = start + 1;
    }
    false
}

pub fn emit_traits_struct(
    kb: &mut KnowledgeBase,
    sort_name: &str,
) -> Result<String, CppCodegenError> {
    let ctx = CodegenContext::new(kb)?;
    let sym = kb
        .try_resolve_symbol(sort_name)
        .ok_or_else(|| CppCodegenError {
            message: format!("sort '{sort_name}' not found in KB"),
        })?;
    emit_traits_struct_by_symbol(kb, &ctx, sym)
}

/// Emit a traits-class struct for a sort given its functor Symbol.
/// Uses the sort's short (final) qualified-name component as the C++
/// struct name. Returns an error if the sort has no operations in
/// its scope.
pub fn emit_traits_struct_by_symbol(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sort_sym: Symbol,
) -> Result<String, CppCodegenError> {
    let qualified = kb.qualified_name_of(sort_sym).to_string();
    let (template, methods_text) = traits_struct_members(kb, ctx, sort_sym)?;
    // Unchanged: asking for the traits class of something that declares no members
    // is a mistake, whether or not it has fields. Checked BEFORE the merge below so
    // a plain data entity keeps this error rather than quietly getting its own
    // struct back from an entry point that was asked for something else.
    if methods_text.is_empty() {
        return Err(CppCodegenError {
            message: format!(
                "sort '{qualified}' has no operations or constants — \
                 a traits struct would be empty"
            ),
        });
    }
    // WI-931 — ONE SYMBOL, ONE STRUCT, from this side too. An eponymous sort that
    // carries FIELDS *and* members is one type, and
    // [`emit_entity_struct_by_symbol`] emits the whole of it; answering here with a
    // methods-only `struct` of the same name would be the second definition of it.
    // Delegating rather than refusing keeps the two public by-name entry points
    // agreeing on what the type IS, which is the property §6.3 promises.
    if kb.entity_field_types(sort_sym).is_some() {
        return emit_entity_struct_by_symbol(kb, ctx, sort_sym);
    }
    let name = cpp_identifier(short_name_of(&qualified));
    Ok(TEMPLATE_TRAITS_STRUCT
        .replace("{template}", &template)
        .replace("{name}", &name)
        .replace("{methods}", &methods_text))
}

/// The template prefix and rendered CONSTANT + METHOD lines of a traits struct,
/// without the `struct … { … };` wrapper. EMPTY (rather than an error) when the
/// sort declares neither: [`emit_entity_struct_by_symbol`] asks this of every
/// entity to find an eponymous sort's operations, and "this entity owns no
/// operations" is its ordinary answer, not a failure. The caller that wants the
/// error — [`emit_traits_struct_by_symbol`], where an empty traits class IS the
/// mistake — raises it from the empty result.
fn traits_struct_members(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sort_sym: Symbol,
) -> Result<(String, String), CppCodegenError> {
    let qualified = kb.qualified_name_of(sort_sym).to_string();

    // Push the sort's type params onto the lexical scope stack for
    // the duration of operation signature lowering — `lower_type`
    // consults the stack to render `?T` references to the C++
    // template parameter name.
    let (template, type_params) = template_prefix_for_sort(kb, sort_sym)?;
    // The sort's chosen C++ param names seed each op's canonicaliser so a
    // per-operation type param can't collide with a class template param.
    let sort_param_cpp: std::collections::HashSet<String> =
        type_params.values().map(|b| b.cpp.clone()).collect();
    let _guard = ctx.push_type_params(type_params);

    let ops = operations_in_sort(kb, ctx, sort_sym, &sort_param_cpp)?;
    let consts = consts_in_scope(kb, ctx, &qualified)?;
    let mut member_names: Vec<&str> = ops.iter().map(|op| op.source_name.as_str()).collect();
    member_names.extend(consts.iter().map(|c| c.source_name.as_str()));
    if let Some(fields) = kb.entity_field_types(sort_sym) {
        member_names.extend(fields.iter().map(|(sym, _)| kb.local_name_of(*sym)));
    }
    refuse_cpp_identifier_collisions(&format!("sort '{qualified}'"), member_names)?;
    let mut methods_text = String::new();
    // Term-level constants (WI-533) first: they read as the class's named
    // sentinels and match source order where the const precedes the operations
    // (e.g. lf1 `Emitter::BROADCAST_CHANNEL`).
    for c in &consts {
        methods_text.push_str(&format!(
            "    static constexpr {} {} = {};\n",
            c.cpp_type, c.name, c.cpp_value
        ));
    }
    for op in &ops {
        let params_text = op
            .params
            .iter()
            .map(|p| format!("{} {}", p.cpp_type, p.name))
            .collect::<Vec<_>>()
            .join(", ");
        let rendered = match &op.body {
            Some(body) => TEMPLATE_STATIC_METHOD_BODY
                .replace("{ret}", &op.return_type_cpp)
                .replace("{name}", &op.name)
                .replace("{params}", &params_text)
                .replace("{body}", body),
            None => TEMPLATE_STATIC_METHOD_DECL
                .replace("{ret}", &op.return_type_cpp)
                .replace("{name}", &op.name)
                .replace("{params}", &params_text),
        };
        // WI-575+: a generic op (`map[A, B](…)`) prefixes its signature with a
        // member-template `template<typename A, typename B>` line.
        methods_text.push_str(&op.template_prefix);
        methods_text.push_str(&rendered);
    }

    Ok((template, methods_text))
}

/// One operation's signature, as needed for traits-class emission.
/// `body` is `Some` when we can synthesise a definition that calls
/// into the carrier; `None` otherwise (declaration-only).
struct OperationSig {
    /// Anthill spelling, retained for collision checks and diagnostics.
    source_name: String,
    name: String,
    params: Vec<ParamInfo>,
    return_type_cpp: String,
    body: Option<String>,
    /// WI-575+: the per-operation member-template prefix (`    template<typename
    /// A, typename B>\n`) for a generic op like `map[A, B](…)`. Empty for a
    /// monomorphic op. Rendered immediately before the `static` method line.
    template_prefix: String,
}

struct ParamInfo {
    /// Anthill spelling used by expression-body symbol lookup.
    source_name: String,
    name: String,
    cpp_type: String,
    /// The param's anthill type term, kept so body synthesis can look
    /// up a marshalled representation (WI-088) and `lower` the argument
    /// when the host API wants the foreign rep.
    type_term: TermId,
}

/// Whether an operation's return type is "body-emittable" — i.e.,
/// we can safely synthesise `return self->method(args);` without a
/// marshalling step.
///
/// True when the anthill return type is:
///   - a primitive (`Int`, `Float`, `Bool`, `String`, `Unit`)
///   - a carrier-bound sort (we know the C++ type matches the
///     method's return)
///   - a parameterized type whose base is body-emittable AND every
///     binding's value is body-emittable (e.g. `List[T = Float]`,
///     `Option[T = List[T = Bool]]`)
///
/// False for project-local entities (we don't know what the carrier
/// method returns — a Vec3-from-`const double *` shape needs WI-088
/// marshalling) and for anything else exotic.
fn is_body_emittable(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    type_term: TermId,
) -> Result<bool, CppCodegenError> {
    if let Some(sym) = extract_sort_ref_sym(kb, &TermIdView(type_term)) {
        let qualified = kb.qualified_name_of(sym).to_string();
        if ctx.carriers.lookup(&qualified).is_some() {
            return Ok(true);
        }
        let short = short_name_of(&qualified);
        return Ok(resolve_type_mapping(kb, ctx, &[short], None)?.is_some());
    }
    let Some((base_sym, binding_values)) = unpack_parameterized(kb, type_term) else {
        return Ok(false);
    };
    let base_qn = kb.qualified_name_of(base_sym).to_string();
    let base_short = short_name_of(&base_qn);
    let base_known = ctx.carriers.lookup(&base_qn).is_some()
        || resolve_type_mapping(kb, ctx, &[base_short], None)?.is_some();
    if !base_known {
        return Ok(false);
    }
    // Every binding value must be body-emittable. A fallible recursive check, so
    // a plain `.all()` won't do: short-circuit on the first non-emittable value,
    // and a bodied-rule refusal in a nested `resolve_type_mapping` propagates.
    for (_, v) in &binding_values {
        if !is_body_emittable(kb, ctx, *v)? {
            return Ok(false);
        }
    }
    Ok(true)
}

/// If `type_term` is a `parameterized(base: sort_ref(<sort>), bindings:
/// [TypeBinding(value: <type>) ...])` term, return the base sort
/// symbol and the list of binding-value term ids. Otherwise `None`.
/// Shared between `lower_parameterized` (which formats the C++ template
/// expression) and `is_body_emittable` (which decides whether a body
/// can be synthesised).
fn unpack_parameterized(
    kb: &KnowledgeBase,
    term: TermId,
) -> Option<(Symbol, Vec<(Symbol, TermId)>)> {
    // WI-361: read base + `(param, value)` bindings form-agnostically — deep
    // `parameterized(base: sort_ref(S), bindings)` or term-backed `Fn{S, named}`.
    // The param symbol is kept so `lower_parameterized` can order the template
    // args by the sort's DECLARATION order (the bindings are stored in canonical
    // symbol-interning order, NOT declaration order, post the WI-361 flip).
    let TypeExtractor::Parameterized { base, bindings } = extract_type(kb, &TermIdView(term))
    else {
        return None;
    };
    // cpp-gen operates on well-formed ground parameterized types: every binding is
    // a `TypeBinding(param, value)` whose value is a hash-consed `TermId`. (A
    // non-`Term` value maps to `None` → whole result `None`; a binding missing
    // `value` is skipped by `extract_type` — both unreachable for loader types.)
    let values: Option<Vec<(Symbol, TermId)>> = bindings
        .iter()
        .map(|(p, v)| match v {
            Value::Term { id: t, .. } => Some((*p, *t)),
            _ => None,
        })
        .collect();
    Some((base, values?))
}

/// Convert a snake_case identifier to camelCase. Naive transform —
/// drops underscores and uppercases the next char. Does not preserve
/// acronyms (`get_gps` → `getGps`, not `getGPS`). Per-operation
/// overrides will arrive with WI-087 attributes; until then,
/// acronym-heavy ops emit the wrong C++ method name and need a
/// hand-edit. Documented in the cpp-forward-mapping spec.
fn snake_to_camel(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    let mut upper_next = false;
    for c in snake.chars() {
        if c == '_' {
            upper_next = true;
        } else if upper_next {
            out.extend(c.to_uppercase());
            upper_next = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// Look up the marshalled representation (WI-088) for an anthill type term at a
/// carrier-dispatch boundary, if one is registered. Resolves the term to its
/// sort symbol and runs the keyed `TypeMapping` query (WI-089(a)) under the
/// active binding key — so the binding's marshalling overlay (`Vec3 -> const
/// double *`) is selected here, while declared-signature lowering (with no
/// binding key active) never sees it. A hit that carries no adapter (`lift` and
/// `lower` both absent) is a plain rename, not a marshalled rep, so it returns
/// `None`: the value passes through bare.
fn marshal_for_type(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    type_term: TermId,
    binding: Option<&str>,
) -> Result<Option<Marshal>, CppCodegenError> {
    let sym =
        extract_sort_ref_sym(kb, &TermIdView(type_term)).or_else(|| match kb.get_term(type_term) {
            Term::Ref(s) | Term::Ident(s) => Some(*s),
            _ => None,
        });
    let Some(sym) = sym else { return Ok(None) };
    let qualified = kb.qualified_name_of(sym).to_string();
    let short = short_name_of(&qualified);
    let Some(hit) = resolve_type_mapping(kb, ctx, &[&qualified, short], binding)? else {
        return Ok(None);
    };
    if hit.lift.is_none() && hit.lower.is_none() {
        return Ok(None);
    }
    Ok(Some(Marshal {
        lift: hit.lift,
        lower: hit.lower,
    }))
}

/// WI-891: the body cpp-gen emits for an operation it cannot lower yet (a
/// CAPABILITY GAP — see [`CodegenContext::capability_gap`]). A build-breaking
/// `static_assert` carrying the codegen-time `message`, so the diagnosed gap FAILS
/// the C++ build at the exact method rather than degrading to `return {};`, which
/// compiled and answered a zero-initialized value. The rest of the header still
/// emits, since this is a returned body, not a codegen abort.
///
/// With a first-order template parameter in scope (`innermost_type_param`), the
/// method is a template member and the assert is keyed on that parameter through
/// `anthill::runtime::dependent_false_v` (pulling in the runtime header): being a
/// dependent expression it fires with a required diagnostic exactly when the member
/// is instantiated, and never eagerly — where a bare `static_assert(false, …)` would
/// be ill-formed-no-diagnostic-required before C++23. Otherwise — a non-template
/// method, or the rare template member whose only params are higher-kinded (not
/// usable as a `dependent_false_v<…>` type) — it uses `static_assert(false, …)`,
/// which still carries the message (a compiler may diagnose it eagerly there, losing
/// the per-method locality but never the diagnosis).
fn unlowerable_body(ctx: &CodegenContext, message: &str) -> String {
    let msg = escape_cpp_str(message);
    match ctx.innermost_type_param() {
        Some(param) => {
            // The emitted `::anthill::runtime::dependent_false_v` would ALSO be caught
            // by the `anthill::runtime::` IncludeMapping probe (WI-890) when cpp_std is
            // loaded, but this insert stays: the degrade must work in a KB that supplies
            // its own bindings WITHOUT the cpp profile (no probe fact), so it is the
            // load-independent floor. `Includes::render` dedups the overlap by directive.
            ctx.requested_includes
                .borrow_mut()
                .insert("#include \"anthill_runtime.hpp\"".to_string());
            format!("static_assert(::anthill::runtime::dependent_false_v<{param}>, \"{msg}\");")
        }
        None => format!("static_assert(false, \"{msg}\");"),
    }
}

/// Synthesise a method body for an operation. Lookup order:
///   1. **OperationImpl** (anthill expression body) — lower the body
///      via `lower_expr` and wrap with `return`. Highest precedence:
///      an operation with an explicit body MUST use that body.
///   2. **Carrier dispatch with marshalling** (WI-088) — `self->method(args)`,
///      with each argument `lower`ed and the result `lift`ed when its
///      anthill type has a marshalled representation. The host method's
///      foreign signature is derived by mapping the operation's anthill
///      types through the binding-keyed `TypeMapping` query (`marshal_for_type`,
///      WI-089(a)); `lift`/`lower` adapters bridge the boundary
///      (`return Vec3::from_array(self->getValues());`).
///   3. **None** — fall back to a declaration-only signature.
fn synthesise_body_for(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    op_sym: Symbol,
    name: &str,
    params: &[ParamInfo],
    return_type: &str,
    return_term: TermId,
) -> Result<Option<String>, CppCodegenError> {
    // (1) Expression body via OperationImpl — sourced from
    // `kb.op_body_node` as a NodeOccurrence tree after WI-249.
    if let Some(body_node) = ctx.op_impls.lookup(op_sym) {
        // WI-891: clear before, read after — see `CodegenContext::capability_gap`
        // for why that ordering is what makes the flag exact.
        ctx.capability_gap.set(false);
        let frame = params
            .iter()
            .map(|param| (param.source_name.clone(), param.name.clone()))
            .collect();
        let _param_guard = ctx.push_value_bindings(frame);
        match lower_node(kb, ctx, &body_node) {
            Ok(expr) => {
                return Ok(Some(if return_type == "void" {
                    format!("{expr};")
                } else {
                    format!("return {expr};")
                }))
            }
            // WI-891: a CAPABILITY GAP (a lowering the profile does not implement yet)
            // degrades to a build-breaking `static_assert` for THIS method, keeping the
            // rest of the header. Every other error — a DeBruijn var reaching cpp-gen,
            // an unresolved dot, an unknown constructor, a broken host binding (WI-886)
            // — is a program- or invariant-fault and is FATAL: it aborts codegen, so a
            // silently-wrong header is never written.
            Err(e) if ctx.capability_gap.take() => {
                return Ok(Some(unlowerable_body(ctx, &e.message)));
            }
            Err(e) => return Err(e),
        }
    }

    // Carrier-dispatch paths (2) and (3) require a `self` first param.
    let Some(self_param) = params.first() else {
        return Ok(None);
    };
    if self_param.name != "self" {
        return Ok(None);
    }
    let arrow = if self_param.cpp_type.contains('*') {
        "->"
    } else {
        "."
    };
    let cpp_method = cpp_method_name(kb, name)?;

    // WI-089(a): the carrier we dispatch onto is the operation's parent sort;
    // its `Implementation.binding` (if any) names the marshalling overlay
    // family active across THIS boundary. Prepended to the active-key list so a
    // binding-keyed `TypeMapping` (webots `Vec3 -> const double *`) is selected
    // for the arguments and return below, while declared-signature lowering
    // (no binding key) leaves `Vec3` its generated struct.
    let binding = parent_qualified_name(kb, op_sym)
        .and_then(|qn| ctx.carriers.binding(&qn).map(str::to_string));
    let binding = binding.as_deref();

    // A non-self argument whose anthill type IS marshalled but declares no
    // `lower` adapter cannot be bridged into the host call — a capability gap
    // (WI-088), degraded via `unlowerable_body`. A type with no marshalled entry
    // at all is a normal value and passes through bare; only the "marshalled, but
    // no anthill->foreign adapter" case is unhandleable.
    for p in params.iter().skip(1) {
        if matches!(marshal_for_type(kb, ctx, p.type_term, binding)?, Some(m) if m.lower.is_none())
        {
            return Ok(Some(unlowerable_body(
                ctx,
                &format!(
                    "WI-088: parameter '{}' has a marshalled type with no `lower` adapter — \
                 add a `lower` to its TypeMapping fact so the anthill value converts to the \
                 host's foreign representation",
                    p.name
                ),
            )));
        }
    }

    // Marshal each non-self argument (WI-088): if its anthill type has a
    // `lower` adapter, the host API wants the foreign rep, so wrap the
    // argument before passing it (`Vec3 -> const double *`). After the
    // guard above, a `None` here means the type is not marshalled at all,
    // so the argument passes through bare. The `marshal_for_type` read is
    // fallible (a bodied TypeMapping refusal), so collect a `Result` rather
    // than mapping infallibly.
    let non_self_args = params
        .iter()
        .skip(1)
        .map(|p| -> Result<String, CppCodegenError> {
            Ok(
                match marshal_for_type(kb, ctx, p.type_term, binding)?.and_then(|m| m.lower) {
                    Some(lower) => format!("{lower}({})", p.name),
                    None => p.name.clone(),
                },
            )
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    let call = format!("self{arrow}{cpp_method}({non_self_args})");

    // (2) Return marshalling (WI-088): if the return type has a `lift`
    // adapter, the host method yields the foreign rep, so wrap the call
    // to lift it back to the anthill type (`const double * -> Vec3`).
    // Takes precedence over plain dispatch — the lift applies even when
    // the return would otherwise have been body-emittable.
    if let Some(lift) = marshal_for_type(kb, ctx, return_term, binding)?.and_then(|m| m.lift) {
        if return_type == "void" {
            // Nothing to lift from a void return — a `lift` here is a spec error,
            // degraded via `unlowerable_body` (WI-891) rather than emitting
            // `{call};`, which compiled and silently discarded the declared lift.
            return Ok(Some(unlowerable_body(
                ctx,
                &format!(
                    "WI-088: `lift` adapter '{lift}' declared for the return type of \
                 void-returning operation '{name}' — a lift converts a returned value; \
                 drop the lift or give the operation a non-void return"
                ),
            )));
        }
        return Ok(Some(format!("return {lift}({call});")));
    }

    // (3) Plain carrier dispatch (no return marshalling).
    if !is_body_emittable(kb, ctx, return_term)? {
        return Ok(None);
    }
    Ok(Some(if return_type == "void" {
        format!("{call};")
    } else {
        format!("return {call};")
    }))
}

/// Walk the KB's `OperationInfo` facts and return all that belong to
/// `sort_sym`'s scope. Each entry's params and return type are lowered
/// via the carrier-aware `lower_type`. `sort_param_cpp` is the enclosing
/// sort's chosen C++ template-param names — it seeds each generic op's
/// canonicaliser so a per-operation type param never collides with a class
/// template param.
fn operations_in_sort(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sort_sym: Symbol,
    sort_param_cpp: &std::collections::HashSet<String>,
) -> Result<Vec<OperationSig>, CppCodegenError> {
    let op_info_sym = match kb.try_resolve_symbol("anthill.reflect.OperationInfo") {
        Some(s) => s,
        None => return Ok(Vec::new()),
    };
    let qualified = kb.qualified_name_of(sort_sym).to_string();

    // WI-771: read OperationInfo FACTS through the values-first accessor
    // (WI-773/057), refusing a bodied OperationInfo rule loudly. The rows are
    // owned Values, so the immutable read releases before the `&mut kb` lowering
    // calls below (`lower_type`, `template_param_decls`) run.
    let op_info_rows = kb.read_facts(op_info_sym, &[], BodiedRulePolicy::Refuse)?;
    let mut out = Vec::new();
    for row in &op_info_rows {
        // WI-348: the OperationInfo head may be a *value fact* (Node-carrying)
        // for an op with a `denoted` effect (`Modify[c]`), so it can't be read
        // as a term. Match the fact to its op symbol carrier-agnostically, then
        // read its fields through the `op_info` API rather than walking the head.
        let op_sym = match anthill_core::kb::op_info::head_name_ref(kb, row) {
            Some(s) => s,
            None => continue,
        };
        // The operation's parent sort is the prefix of its qualified
        // name (test.simple.Greeter.count → test.simple.Greeter).
        // We don't use SymbolTable::scope_of because that helper finds
        // a *sibling* symbol in the same scope, not the parent.
        if parent_qualified_name(kb, op_sym) != Some(qualified.to_string()) {
            continue;
        }

        let name = kb.local_name_of(op_sym).to_string();
        let rec =
            anthill_core::kb::op_info::lookup_operation_info(kb, op_sym).ok_or_else(|| {
                CppCodegenError {
                    message: format!("operation '{name}' missing OperationInfo"),
                }
            })?;

        // WI-575+: a generic operation (`map[A, B, EffP](…)`) carries its own
        // type params — read straight from the OperationInfo record (the
        // dedicated accessor) as declaration-ordered bare names, not re-derived.
        // Push them as a member-template frame for the duration of THIS op's
        // signature lowering (popped when `_op_guard` drops at the loop's end)
        // so references to them in the param / return types resolve. The
        // `template<…>` prefix is built AFTER lowering (below, via
        // `member_template_prefix`) so a param that lowers to nothing — an
        // effect-only `EffP`, since C++ erases the effect row — is dropped
        // rather than emitted as a dead template parameter. A monomorphic op
        // pushes nothing.
        let op_type_params: Vec<String> = rec
            .type_params
            .iter()
            .map(|(sym, _)| kb.local_name_of(*sym).to_string())
            .collect();
        let mut op_param_decls: Vec<(String, String)> = Vec::new();
        let mut _op_guard = None;
        if !op_type_params.is_empty() {
            let mut op_taken = sort_param_cpp.clone();
            let (decls, frame) = template_param_decls(kb, op_sym, &op_type_params, &mut op_taken)?;
            // (cpp_name, decl) pairs in declaration order, captured before the
            // frame is moved into the type-param stack.
            op_param_decls = op_type_params
                .iter()
                .map(|src| frame[src].cpp.clone())
                .zip(decls)
                .collect();
            _op_guard = Some(ctx.push_type_params(frame));
        }

        // WI-341: the return type is carrier-agnostic; a denoted-bearing
        // (`Value::Node`) return — an op returning a `Modify`-carrying callback —
        // is unsupported by C++ codegen (never materialized).
        let return_term = match &rec.return_type {
            anthill_core::eval::Value::Term { id: t, .. } => *t,
            _ => {
                return Err(CppCodegenError {
                    message: format!(
                        "operation '{name}' has a denoted-bearing return type \
                         unsupported by C++ codegen"
                    ),
                })
            }
        };
        let return_type_cpp = lower_type(kb, ctx, return_term)?;

        let mut params = Vec::new();
        for (p_name_sym, p_type) in &rec.params {
            // WI-341 Stage A: param types are carrier-agnostic. A ground type
            // lowers as before; a denoted-bearing (`Value::Node`) callback-arrow
            // param is not supported by C++ codegen (and is never materialized).
            let p_term = match p_type {
                anthill_core::eval::Value::Term { id: t, .. } => *t,
                _ => {
                    return Err(CppCodegenError {
                        message: format!(
                            "operation '{name}' parameter '{}' has a denoted-bearing \
                             type unsupported by C++ codegen",
                            kb.local_name_of(*p_name_sym)
                        ),
                    })
                }
            };
            let cpp_type = lower_type(kb, ctx, p_term)?;
            let source_name = kb.local_name_of(*p_name_sym).to_string();
            params.push(ParamInfo {
                name: cpp_identifier(&source_name),
                source_name,
                cpp_type,
                type_term: p_term,
            });
        }
        refuse_cpp_identifier_collisions(
            &format!("parameters of operation '{name}'"),
            params.iter().map(|param| param.source_name.as_str()),
        )?;

        // WI-576 CAPABILITY GATE: the operation's residual required effect row
        // must be a SUBSET of the target profile's supported-effect set. That
        // set is exactly the effects `realizes_effect` resolves — the keys of
        // the profile's effect_map, whichever representation carries it. An
        // effect with no realization here is UNREALIZABLE on this target, so it
        // fails LOUDLY instead of being folded away as "does not wrap".
        //
        // The row read here is the operation's DECLARED one, and that IS the
        // residual: handler discharge (WI-329) narrows a CALL's row inside a
        // body, and the op-boundary check then requires the declaration to
        // cover what survives — so an operation that handles `Error` internally
        // legitimately declares a row without it and the gate sees the narrower
        // set. Nothing in this loop changes for it.
        //
        // Resolving each effect ALSO drives return-type wrapping: an effect
        // wraps iff the profile realizes it as `ResultWrap` (WI-089(b) made
        // that decision fact-driven, replacing a hardcoded "Error" string
        // match). The cpp meaning of `ResultWrap` — `tl::expected<R,
        // std::string>` plus its include — stays here, exactly as a
        // `TypeMapping` host_type's template wrapping does.
        let mut wraps_result = false;
        for eff in &rec.effects {
            let kind = match classify_effect_label(kb, eff, &rec.type_params) {
                EffectLabel::Kind(k) => k,
                // Effect-polymorphic: nothing concrete to check here.
                EffectLabel::RowParam => continue,
                EffectLabel::Unreadable => {
                    return Err(CppCodegenError {
                        message: format!(
                            "operation '{name}' declares an effect whose kind C++ codegen \
                             cannot read (carrier {}), so {} cannot check it against its \
                             supported effects",
                            eff.type_name(),
                            cpp_profile_label(ctx)
                        ),
                    })
                }
            };
            let Some(receiver) = cpp_effect_receiver(kb, ctx, &kind) else {
                // Render the supported-effect set BEFORE building the error (WI-774:
                // it now resolves, so it is fallible — a truncated/failed candidate
                // search is a loud refusal here, never a panic mid-diagnostic).
                let supported = describe_supported_effects(kb, ctx)?;
                return Err(CppCodegenError {
                    message: format!(
                        "operation '{name}' requires effect '{kind}', which {} cannot \
                         realize — no EffectMapping declares it. Supported effects: {supported}",
                        cpp_profile_label(ctx),
                    ),
                });
            };
            wraps_result |= receiver == "ResultWrap";
        }
        let return_type_cpp = if wraps_result {
            ctx.requested_includes
                .borrow_mut()
                .insert("#include <tl/expected.hpp>".to_string());
            format!("tl::expected<{return_type_cpp}, std::string>")
        } else {
            return_type_cpp
        };
        let body = synthesise_body_for(
            kb,
            ctx,
            op_sym,
            &name,
            &params,
            &return_type_cpp,
            return_term,
        )?;
        let template_prefix =
            member_template_prefix(&op_param_decls, &params, &return_type_cpp, &body);
        out.push(OperationSig {
            name: cpp_identifier(&name),
            source_name: name,
            params,
            return_type_cpp,
            body,
            template_prefix,
        });
    }

    refuse_cpp_identifier_collisions(
        &format!("operations of sort '{qualified}'"),
        out.iter().map(|op| op.source_name.as_str()),
    )?;
    out.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(out)
}

// ── Namespace header emission ────────────────────────────────────────

/// Emit a complete C++ header file for every entity declared directly
/// under the given anthill namespace. Output includes `#pragma once`,
/// the minimum set of standard-library includes implied by emitted
/// types, and a `namespace foo::bar { ... }` wrapper.
///
/// Anthill `foo.bar.Baz` becomes C++ `foo::bar` (C++17 nested-namespace
/// syntax). Entities are emitted in qualified-name order for
/// determinism.
///
/// Returns an error if no entities are found under the namespace
/// (catches typos / wrong namespace strings before they produce empty
/// headers).
/// Short names of all traits classes (sorts with operations) declared
/// directly under `namespace`. Mirrors the third element of
/// `classify_namespace`'s tuple but lifts it to a public API so
/// callers driving project-layout scaffolding (one controller per
/// traits class) can iterate the targets without re-implementing the
/// classification.
pub fn traits_classes_in_namespace(
    kb: &mut KnowledgeBase,
    namespace: &str,
) -> Result<Vec<String>, CppCodegenError> {
    let ctx = CodegenContext::new(kb)?;
    let (_, _, traits) = classify_namespace(kb, &ctx, namespace)?;
    let source_names: Vec<&str> = traits
        .iter()
        .map(|sym| short_name_of(kb.qualified_name_of(*sym)))
        .collect();
    refuse_cpp_identifier_collisions(
        &format!("traits classes in namespace '{namespace}'"),
        source_names.iter().copied(),
    )?;
    Ok(source_names.into_iter().map(cpp_identifier).collect())
}

/// One `fact Generated(...)` declaration: an anthill sort the
/// project intends to lower into a host artifact. Read by project-
/// layout writers as the spec-driven source of truth for "what to
/// scaffold" — replacing the older heuristic that any traits class
/// in a namespace is a controller.
#[derive(Debug, Clone)]
pub struct GeneratedTarget {
    pub source: String,
    pub artifact: String,
    pub language: String,
    pub profile: Option<String>,
    pub kind: String,
    pub description: Option<String>,
}

/// Scan the KB for `Generated(...)` facts, read through the values-first
/// `read_facts` accessor (WI-771/773/057). Returns every fact regardless of
/// language so callers can filter (cpp-gen wants `language = "cpp"`; a Rust
/// scaffold would want `"rust"`). Empty when nothing is declared. A BODIED
/// `Generated` rule is refused loudly through `CppCodegenError` rather than
/// head-matched with its guard silently skipped — which would emit the artifact
/// / select the profile overlay unconditionally (WI-770 class; `generated_targets`
/// feeds CLI profile selection and the target-declaration check).
pub fn generated_targets(kb: &KnowledgeBase) -> Result<Vec<GeneratedTarget>, CppCodegenError> {
    let sym = match kb
        .try_resolve_symbol("anthill.realization.Generated")
        .or_else(|| kb.try_resolve_symbol("Generated"))
    {
        Some(s) => s,
        None => return Ok(Vec::new()),
    };
    let mut out = Vec::new();
    for row in kb.read_facts(sym, &[], BodiedRulePolicy::Refuse)? {
        let head = expect_term_head(kb, sym, row)?;
        let Some(source) = named_arg(kb, head, "source").and_then(|t| as_string(kb, t)) else {
            continue;
        };
        let Some(artifact) = named_arg(kb, head, "artifact").and_then(|t| as_string(kb, t)) else {
            continue;
        };
        let Some(language) = named_arg(kb, head, "language").and_then(|t| as_string(kb, t)) else {
            continue;
        };
        let Some(kind) = named_arg(kb, head, "kind").and_then(|t| as_string(kb, t)) else {
            continue;
        };
        let profile = named_optional_string(kb, head, "profile");
        let description = named_optional_string(kb, head, "description");
        out.push(GeneratedTarget {
            source,
            artifact,
            language,
            profile,
            kind,
            description,
        });
    }
    out.sort_by(|a, b| a.source.cmp(&b.source));
    Ok(out)
}

/// Unwrap an `Option<String>` term: `some("foo")` → `Some("foo")`,
/// `none` → `None`. Canonical layout per the prelude is
/// `entity some(value: T)`, so we read the `value` named arg first
/// and fall back to the first positional slot — the typing pass
/// can leave the named slot as an unbound Var while the actual
/// string lands positionally. We do *not* scan every named slot;
/// a future `some(value: ?, debug: "x")` shape would otherwise
/// silently return the wrong string.
fn extract_optional_string(kb: &KnowledgeBase, term: TermId) -> Option<String> {
    if let Some(s) = as_string(kb, term) {
        return Some(s);
    }
    let Term::Fn {
        functor,
        named_args,
        pos_args,
    } = kb.get_term(term)
    else {
        return None;
    };
    let qn = kb.qualified_name_of(*functor);
    if qn != "anthill.prelude.Option.some" && qn != "Option.some" {
        return None;
    }
    if let Some(v) = find_named(kb, named_args, "value").and_then(|t| as_string(kb, t)) {
        return Some(v);
    }
    pos_args.first().and_then(|t| as_string(kb, *t))
}

/// Static runtime support header for anthill-emitted C++.
///
/// Provides two things (see the header's own banner): SFINAE detection traits
/// for the prelude typeclasses we generate against — so generated code can
/// `static_assert` a host carrier satisfies the expected interface instead of
/// failing deep in a template instantiation — and hand-authored operation
/// REALIZATIONS (`anthill::runtime::str_*`, WI-890) for primitives whose lowering
/// is an algorithm no expression template can carry.
///
/// Stable, hand-authored, C++17. New entries land here when a new typeclass
/// becomes a codegen target, or a new host operation needs more than a `host_fn`
/// template.
pub const ANTHILL_RUNTIME_HEADER: &str = include_str!("anthill_runtime.hpp");

/// Return the runtime support header verbatim. Convenience wrapper —
/// callers that build a project layout can drop this beside the
/// generated namespace headers.
pub fn emit_runtime_header() -> &'static str {
    ANTHILL_RUNTIME_HEADER
}

/// WI-761: the "namespace declares nothing emittable" diagnostic. Raised by the
/// REQUIRED entry points (the primary `--namespace`, tests asserting a non-empty
/// header) when the namespace resolves to no entities / sums / traits / consts —
/// so a typo'd namespace still fails loudly. Distinct from a genuine lowering
/// failure: the optional-header path
/// (`emit_optional_namespace_header_with_profile`) reports this same empty
/// condition as `Ok(None)` instead and skips it quietly.
fn empty_namespace_error(namespace: &str) -> CppCodegenError {
    CppCodegenError {
        message: format!(
            "no entities, sum sorts, sort-with-operations, or constants to emit \
             directly under namespace '{namespace}' (either nothing is declared \
             there, or every candidate is carrier-bound by Implementation facts)"
        ),
    }
}

pub fn emit_namespace_header(
    kb: &mut KnowledgeBase,
    namespace: &str,
) -> Result<String, CppCodegenError> {
    // No active profile is `CodegenContext::new`, i.e. `with_profile(kb, None)`
    // — so this is the profile-aware required path with `None`.
    emit_namespace_header_with_profile(kb, namespace, None)
}

/// WI-089(a): like `emit_namespace_header`, but for a specific compilation
/// profile — so profile-keyed `TypeMapping` / `EffectMapping` overlays are
/// selected ahead of the language base. The CLI passes the profile from the
/// namespace's `Generated` / `Implementation` fact.
pub fn emit_namespace_header_with_profile(
    kb: &mut KnowledgeBase,
    namespace: &str,
    profile: Option<String>,
) -> Result<String, CppCodegenError> {
    // WI-761: a REQUIRED namespace — the optional path's `Ok(None)` (nothing
    // emittable) becomes the loud empty-namespace error, so a typo'd namespace
    // still fails rather than emitting an empty header.
    emit_optional_namespace_header_with_profile(kb, namespace, profile)?
        .ok_or_else(|| empty_namespace_error(namespace))
}

/// WI-761: emit an OPTIONAL namespace header — like
/// `emit_namespace_header_with_profile`, but a namespace that declares nothing
/// emittable yields `Ok(None)` rather than an error. Callers driving an optional
/// header (the CLI's `anthill.geometry` sidecar, absent unless a spec references
/// geometry) skip on `Ok(None)` yet still surface a genuine lowering failure —
/// e.g. an op requiring an effect the profile can't realize (WI-576) — as `Err`,
/// instead of the old `.ok()` / `if let Ok(..)` that discarded every error as if
/// it could only ever mean "namespace empty". The sole builder of the codegen
/// context among the header entry points; the required wrappers delegate here.
pub fn emit_optional_namespace_header_with_profile(
    kb: &mut KnowledgeBase,
    namespace: &str,
    profile: Option<String>,
) -> Result<Option<String>, CppCodegenError> {
    let ctx = CodegenContext::with_profile(kb, profile)?;
    emit_namespace_header_in(kb, &ctx, namespace)
}

/// Like `emit_namespace_header` but reuses an existing context.
/// Prefer this when emitting multiple namespaces in one run.
///
/// Emits flat entities (`entity Foo(...)` directly under the
/// namespace) and sum sorts (`enum S { entity C1(...) ; ... }` —
/// per-constructor structs followed by a `using S = std::variant<...>`
/// alias). Items are emitted in qualified-name order, so the layout
/// is deterministic across runs.
///
/// WI-761: returns `Ok(None)` when the namespace declares nothing
/// emittable (no entities / sums / traits / consts, or everything is
/// carrier-bound) — a benign "nothing here" outcome that the optional-
/// header path skips quietly. `Err` is reserved for a genuine lowering
/// failure. Required entry points recover the loud empty-namespace
/// error via `empty_namespace_error`.
pub fn emit_namespace_header_in(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    namespace: &str,
) -> Result<Option<String>, CppCodegenError> {
    // Track the currently-emitting namespace so `sort_to_cpp` can
    // qualify cross-namespace entity references (e.g. an
    // `anthill.geometry.Vec3` field inside an `anthill.examples.lf1`
    // entity must render as `::anthill::geometry::Vec3`). The guard
    // restores the previous value on every exit path.
    let _ns_guard = ctx.enter_namespace(namespace);
    let (entities, sums, traits) = classify_namespace(kb, ctx, namespace)?;
    // Namespace-level term-level constants (WI-533) declared directly under
    // this namespace (not inside a sort body — those emit as struct members),
    // plus the WI-536 `Sort_NAME` companions for consts inside carrier-bound
    // sorts (excluded from struct emission). One band, topologically ordered so
    // a const that references another is declared after it.
    let mut const_band = consts_in_scope(kb, ctx, namespace)?;
    const_band.extend(carrier_bound_const_companions(kb, ctx, namespace)?);
    let const_band = topo_sort_const_likes(const_band)?;

    if entities.is_empty() && sums.is_empty() && traits.is_empty() && const_band.is_empty() {
        // WI-761: benign "nothing to emit" → `Ok(None)`, kept DISTINCT from a
        // genuine lowering failure below (`Err`) so the two never collapse into
        // one error string the CLI has to guess between. See the fn doc for how
        // the required entry points recover the loud empty-namespace error.
        return Ok(None);
    }

    // All of these declarations land directly in the same C++ namespace: sum
    // constructors are lifted out of their Anthill sort beside its variant
    // alias, and carrier-bound constants become namespace companions. Refuse
    // `foo-bar` / `foo_bar` before rendering either declaration.
    let mut namespace_names: Vec<String> = entities
        .iter()
        .map(|sym| short_name_of(kb.qualified_name_of(*sym)).to_string())
        .collect();
    for (sort, constructors) in &sums {
        namespace_names.push(short_name_of(kb.qualified_name_of(*sort)).to_string());
        namespace_names.extend(
            constructors
                .iter()
                .map(|sym| short_name_of(kb.qualified_name_of(*sym)).to_string()),
        );
    }
    namespace_names.extend(
        traits
            .iter()
            .map(|sym| short_name_of(kb.qualified_name_of(*sym)).to_string()),
    );
    namespace_names.extend(const_band.iter().map(|c| c.source_name.clone()));
    refuse_cpp_identifier_collisions(
        &format!("namespace '{namespace}'"),
        namespace_names.iter().map(String::as_str),
    )?;

    // Emit data types (flat entities + sum sorts) first, then traits
    // classes — this guarantees traits-class method declarations
    // referencing entity / sum types compile without forward
    // declarations.
    //
    // Within the data band, items are topologically sorted by their
    // field-type dependencies: an entity that has a `Pose` field is
    // emitted after `Pose`. Cycles fall back to alphabetical order
    // (C++ resolves them with explicit forward declarations, which
    // we don't emit yet — cycles produce a non-compilable header
    // but at least a deterministic one).
    let mut data_items: HashMap<Symbol, Item> = HashMap::new();
    for sym in &entities {
        data_items.insert(*sym, Item::Flat(*sym));
    }
    for (sort_sym, ctors) in sums {
        data_items.insert(sort_sym, Item::Sum(sort_sym, ctors));
    }
    let data_order = topo_sort_data_items(kb, &data_items);

    // `classify_namespace` returns the three bands DISJOINT (WI-931), so an
    // eponymous sort is in `entities` only and the data band emits its fields and
    // its operations in one `struct`.
    let mut traits_band: Vec<Symbol> = traits;
    traits_band.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));

    let mut items = String::new();
    let mut needs = Includes::from_kb(kb)?;
    // Namespace-scope constants (incl. companions) first, so any later struct
    // or method body that references one sees its declaration (a const of a
    // primitive type carries no forward dependency on a same-namespace struct).
    for c in &const_band {
        let block = format!(
            "inline constexpr {} {} = {};\n",
            c.cpp_type, c.name, c.cpp_value
        );
        needs.scan(&block);
        items.push_str(&block);
    }
    if !const_band.is_empty() {
        items.push('\n');
    }
    for sym in data_order {
        let item = data_items
            .remove(&sym)
            .expect("topo result must be in data_items");
        let block = match item {
            Item::Flat(sym) => emit_entity_struct_by_symbol(kb, ctx, sym)?,
            Item::Sum(sort_sym, ctors) => emit_sum_in(kb, ctx, sort_sym, &ctors)?,
        };
        needs.scan(&block);
        items.push_str(&block);
        items.push('\n');
    }
    for sym in traits_band {
        let block = emit_traits_struct_by_symbol(kb, ctx, sym)?;
        needs.scan(&block);
        items.push_str(&block);
        items.push('\n');
    }
    // Includes that cpp-gen registered at run-time (e.g.
    // `<tl/expected.hpp>` for Error-effect ops) live on the context;
    // fold them in here.
    for inc in ctx.requested_includes.borrow().iter() {
        needs.add_directive(inc);
    }

    let ns_cpp = cpp_namespace(namespace);
    Ok(Some(
        TEMPLATE_HEADER
            .replace("{ns_anthill}", namespace)
            .replace("{ns_cpp}", &ns_cpp)
            .replace("{includes}", &needs.render())
            .replace("{items}", &items),
    ))
}

// ── Sum sort emission (std::variant) ─────────────────────────────────

/// Emit a sum sort as per-constructor structs followed by a variant
/// alias: `using SortName = std::variant<Ctor1, Ctor2>;`. Constructors
/// with fields produce structs with those fields; zero-field
/// constructors produce empty structs.
pub fn emit_sum(kb: &mut KnowledgeBase, sort_name: &str) -> Result<String, CppCodegenError> {
    let ctx = CodegenContext::new(kb)?;
    let sort_sym = kb
        .try_resolve_symbol(sort_name)
        .ok_or_else(|| CppCodegenError {
            message: format!("sort '{sort_name}' not found in KB"),
        })?;
    let ctors = constructors_of(kb, sort_sym);
    if ctors.is_empty() {
        return Err(CppCodegenError {
            message: format!(
                "sort '{sort_name}' has no constructor entities — \
                 not a sum sort"
            ),
        });
    }
    emit_sum_in(kb, &ctx, sort_sym, &ctors)
}

fn emit_sum_in(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    sort_sym: Symbol,
    ctors: &[Symbol],
) -> Result<String, CppCodegenError> {
    let sort_qualified = kb.qualified_name_of(sort_sym).to_string();
    let sort_short = short_name_of(&sort_qualified);
    let sort_cpp = cpp_identifier(sort_short);
    let mut declaration_names = vec![sort_short];
    declaration_names.extend(
        ctors
            .iter()
            .map(|ctor| short_name_of(kb.qualified_name_of(*ctor))),
    );
    refuse_cpp_identifier_collisions(&format!("sum sort '{sort_qualified}'"), declaration_names)?;

    // Generic-sort header: `template<typename T>` if the sum sort
    // declares any `sort T = ?` parameters. Each constructor that
    // mentions a parameter becomes a templated struct; the variant
    // alias is also templated. Constructors that don't reference any
    // parameter (e.g. nullary `None`) stay non-templated and appear
    // bare in the alias's argument list.
    //
    // Compute prefix + canonical-name mapping + param-name list once;
    // the per-ctor branch below reads them by reference to avoid
    // re-scanning `by_qualified_name` per constructor.
    let param_names = type_params_of(kb, sort_sym);
    let (template_prefix, mapping) = template_prefix_for_sort(kb, sort_sym)?;
    let cpp_args = if param_names.is_empty() {
        String::new()
    } else {
        param_names
            .iter()
            .map(|p| {
                mapping
                    .get(p)
                    .map(|b| b.cpp.clone())
                    .unwrap_or_else(|| p.clone())
            })
            .collect::<Vec<_>>()
            .join(", ")
    };

    let mut out = String::new();
    for ctor_sym in ctors {
        out.push_str(&emit_entity_struct_by_symbol(kb, ctx, *ctor_sym)?);
        out.push('\n');
    }

    let ctor_list = ctors
        .iter()
        .map(|c| {
            let short = short_name_of(kb.qualified_name_of(*c)).to_string();
            let cpp = cpp_identifier(&short);
            if !param_names.is_empty() && constructor_uses_params(kb, *c, &param_names) {
                format!("{cpp}<{cpp_args}>")
            } else {
                cpp
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(
        &TEMPLATE_VARIANT_ALIAS
            .replace("{template}", &template_prefix)
            .replace("{sort_name}", &sort_cpp)
            .replace("{ctor_list}", &ctor_list),
    );
    Ok(out)
}

/// True if any of the entity's field types references one of the
/// supplied type parameters (by source-level name). Drives the
/// `Ctor<T>` vs `Ctor` decision in generic sum-alias emission.
fn constructor_uses_params(kb: &KnowledgeBase, entity_sym: Symbol, param_names: &[String]) -> bool {
    let Some(fields) = kb.entity_field_types(entity_sym) else {
        return false;
    };
    for (_, type_term) in fields {
        // WI-342: ground field types only (denoted fields don't occur in codegen).
        if let Value::Term { id: t, .. } = type_term {
            if term_references_param(kb, *t, param_names) {
                return true;
            }
        }
    }
    false
}

/// Recursively scan a type term for references to any of the named
/// type parameters. Catches both bare `?T` (`Term::Var`) and nested
/// occurrences inside parameterized wrappers (`Vec[T = ?T]`).
fn term_references_param(kb: &KnowledgeBase, term: TermId, param_names: &[String]) -> bool {
    match kb.get_term(term) {
        Term::Var(v) => {
            let name_sym = match v {
                anthill_core::kb::term::Var::Global(vid) => vid.name(),
                _ => return false,
            };
            let name = kb.local_name_of(name_sym);
            param_names.iter().any(|p| p == name)
        }
        Term::Fn {
            pos_args,
            named_args,
            ..
        } => {
            pos_args
                .iter()
                .any(|a| term_references_param(kb, *a, param_names))
                || named_args
                    .iter()
                    .any(|(_, a)| term_references_param(kb, *a, param_names))
        }
        _ => false,
    }
}

/// One pass over the entity index, classifying each entity under a
/// namespace into either a "flat" entity (directly under the namespace)
/// or a sum-constructor (one level deeper, parent is a Sort). Also
/// surfaces sorts that have operations declared directly under the
/// namespace — those become traits classes in the emitted header.
/// Returns `(flat, sums, traits)` all sorted by qualified name for
/// determinism.
///
/// Carrier-bound items are excluded: when an `Implementation` /
/// `CarrierBinding` already maps the type to a host-side equivalent,
/// emitting a fresh struct would shadow it. Sums are preferred over
/// traits when a sort qualifies as both.
fn classify_namespace(
    kb: &mut KnowledgeBase,
    ctx: &CodegenContext,
    namespace: &str,
) -> Result<(Vec<Symbol>, Vec<(Symbol, Vec<Symbol>)>, Vec<Symbol>), CppCodegenError> {
    let prefix = format!("{namespace}.");
    let mut flat: Vec<Symbol> = Vec::new();
    let mut by_parent: HashMap<String, Vec<Symbol>> = HashMap::new();

    for sym in kb.entity_field_type_functors().copied() {
        let qn = kb.qualified_name_of(sym);
        if !qn.starts_with(&prefix) {
            continue;
        }
        let rest = &qn[prefix.len()..];
        match rest.find('.') {
            None => {
                if ctx.carriers.lookup(qn).is_none() {
                    flat.push(sym);
                }
            }
            Some(dot) if !rest[dot + 1..].contains('.') => {
                let parent_qn = &qn[..prefix.len() + dot];
                if ctx.carriers.lookup(parent_qn).is_none() {
                    by_parent
                        .entry(parent_qn.to_string())
                        .or_default()
                        .push(sym);
                }
            }
            _ => {}
        }
    }

    let mut sums: Vec<(Symbol, Vec<Symbol>)> = Vec::new();
    let mut sum_sort_qns: std::collections::HashSet<String> = std::collections::HashSet::new();
    for (parent_qn, mut ctors) in by_parent {
        let Some(sort_sym) = kb.try_resolve_symbol(&parent_qn) else {
            continue;
        };
        if !matches!(kb.kind_of(sort_sym), Some(SymbolKind::Sort)) {
            continue;
        }
        ctors.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));
        sum_sort_qns.insert(parent_qn);
        sums.push((sort_sym, ctors));
    }

    // Traits-class candidates: sorts that have at least one
    // OperationInfo whose parent is `<namespace>.<short>` (one level
    // deep), aren't carrier-bound, and aren't already a sum sort.
    let mut traits_qns: std::collections::HashSet<String> = std::collections::HashSet::new();
    if let Some(op_info_sym) = kb.try_resolve_symbol("anthill.reflect.OperationInfo") {
        // WI-771: read OperationInfo FACTS through the values-first accessor
        // (WI-773/057), refusing a bodied OperationInfo rule loudly.
        for row in kb.read_facts(op_info_sym, &[], BodiedRulePolicy::Refuse)? {
            // WI-348: carrier-agnostic — the head may be a value fact for an op
            // with a `denoted` effect; match it to its op symbol via `op_info`.
            let Some(op_sym) = anthill_core::kb::op_info::head_name_ref(kb, &row) else {
                continue;
            };
            let Some(parent_qn) = parent_qualified_name(kb, op_sym) else {
                continue;
            };
            if !parent_qn.starts_with(&prefix) {
                continue;
            }
            let rest = &parent_qn[prefix.len()..];
            if rest.contains('.') {
                continue;
            }
            if ctx.carriers.lookup(&parent_qn).is_some() {
                continue;
            }
            if sum_sort_qns.contains(&parent_qn) {
                continue;
            }
            traits_qns.insert(parent_qn);
        }
    }

    // WI-533: a sort whose only members are term-level consts has no
    // OperationInfo, so the loop above misses it and its consts would silently
    // vanish from the header. Surface const-bearing sorts the same way (one
    // level deep, not carrier-bound, not already a sum) so a const-only sort
    // emits as a struct of `static constexpr` members. The `kind == Sort`
    // filter below drops a const that is directly under the namespace
    // (`ns.X`, parent `ns`, already handled by the namespace-level scan) or in
    // a nested namespace (`ns.sub`, not a Sort). A sum sort that also carries a
    // const is left to its sum emission (consts there are a separate gap).
    for (const_sym, _) in kb.const_types_iter() {
        let Some(parent_qn) = parent_qualified_name(kb, const_sym) else {
            continue;
        };
        if !parent_qn.starts_with(&prefix) {
            continue;
        }
        if parent_qn[prefix.len()..].contains('.') {
            continue;
        }
        if ctx.carriers.lookup(&parent_qn).is_some() {
            continue;
        }
        if sum_sort_qns.contains(&parent_qn) {
            continue;
        }
        traits_qns.insert(parent_qn);
    }

    let mut traits: Vec<Symbol> = traits_qns
        .into_iter()
        .filter_map(|qn| kb.try_resolve_symbol(&qn))
        .filter(|s| matches!(kb.kind_of(*s), Some(SymbolKind::Sort)))
        // WI-931 — THE THREE BANDS ARE DISJOINT, and that is this function's
        // contract rather than each consumer's chore. An EPONYMOUS sort
        // (`sort Vec3 { entity Vec3(x: Float, …); operation vec_add(…) = … }`) is
        // found TWICE — the entity-field registry puts it in `flat`, an
        // `OperationInfo` under the same symbol puts it here — but §6.3 / WI-926
        // make it ONE symbol and one declaration, so it is ONE band's item. The
        // data band keeps it, because that is where its fields are and where
        // `emit_entity_struct_by_symbol` emits the whole type.
        //
        // Subtracting here rather than in the emitter is what makes the answer
        // uniform: the OTHER consumer is the public `traits_classes_in_namespace`,
        // which the CLI's `codegen cpp-project` uses to scaffold "one controller
        // per traits class". Left overlapping, it offered `Vec3` — a data type —
        // as a controller target (MEASURED).
        .filter(|s| !flat.contains(s))
        .collect();

    flat.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));
    sums.sort_by(|(a, _), (b, _)| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));
    traits.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));
    Ok((flat, sums, traits))
}

/// Topologically order the data band so an item's dependencies on
/// other in-band symbols come first. Out-of-band references (carrier
/// types, primitives, parameters) are ignored. Within a single tier
/// (no inter-dependency, or unbroken cycle), items are tied by
/// alphabetical qualified-name order for determinism.
///
/// Sum sorts depend on every constructor's field types — emitting a
/// sum requires its constructor structs to come first, but the sum
/// alias and constructor structs are always rendered together by
/// `emit_sum_in`, so we just need the *external* deps the sum
/// reaches into (anything in the data band that isn't a constructor
/// of this sum).
fn topo_sort_data_items(
    kb: &mut KnowledgeBase,
    items: &std::collections::HashMap<Symbol, Item>,
) -> Vec<Symbol> {
    use std::collections::{HashMap, HashSet};
    let in_band: HashSet<Symbol> = items.keys().copied().collect();
    let mut deps: HashMap<Symbol, HashSet<Symbol>> = HashMap::new();
    for (sym, item) in items.iter() {
        let mut item_deps: HashSet<Symbol> = HashSet::new();
        match item {
            Item::Flat(s) => collect_entity_deps(kb, *s, &in_band, &mut item_deps),
            Item::Sum(_, ctors) => {
                for ctor_sym in ctors {
                    collect_entity_deps(kb, *ctor_sym, &in_band, &mut item_deps);
                }
                for c in ctors {
                    item_deps.remove(c);
                }
            }
        }
        item_deps.remove(sym);
        deps.insert(*sym, item_deps);
    }
    let mut remaining: Vec<Symbol> = items.keys().copied().collect();
    remaining.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));

    let mut emitted: HashSet<Symbol> = HashSet::new();
    let mut order: Vec<Symbol> = Vec::with_capacity(remaining.len());
    while !remaining.is_empty() {
        let mut progress = false;
        let mut next_remaining = Vec::with_capacity(remaining.len());
        for sym in remaining {
            let ready = deps[&sym].iter().all(|d| emitted.contains(d));
            if ready {
                order.push(sym);
                emitted.insert(sym);
                progress = true;
            } else {
                next_remaining.push(sym);
            }
        }
        if !progress {
            order.extend(next_remaining);
            break;
        }
        remaining = next_remaining;
    }
    order
}

/// One item in the data band of a namespace header. Traits classes
/// are emitted separately, after the data band.
enum Item {
    Flat(Symbol),
    Sum(Symbol, Vec<Symbol>),
}

/// Walk `entity_sym`'s field types, recording every reference to
/// another symbol in `in_band`. Out-of-band symbols (primitives,
/// carrier-bound types, type parameters) are ignored.
fn collect_entity_deps(
    kb: &KnowledgeBase,
    entity_sym: Symbol,
    in_band: &std::collections::HashSet<Symbol>,
    out: &mut std::collections::HashSet<Symbol>,
) {
    let Some(fields) = kb.entity_field_types(entity_sym) else {
        return;
    };
    for (_, type_term) in fields {
        // WI-342: ground field types only (denoted fields don't occur in codegen).
        if let Value::Term { id: t, .. } = type_term {
            collect_type_term_refs(kb, *t, in_band, out);
        }
    }
}

fn collect_type_term_refs(
    kb: &KnowledgeBase,
    term: TermId,
    in_band: &std::collections::HashSet<Symbol>,
    out: &mut std::collections::HashSet<Symbol>,
) {
    if let Some(sym) = extract_sort_ref_sym(kb, &TermIdView(term)) {
        if in_band.contains(&sym) {
            out.insert(sym);
        }
        return;
    }
    match kb.get_term(term) {
        Term::Ref(s) | Term::Ident(s) => {
            if in_band.contains(s) {
                out.insert(*s);
            }
        }
        Term::Fn {
            pos_args,
            named_args,
            ..
        } => {
            for a in pos_args {
                collect_type_term_refs(kb, *a, in_band, out);
            }
            for (_, a) in named_args {
                collect_type_term_refs(kb, *a, in_band, out);
            }
        }
        _ => {}
    }
}

/// Constructors of a sort: entities whose qualified name has the
/// sort's qualified name as a prefix (one component deeper). Sorted.
/// Used by the public `emit_sum` wrapper when called outside the
/// namespace-walk path.
fn constructors_of(kb: &mut KnowledgeBase, sort_sym: Symbol) -> Vec<Symbol> {
    let sort_qn = kb.qualified_name_of(sort_sym).to_string();
    let prefix = format!("{sort_qn}.");
    let mut out: Vec<Symbol> = kb
        .entity_field_type_functors()
        .copied()
        .filter(|sym| {
            let qn = kb.qualified_name_of(*sym);
            qn.starts_with(&prefix) && !qn[prefix.len()..].contains('.')
        })
        .collect();
    out.sort_by(|a, b| kb.qualified_name_of(*a).cmp(kb.qualified_name_of(*b)));
    out
}

/// Set of standard-library headers required by emitted types. After rendering a
/// namespace header's body, cpp-gen scans that text for host type spellings and,
/// on a hit, pulls in the matching `#include` — the (spelling, header) table is
/// the cpp `IncludeMapping` facts (WI-089), built once via `query_include_mappings`
/// instead of a hardcoded array.
///
/// Every emitted/referenced header is required self-contained (the
/// `IncludeMapping` invariant), so include order is never load-bearing: the
/// probe list is sorted for deterministic output, and the stdlib group renders
/// before `extras` (the non-stdlib directives — `<tl/expected.hpp>`,
/// cross-namespace, vendor headers) purely for readability.
struct Includes {
    /// (host type spelling, include directive), sorted by directive for a
    /// deterministic preamble. The cpp `IncludeMapping` stdlib group.
    probes: Vec<(String, String)>,
    /// Indices into `probes` whose spelling was found in emitted text.
    needed: std::collections::BTreeSet<usize>,
    /// Additional `#include …` directives registered at codegen time (e.g.
    /// `<tl/expected.hpp>` for Error-effect ops). `BTreeSet` for determinism.
    extras: std::collections::BTreeSet<String>,
}

impl Includes {
    /// Build from the cpp `IncludeMapping` facts, sorted by include directive.
    /// WI-833: a BODIED `IncludeMapping` rule is now RESOLVED (its guard honored)
    /// via `read_facts_resolved`, not refused — the same `Resolve` migration the
    /// other realization readers carry; duplicate resolved pairs are deduped
    /// (`query_include_mappings`).
    fn from_kb(kb: &mut KnowledgeBase) -> Result<Self, CppCodegenError> {
        let mut probes = query_include_mappings(kb, "cpp")?;
        probes.sort_by(|a, b| a.1.cmp(&b.1));
        Ok(Includes {
            probes,
            needed: std::collections::BTreeSet::new(),
            extras: std::collections::BTreeSet::new(),
        })
    }

    fn scan(&mut self, text: &str) {
        for (i, (probe, _)) in self.probes.iter().enumerate() {
            if text.contains(probe) {
                self.needed.insert(i);
            }
        }
    }

    /// Add a literal `#include …` directive, e.g. when expression-body
    /// lowering introduced a dependency on a non-stdlib header.
    fn add_directive(&mut self, directive: &str) {
        self.extras.insert(directive.to_string());
    }

    /// Render the include block with a leading newline (so the slot in
    /// the header template doesn't introduce a blank line when empty).
    ///
    /// DEDUPED BY DIRECTIVE, across both groups. The probe table is keyed by host
    /// SPELLING and several spellings legitimately share one header — WI-886 added
    /// twenty-three `<cmath>` probes at a stroke, and a body using `sqrt`, `fmax` and
    /// `isnan` emitted `#include <cmath>` three times. Harmless to the compiler,
    /// which is why it went unnoticed while `std::numeric_limits` was the only
    /// possible collision; still noise in a generated artifact people read.
    fn render(&self) -> String {
        // `needed` holds indexes into `probes`, which is sorted by directive, so
        // ascending index order is directive order; `extras` follows, as its own group.
        let directives = self
            .needed
            .iter()
            .map(|&i| self.probes[i].1.as_str())
            .chain(self.extras.iter().map(String::as_str));
        let mut out = String::new();
        let mut seen: std::collections::BTreeSet<&str> = std::collections::BTreeSet::new();
        for d in directives {
            if seen.insert(d) {
                out.push('\n');
                out.push_str(d);
            }
        }
        out.push('\n');
        out
    }
}

